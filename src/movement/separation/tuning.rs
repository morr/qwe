//! Ручки расталкивания: тумблер пользователя ([`SeparationStyle`]), числовые
//! значения замера ([`SeparationLab`]) и то, чего в игре нет
//! ([`SeparationExperiments`]). Ни одного правила механизма здесь нет — сам
//! прогон живёт в [`super`], математика пары в [`super::pairs`], решатель в
//! [`super::solver`].

use bevy::prelude::*;
use bevy::settings::{ReflectSettingsGroup, SettingsGroup};

// Из `settings.rs` под ручки приходит одна константа: на `SEPARATION_RATE`
// завязано равновесие «ходьба против расталкивания», которым объясняют себя
// слоты назначения (`movement/destination.rs`), — читатель у неё не один.
// Остальные дефолты лежат здесь: у них владелец ровно один, этот механизм
// (`CLAUDE.md`, «Code Conventions»).
use crate::settings::SEPARATION_RATE;

/// Насколько сильно встречные обходят друг друга боком, в долях продольной
/// коррекции той же пары (см. `separation::sidestep`). 0 — прежнее поведение,
/// когда лобовая пара умеет только пятиться и потому «слипается»; 1.0 — на
/// строго лобовой встрече толчок уходит под 45°, то есть пешка столько же
/// шагает вбок, сколько назад. Больше единицы — обход становится заметнее
/// расталкивания и выглядит как рывок в сторону.
///
/// Величина — только половина вопроса; вторая половина в том, КОМУ добавка
/// достаётся, и там ручки нет, потому что обе поломки не про силу, а про
/// симметрию: обходят оба — пара вращается вместо того, чтобы разъехаться
/// (`separation::yields`); обходит вся давка сразу — вращается затор целиком
/// (гейт «пара одна» в `separation::resolve_pushes`).
pub const SEPARATION_SIDESTEP: f32 = 1.0;
/// Какая доля толчка ВДОЛЬ курса пешки доживает до применения
/// (`separation::damp_along_heading`). **1.0 — ничего не давим**, и это не
/// «пока не дошли руки», а результат замера.
///
/// Давить продольную часть напрашивается: именно она отбрасывает догоняющего
/// назад по его же пути, и на экране это читается как разворот. Но она же —
/// единственное, чем сходящаяся толпа может РАЗДАТЬСЯ: наружу из давки это
/// всегда «назад по курсу». Замер на сценарии «воронка» (200 пешек в одну
/// точку, перекрывшихся пар / худшее перекрытие):
///
/// | backstep | пар | худшее |
/// |---|---|---|
/// | 0.0 | 630…2251 | 1.79 м |
/// | 0.3 | 223…456 | 1.39 м |
/// | 0.6 | 154…281 | 1.38 м |
/// | 1.0 | 100…204 | 0.92 м |
///
/// Монотонно: чем сильнее давим, тем хуже. Разворот догоняющего лечится не
/// здесь, а долями коррекции (`separation::shares`) — уступает и отходит тот,
/// кто догнал, а переднего не толкают вовсе. Ручка оставлена, чтобы это можно
/// было перепроверить ползунком, а не пересборкой.
pub const SEPARATION_BACKSTEP: f32 = 1.0;
/// Какая доля шага ходьбы остаётся у придержанной пешки — той, чей курс на
/// последнем прогоне расталкивания упирался в перекрытого соседа, СТОЯЩЕГО или
/// ВСТРЕЧНОГО (`separation::SeparationHolds`; попутных и поперечных придержка
/// не касается — см. док ресурса).
///
/// Ручка мощности упора «ходьба против расталкивания». Пока обе стороны в
/// полную силу, пара встаёт на равновесии
/// `скорость / (SEPARATION_RATE · доля коррекции)` ≈ 0.35 м перекрытия — и
/// висит на нём вечно: пешка «идёт» на месте, дрожа на шаг за кадр. Доля `F`
/// опускает равновесие до `F ·` того же, то есть при 0.2 — до ~0.07 м,
/// которых на экране не видно. Ноль не берётся намеренно: полный стоп
/// превращает плотный перекрёсток в стоп-кадры — толпа перестаёт течь и
/// движется рывками от прогона к прогону.
/// **1.0 — придержки нет, и это результат замера, а не недосмотр.** Придержка
/// существовала ровно затем, чтобы упёршаяся пешка перестала давить в чужое
/// тело; ту же задачу лучше решает руление ([`SEPARATION_STEER`]) — оно уводит
/// её вбок вместо того, чтобы тормозить. На стенде
/// (`tools/crowd_tuning_lab/REPORT.md`) любая доля меньше единицы роняет
/// сходимость: при 0.4 на воронке доходят 156 пешек из 200, а на встречном
/// потоке медианный прогресс падает со 174 до 26 м.
///
/// Остаётся у придержки одна роль, и она не про скорость: придержанный в
/// пределах дистанции покоя от цели засчитывается дошедшим
/// (`movement::systems::move_moving_entities`) — иначе он толкался бы с тем, кто
/// занял его место, до скончания века.
pub const SEPARATION_HOLD: f32 = 1.0;
/// Потолок СКОРОСТИ расталкивания, м/с (`SeparationLab::max_speed`).
///
/// Толчок пары равен `перекрытие × SEPARATION_RATE`: при перекрытии 0.9 м это
/// 7.2 м/с, то есть в два с половиной раза быстрее ходьбы — расталкивание не
/// поправляет ходьбу, а перебивает её. `SEPARATION_MAX_STEP` от этого не
/// спасает — он страховка от телепорта, а не потолок скорости. Потолок
/// прогона — `max_speed · dt`, один на всех скоростях симуляции.
pub const SEPARATION_MAX_SPEED: f32 = 1.4;
/// Сила РУЛЕНИЯ: насколько курс ходьбы отклоняется вбок от того, кто встал на
/// дороге (`SeparationLab::steer`, `movement::SeparationSteer`).
///
/// Толчок двигает ПОЗИЦИЮ, а ходьба тут же везёт пешку обратно к цели — две
/// силы работают друг против друга, и весь результат уходит в намотанный путь.
/// Руление меняет НАПРАВЛЕНИЕ той же ходьбы: пешка обходит по дуге, не теряя
/// скорости. Без него симметричный встречный поток не расходится в принципе.
pub const SEPARATION_STEER: f32 = 1.0;
/// Страховка от телепорта: нижняя планка итогового клампа сдвига одной пешки
/// за прогон, м (итог — `max_step.max(max_speed · dt)`,
/// `separation::solver::clamped_step`). Давка у портала растекается за
/// несколько кадров, а не разлетается телепортом; треть человека за кадр на
/// глаз — плавный разъезд, а на больших dt планка растёт вместе с потолком
/// скорости и легитимный толчок не режет.
pub const SEPARATION_MAX_STEP: f32 = 0.3;

/// Во сколько раз ужимается дистанция покоя в паре «ИДУЩАЯ + СТОЯЩАЯ» — дефолт
/// [`SeparationLab::pass_squeeze`]. Пара «оба стоят» и пара «оба идут» держат
/// полную — сжимается ПРОХОД сквозь толпу, а не сама толпа.
///
/// Ради чего. Шаг решётки слотов — 2.0 м, а идущей пешке между двумя осевшими
/// нужен просвет `2 ×` дистанции покоя = 3.6 м: внутренние слоты недостижимы в
/// принципе. При 0.6 просвет становится 2.16 м, то есть решётка проходима, а
/// осевшая толпа и встречный поток по-прежнему держат полные 1.8 м.
pub const SEPARATION_PASS_SQUEEZE: f32 = 0.6;
/// Доля пешек, обходящих препятствие ВЛЕВО — дефолт
/// [`SeparationLab::left_share`]. Сторона личная и постоянная — хэш `PawnId`.
///
/// Одинаковая сторона у всех — источник двух картинок, которых в жизни не
/// бывает: попутный поток складывается в сплошную колонну, а недошедшие вокруг
/// плотной толпы едут одной каруселью. На стенде пятая часть левшей — лучший
/// результат по времени в расталкивании (0.61 против 0.75) и единственное, что
/// реально разбивает колонну (разброс 2.94 против 2.55).
pub const SEPARATION_LEFT_SHARE: f32 = 0.2;

/// Границы ползунков группы `Separation` панели Navigation для механизмов,
/// которые замер вывел в дефолты (`tools/crowd_tuning_lab/REPORT.md`).
/// Ползунки, а не константы, по той же причине, что у радиуса тела:
/// правильное значение у каждого — это компромисс, и проверяется он глазом на
/// живой толпе.
///
/// У протискивания снизу не ноль: при нём идущая проходит сквозь стоящую
/// насквозь. 1.0 — «не ужимается вовсе», то есть поведение до этого замера.
pub const SEPARATION_PASS_SQUEEZE_MIN: f32 = 0.3;
pub const SEPARATION_PASS_SQUEEZE_MAX: f32 = 1.0;
pub const SEPARATION_PASS_SQUEEZE_STEP: f32 = 0.05;
/// Половина — это уже не «немного левшей», а вторая такая же толпа навстречу
/// первой; выше ставить незачем, ниже нуля не бывает.
pub const SEPARATION_LEFT_SHARE_MIN: f32 = 0.0;
pub const SEPARATION_LEFT_SHARE_MAX: f32 = 0.5;
pub const SEPARATION_LEFT_SHARE_STEP: f32 = 0.05;

// Умолчание каждого ползунка — внутри его же диапазона.
const _: () = {
    assert!(
        SEPARATION_PASS_SQUEEZE >= SEPARATION_PASS_SQUEEZE_MIN
            && SEPARATION_PASS_SQUEEZE <= SEPARATION_PASS_SQUEEZE_MAX
    );
    assert!(
        SEPARATION_LEFT_SHARE >= SEPARATION_LEFT_SHARE_MIN
            && SEPARATION_LEFT_SHARE <= SEPARATION_LEFT_SHARE_MAX
    );
};

/// Тумблер расталкивания — заголовок группы `Separation` во вкладке Nav.
/// Выбор пользователя, переживает
/// рестарт и смену города (тот же контракт, что у `DemonStyle`). Выключение
/// ничего не откатывает: уже разведённые позиции просто остаются как есть.
#[derive(Resource, Reflect, SettingsGroup, Clone, Copy, PartialEq, Debug)]
#[reflect(Resource, SettingsGroup, Default)]
#[settings_group(group = "separation")]
pub struct SeparationStyle {
    pub enabled: bool,
    /// Сила обхода встречного в долях продольной коррекции (см.
    /// [`sidestep`](super::pairs::sidestep)).
    /// Ручка, а не константа, потому что у неё узкое окно между двумя разными
    /// поломками — ниже слипание, выше карусель — и подбирается она только
    /// замером в толпе (`examples/demos/crowd_demo.rs`).
    pub sidestep: f32,
    /// Какая доля продольного толчка доживает до применения (см.
    /// [`damp_along_heading`](super::pairs::damp_along_heading)). 1 — ничего не
    /// давим, и догоняющий в очереди
    /// заметно пятится; 0 — толчок строго поперечный, и толпа, идущая в одну
    /// точку, схлопывается в пятно и вращается вместо того, чтобы раздаться.
    pub backstep: f32,
    /// Какая доля шага ходьбы остаётся у придержанной пешки (см.
    /// [`SeparationHolds`](super::SeparationHolds)): 1 — придержки нет и ходьба
    /// давит в упор до
    /// равновесия, 0 — полный стоп и рваное движение толпы. Дефолт и разбор
    /// компромисса — [`SEPARATION_HOLD`].
    pub hold: f32,
}

impl Default for SeparationStyle {
    fn default() -> Self {
        Self {
            enabled: true,
            sidestep: SEPARATION_SIDESTEP,
            backstep: SEPARATION_BACKSTEP,
            hold: SEPARATION_HOLD,
        }
    }
}

impl Eq for SeparationStyle {}

/// Числовые ручки расталкивания — те, что не спрашивают пользователя.
///
/// **Поля этого типа ДЕЙСТВУЮТ В ИГРЕ**: все семь приходят из констант — пять
/// из этого файла ([`SEPARATION_MAX_STEP`], [`SEPARATION_MAX_SPEED`],
/// [`SEPARATION_STEER`], [`SEPARATION_PASS_SQUEEZE`], [`SEPARATION_LEFT_SHARE`])
/// и одна из `settings.rs` ([`SEPARATION_RATE`] — у неё читатель не один,
/// см. `movement/destination.rs`); `steer_release` — 2 м. Две последние вдобавок
/// торчат ползунками во вкладке Nav (`ui/navigation/knobs.rs`).
///
/// **Всё, чего в игре нет, лежит в [`SeparationExperiments`]** — отдельным
/// полем, а не вперемешку: ветка решателя, читающая `lab.experiments.*`, тем
/// самым помечена «в игре не исполняется», и перевести ручку в живые нельзя,
/// не передвинув поле. Раньше это было обещанием в этом доке, и док устарел.
///
/// Намеренно НЕ [`SettingsGroup`], в отличие от [`SeparationStyle`]: значения
/// подбираются замером (`examples/demos/crowd_demo.rs`), а не выбираются
/// пользователем, и уезжать в `settings.toml` им незачем.
#[derive(Resource, Reflect, Clone, Copy, PartialEq, Debug)]
#[reflect(Resource, Default)]
pub struct SeparationLab {
    /// Скорость экспоненциальной релаксации перекрытия, 1/с виртуального
    /// времени: перекрытие затухает как `exp(-rate · t)`
    /// ([`SEPARATION_RATE`], [`relaxation_fraction`](super::solver::relaxation_fraction)).
    pub rate: f32,
    /// Страховка от телепорта: нижняя планка итогового клампа сдвига за
    /// прогон ([`SEPARATION_MAX_STEP`], [`clamped_step`](super::solver::clamped_step)).
    ///
    /// Потолком скорости он не работает — настоящий предел задаёт
    /// [`SeparationLab::max_speed`]; итоговый кламп равен
    /// `max_step.max(max_speed · dt)`: на 1× это 0.3 м на прогон (ловит
    /// толчок твёрдого ядра, у которого потолка скорости нет), на больших dt
    /// он растёт вместе с потолком и легитимный толчок не режет.
    pub max_step: f32,
    /// Потолок СКОРОСТИ расталкивания, м/с — в отличие от `max_step`, не
    /// зависит от частоты кадров и сравним со скоростью ходьбы (2.8 м/с).
    /// Потолок прогона — `max_speed · dt`, один на всех скоростях симуляции.
    /// 0 — выключен, ограничивает только `max_step` (ветка стенда, к нарезке
    /// dt не инвариантная; в игре недостижима).
    ///
    /// Ради чего. Толчок пары равен `перекрытие × rate`, а `rate` — 8/с: при
    /// перекрытии в 0.9 м это 7.2 м/с, то есть в два с половиной раза быстрее
    /// ходьбы. В плотном встречном потоке расталкивание не поправляет ходьбу,
    /// а перебивает её: пешку швыряет назад быстрее, чем она идёт вперёд, она
    /// доходит обратно, и так по кругу. Отсюда 24 км намотанного пути на 2.4 км
    /// продвижения в базовом прогоне стенда.
    pub max_speed: f32,
    /// Сила РУЛЕНИЯ, доли: насколько курс ходьбы отклоняется вбок от того, кто
    /// стоит на дороге. 0 — руления нет, и `move_moving_entities` идёт ровно
    /// тем кодом, что и раньше. См. [`SeparationSteer`](super::SeparationSteer).
    pub steer: f32,
    /// Ближе этого расстояния до waypoint'а руление выключается, м. Иначе
    /// пешка, которую уводит вбок у самой точки, начинает наматывать вокруг
    /// неё круги вместо того, чтобы её пройти: `move_moving_entities` снимает
    /// waypoint только когда бюджет шага накрывает остаток, а отклонённый курс
    /// этот остаток не сокращает.
    pub steer_release: f32,
    /// Во сколько раз ужимается дистанция покоя в паре «ИДУЩАЯ + СТОЯЩАЯ»
    /// (1 — не ужимается, как сейчас; 0.6 — 1.8 м покоя превращаются в 1.08 м
    /// на время протискивания).
    ///
    /// Зачем это отдельно от [`SeparationExperiments::compress`]. Сжатие по числу
    /// контактов ужимает пешку тем сильнее, чем больше рядом соседей, — то есть
    /// ровно ТАМ, где толпа стоит: осевшая толпа садится на постоянно сжатой
    /// дистанции, и радиус тела перестаёт работать как задумано (на стенде это
    /// `sep_share` 0.81 против 0.43 без сжатия — равновесие толпы оказывается
    /// перекрытым навсегда).
    ///
    /// Ужимать надо не толпу, а ПРОХОД сквозь неё. Шаг решётки слотов — 2.0 м,
    /// а идущей пешке между двумя осевшими нужен просвет `2 × дистанции покоя`
    /// = 3.6 м: внутренние слоты недостижимы в принципе (см.
    /// `tools/separation_slots_lab/REPORT.md`, раздел 2.3). Стоящему при этом
    /// хватает гораздо меньшего личного пространства, чем идущему, — у живых
    /// людей это разные величины. Ужатие ровно этой пары даёт просвет 2 × 1.08 =
    /// 2.16 м, то есть решётка становится проходимой, а дистанция «стоящий —
    /// стоящий» и «идущий — идущий» остаётся полной: осевшая толпа не слипается,
    /// поток не сходится в колонну.
    pub pass_squeeze: f32,
    /// Доля пешек, обходящих препятствие ВЛЕВО, а не вправо (0 — все вправо,
    /// как сейчас; 0.2 — каждая пятая левша). Сторона личная и постоянная —
    /// хэш [`crate::rng::PawnId`], тот же трюк, что у `coincident_direction`.
    ///
    /// Зачем. Одинаковая сторона у всех — это не только «предсказуемо, как у
    /// живых пешеходов», но и источник двух картинок, которых в жизни не бывает:
    /// попутный поток складывается в одну сплошную колонну (все уступают в одну
    /// сторону и выстраиваются друг за другом), а недошедшие вокруг плотной
    /// толпы едут одной каруселью — руление всем уводит вправо, и объехать они
    /// пытаются по одной и той же дуге. Немного левшей ломает и то и другое, не
    /// теряя предсказуемости на уровне пары.
    pub left_share: f32,
    /// Ручки, которых в игре нет, — см. [`SeparationExperiments`].
    pub experiments: SeparationExperiments,
}

impl Default for SeparationLab {
    fn default() -> Self {
        Self {
            rate: SEPARATION_RATE,
            max_step: SEPARATION_MAX_STEP,
            max_speed: SEPARATION_MAX_SPEED,
            steer: SEPARATION_STEER,
            steer_release: 2.0,
            pass_squeeze: SEPARATION_PASS_SQUEEZE,
            left_share: SEPARATION_LEFT_SHARE,
            experiments: SeparationExperiments::default(),
        }
    }
}

impl Eq for SeparationLab {}

/// Ручки расталкивания, которых в игре НЕТ: каждая выключена дефолтом
/// ([`SeparationExperiments::default`]) и живёт ради стенда
/// (`examples/demos/crowd_demo/`, отчёты в `tools/separation_lab/` и
/// `tools/separation_slots_lab/`).
///
/// «Выключена» здесь значит буквально: гейт — ноль, и ветка решателя не
/// исполняется (`horizon`, `anticipation`, `lane_bias`, `compress`,
/// `crowd_sidestep`, `slide`, `stuck_compress`, `hard_core`, `slide_release`);
/// либо множитель — нейтральная единица (`idle_mobility`, `arrive_slack`,
/// `anticipate_margin`); либо параметр вторичен и инертен, пока его гейт ноль
/// (`compress_at`, `stuck_after`, `stuck_ramp`). Набор запинен тестом
/// `game_defaults_keep_every_experiment_off`.
///
/// Отдельный тип, а не секция комментариями: место чтения (`lab.experiments.x`
/// в горячем решателе) обязано само говорить, что эта ветка в игре мертва.
#[derive(Reflect, Clone, Copy, PartialEq, Debug)]
#[reflect(Default)]
pub struct SeparationExperiments {
    /// Горизонт упреждения, с: насколько вперёд смотреть на СБЛИЖАЮЩЕГОСЯ, но
    /// ещё не перекрывшегося соседа. 0 — упреждения нет, механизм чисто
    /// реактивный, как сейчас. См. [`anticipate`](super::pairs::anticipate).
    pub horizon: f32,
    /// Сила упреждения, м/с бокового сноса.
    pub anticipation: f32,
    /// Во сколько радиусов считается «мимо»: предсказанный промах меньше
    /// `anticipate_margin × (r_a + r_b)` — повод уклоняться.
    pub anticipate_margin: f32,
    /// Примесь правой нормали в направление уклонения (0…1). Лобовая встреча
    /// вырождается — предсказанный контакт лежит на курсе, и «уклоняться»
    /// некуда; примесь задаёт сторону, как у живых пешеходов.
    pub lane_bias: f32,
    /// На сколько ужимается радиус тела в давке (0 — не ужимается, 0.4 — на
    /// 40% при полной загрузке). Толпа в узком месте сжимается, а не встаёт.
    pub compress: f32,
    /// Сколько одновременных перекрытий считается полной загрузкой для
    /// [`SeparationExperiments::compress`].
    pub compress_at: f32,
    /// Доля обхода встречного, которая достаётся паре В КУЧЕ (у пары, которая
    /// одна, обход работает всегда). 0 — нынешний гейт `alone`.
    pub crowd_sidestep: f32,
    /// Подвижность СТОЯЩЕЙ пешки в паре — доля коррекции, которая ей достаётся
    /// (1 — как сейчас, наравне с идущей; 0 — стоящую не сдвинуть вовсе).
    ///
    /// Зачем. Пешка, дошедшая до своего слота, дошла ОКОНЧАТЕЛЬНО: её слот
    /// заявлен, ничей больше путь в нём не кончается, и всё, что с ней может
    /// случиться дальше, — это толчки от проходящих мимо. Каждый такой толчок
    /// уводит её со слота, а вернуться ей нечем: маршрут кончился, новую цель
    /// в этом сценарии никто не выдаёт. Толпа, которая должна была осесть,
    /// вместо этого весь остаток окна расползается — второй критерий стенда
    /// («никто не двигается») не выполняется никогда, а третий (пройденный
    /// путь) растёт из ничего.
    ///
    /// Стоящий, которого не сдвинуть, — это ещё и то, как ведут себя живые
    /// люди: протискивается тот, кто идёт, а не тот, кто стоит. Ровно этим
    /// уже выражена «толпа обтекает демона»
    /// ([`DEMON_MOBILITY`](crate::settings::DEMON_MOBILITY)).
    ///
    /// Ноль брать опасно: в куче, где НИКТО не идёт (сценарий 1), стоят все, и
    /// при нулевой подвижности она не разойдётся вовсе. Отсюда ручка, а не
    /// правило.
    pub idle_mobility: f32,
    /// Во сколько раз дистанция покоя, на которой ПРИДЕРЖАННАЯ пешка
    /// засчитывается дошедшей (`systems::move_moving_entities`), меньше
    /// настоящей. 1 — как сейчас.
    ///
    /// Зачем ручка. Допуск существует ради затора: упёршуюся в чужое тело
    /// пешку ближе к цели всё равно не пустят, и без засчитанного прихода она
    /// толкалась бы вечно. Но допуск — це́лая дистанция покоя, а шаг решётки
    /// слотов — ровно она же (1.8 м покоя при шаге 2 м): пешка, вставшая на
    /// краю допуска, стоит почти В СОСЕДНЕМ слоте. Соседи после этого
    /// перекрыты навсегда, толкают друг друга без надежды разойтись (обоим
    /// «дойти» уже некуда) — и осевшая толпа не замирает, а тихо ползёт весь
    /// остаток прогона.
    pub arrive_slack: f32,
    /// Какая доля составляющей шага, ведущей В перегородившее тело, снимается
    /// (0 — не снимается ничего, как сейчас; 1 — в тело не идём вовсе).
    /// См. [`SeparationBlock`](super::SeparationBlock).
    pub slide: f32,
    /// На сколько ужимается дистанция покоя у пешки, которая уже
    /// ЗАЛИПЛА, — доля (0 — не ужимается). В отличие от
    /// [`SeparationExperiments::compress`], загрузку задаёт не число соседей, а ВРЕМЯ
    /// непрерывного упора курсом в чужое тело: сжатие получает только тот, кто
    /// действительно не может пройти, и ровно на то время, пока не прошёл.
    ///
    /// Это и есть «кратковременно ужать тело, чтобы пролезть через тупиковую
    /// геометрию» — в отличие от постоянного сжатия рядом с соседями, из-за
    /// которого толпа садится слипшейся.
    pub stuck_compress: f32,
    /// Сколько виртуальных секунд непрерывного упора считается залипанием:
    /// раньше этого сжатия нет вовсе.
    pub stuck_after: f32,
    /// Ещё столько секунд упора — и сжатие выходит на полную
    /// [`SeparationExperiments::stuck_compress`].
    pub stuck_ramp: f32,
    /// Доля дистанции покоя, которая считается ТВЁРДЫМ ЯДРОМ тела: ближе неё
    /// перекрытие снимается целиком за один прогон, а не долей `rate · dt`
    /// (0 — ядра нет, как сейчас).
    ///
    /// Зачем. Всё остальное в этом механизме мягкое, и это правильно: жёсткая
    /// релаксация в давке разлеталась бы цепными толчками. Но у мягкости есть
    /// цена, которую видно глазом: встречная пара сближается за кадр на 0.09 м,
    /// а расталкивание снимает `rate · dt` ≈ 7 % перекрытия — то есть заведомо
    /// меньше, и на полном ходу пешки въезжают друг в друга. Стенд считает это
    /// как `through` (центры ближе половины спрайта), и чем свободнее
    /// протискивание ([`SeparationLab::pass_squeeze`]), тем таких случаев
    /// больше.
    ///
    /// Ядро разделяет две разные величины, которые до сих пор были одной:
    /// личное пространство (мягкое, сжимаемое, торгуется за проходимость) и
    /// собственно ТЕЛО (несжимаемое). При 0.5 ядро равно половине дистанции
    /// покоя, то есть спрайты ровно касаются: ближе этого пешки не сходятся ни
    /// при каком сжатии, а всё, что мягче, работает как работало.
    pub hard_core: f32,
    /// Сколько секунд непрерывного упора терпит СКОЛЬЖЕНИЕ
    /// ([`SeparationExperiments::slide`]), прежде чем отпустить пешку (0 — не отпускает
    /// никогда, как было).
    ///
    /// Зачем. Скольжение — единственный найденный способ гарантировать, что
    /// пешки не входят друг в друга: из шага снимается составляющая, ведущая В
    /// тело. Но в сходящейся толпе оно же и запирает — войти некуда, обойти
    /// некуда, и на стенде это дедлок с каруселью (61 дошедшая из 200,
    /// `tools/separation_slots_lab/REPORT.md`, 3.3).
    ///
    /// Отпускание разводит два случая, которые до сих пор были одним: пока у
    /// пешки есть варианты, она обязана обходить, а не лезть в тело; а когда
    /// вариантов нет и она стои́т в упоре секунду, запрет снимается — дальше
    /// работает протискивание ([`SeparationLab::pass_squeeze`]). Ровно так
    /// ведёт себя человек: сперва обходит, а в час пик протискивается.
    pub slide_release: f32,
}

/// Всё выключено — см. док типа: это и есть «поведение игры».
impl Default for SeparationExperiments {
    fn default() -> Self {
        Self {
            horizon: 0.0,
            anticipation: 0.0,
            anticipate_margin: 1.0,
            lane_bias: 0.0,
            compress: 0.0,
            compress_at: 4.0,
            crowd_sidestep: 0.0,
            idle_mobility: 1.0,
            arrive_slack: 1.0,
            slide: 0.0,
            stuck_compress: 0.0,
            stuck_after: 0.5,
            stuck_ramp: 0.5,
            hard_core: 0.0,
            slide_release: 0.0,
        }
    }
}
