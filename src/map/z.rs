pub const Z_INSPECTOR_HIGHLIGHT: f32 = 29.8;

// Проверяется ровно то, что записано прозой рядом с константами; всё
// остальное — свобода, которую отбирать незачем.
const _: () = {
    // площадные заливки: земля → парк → лес → трава → песок → вода
    assert!(Z_GROUND < Z_LANDUSE);
    // газон острова кольца — сразу над землёй, под всем замапленным на нём;
    // его трава без канта — над травой и под песком
    assert!(Z_GROUND < Z_RING_ISLAND);
    assert!(Z_RING_ISLAND < Z_LANDUSE);
    assert!(Z_GRASS < Z_RING_GRASS);
    assert!(Z_RING_GRASS < Z_SAND);
    // газон широкой обочины — под её плиткой, плитка — над голой землёй,
    // оба — под кварталами
    assert!(Z_GROUND < Z_ROAD_VERGE);
    assert!(Z_ROAD_VERGE_LAWN < Z_ROAD_VERGE_YARD);
    assert!(Z_ROAD_VERGE_YARD < Z_ROAD_VERGE);
    assert!(Z_ROAD_VERGE < Z_LANDUSE);
    assert!(Z_LANDUSE < Z_LANDUSE_YARD);
    assert!(Z_LANDUSE_YARD < Z_PARK);
    assert!(Z_PARK < Z_WOOD);
    assert!(Z_WOOD < Z_TREE_ROW_BAND_CASING);
    assert!(Z_TREE_ROW_BAND_CASING < Z_TREE_ROW_BAND);
    assert!(Z_TREE_ROW_BAND < Z_GRASS);
    assert!(Z_GRASS < Z_SAND);
    // тротуар — над заливками и над лентой аллеи (дорожка упирается в тротуар),
    // но под лентами улицы: на перекрёстке полосу кроет проезжая часть
    assert!(Z_SAND < Z_ALLEY);
    assert!(Z_ALLEY < Z_SIDEWALK);
    assert!(Z_SIDEWALK < Z_ROAD_MEDIAN);
    assert!(Z_ROAD_MEDIAN < Z_ROAD);
    // грунтовка — над тротуарами и дорожками, под асфальтом: узел асфальтовый
    assert!(Z_SIDEWALK < Z_UNPAVED_ROAD);
    assert!(Z_UNPAVED_ROAD < Z_ROAD);
    // стоянка — над дорогами (её край обрезает проезды), под площадкой;
    // разметка — поверх своего покрытия
    assert!(Z_ROAD < Z_ROAD_WEAR_MASK);
    assert!(Z_ROAD_WEAR_MASK < Z_ROAD_WEAR);
    assert!(Z_ROAD_WEAR < Z_ROAD_PAINT);
    assert!(Z_ROAD_PAINT < Z_PARKING);
    assert!(Z_PARKING < Z_PARKING_LINES);
    assert!(Z_PARKING_LINES < Z_PITCH);
    // дорога сквозь большую стоянку: бордюр поверх её асфальта, двойная
    // сплошная поверх бордюра, разметка мест — поверх всего нарисованного
    assert!(Z_PARKING < Z_LOT_SIDEWALK);
    assert!(Z_LOT_SIDEWALK < Z_LOT_LINES);
    assert!(Z_LOT_LINES < Z_PARKING_LINES);
    // краска островков у колец — над краской улиц и асфальтом стоянки, под
    // разметкой мест
    assert!(Z_ROAD_PAINT < Z_ROAD_ISLANDS);
    assert!(Z_PARKING < Z_ROAD_ISLANDS);
    assert!(Z_ROAD_ISLANDS < Z_PARKING_LINES);
    // вода — над всеми дорогами, но под тенью моста и мостом: дорога поверх
    // воды только мостом; русло — волосок над полигоном
    assert!(Z_ROAD < Z_POND);
    // площадка — над дорогами (дорожка упирается в край поля), под водой
    assert!(Z_ROAD < Z_PITCH);
    assert!(Z_PITCH < Z_PITCH_LINES);
    assert!(Z_PITCH_LINES < Z_POND);
    assert!(Z_POND < Z_WATERWAY);
    // ж/д путь — над дорогами (переезд) и под мостом с его тенью: путепровод
    // кроет пути. Снизу вверх: балласт → шпалы → нитки → вагон на них
    assert!(Z_WATERWAY < Z_RAIL);
    assert!(Z_RAIL < Z_RAIL_TIE);
    // настил переезда — над шпалами и балластом, под нитками, которые по нему
    assert!(Z_RAIL_TIE < Z_RAIL_CROSSING);
    assert!(Z_RAIL_CROSSING < Z_RAIL_STEEL);
    assert!(Z_RAIL_TIE < Z_RAIL_STEEL);
    assert!(Z_RAIL_STEEL < Z_WAGON);
    assert!(Z_WAGON < Z_BRIDGE_SHADOW);
    assert!(Z_ROAD < Z_BRIDGE_SHADOW);
    assert!(Z_BRIDGE_SHADOW < Z_BRIDGE_CASING);
    assert!(Z_BRIDGE_CASING < Z_BRIDGE);
    // мост над дорогами и путями, но под трамваем: трамвай по мосту обязан
    // быть виден
    assert!(Z_ROAD < Z_BRIDGE_CASING);
    assert!(Z_BRIDGE < Z_BRIDGE_PAINT);
    assert!(Z_BRIDGE_PAINT < Z_TRAM);
    // путь на путепроводе — своей лестницей балласт → шпалы → нитки над
    // настилом моста, под трамваем
    assert!(Z_BRIDGE < Z_RAIL_BRIDGE);
    assert!(Z_RAIL_BRIDGE < Z_RAIL_BRIDGE_TIE);
    assert!(Z_RAIL_BRIDGE_TIE < Z_RAIL_BRIDGE_STEEL);
    assert!(Z_RAIL_BRIDGE_STEEL < Z_TRAM);
    // машина — выше трамвая: стоит на асфальте поверх путей
    assert!(Z_TRAM < Z_CAR);
    // забор стоит на земле — над машиной, но под опорами теплотрассы
    assert!(Z_CAR < Z_FENCE);
    // теплотрасса перешагивает всё, что стоит на земле, — и свою тень
    assert!(Z_FENCE < Z_PIPE_SHADOW);
    assert!(Z_PIPE_SHADOW < Z_PIPE);
    // пятно под порталом кроет дороги, но не тела
    assert!(Z_PIPE < Z_PORTAL_STAIN);
    assert!(Z_PORTAL_STAIN < Z_CORPSE);
    assert!(Z_CORPSE < Z_FAR_CROWD);
    assert!(Z_FAR_CROWD < Z_PORTAL);
    // цилиндр промзоны: тень под домами, стена и верх над ними
    assert!(Z_PORTAL < Z_INDUSTRY_SHADOW);
    assert!(Z_INDUSTRY_SHADOW < Z_BUILDING);
    assert!(Z_BUILDING < Z_INDUSTRY_WALL);
    assert!(Z_INDUSTRY_WALL < Z_INDUSTRY);
    // лента крепостной стены — над зданиями и цилиндрами промзоны, под юнитами
    assert!(Z_INDUSTRY < Z_WALL);
    // дебаг-заливки навмеша и полимеша — над статичной картой, но под любым
    // юнитом: нижний юнит стоит на `Z_UNIT_BASE` минус полная просадка
    assert!(Z_WALL < Z_NAVMESH_OVERLAY);
    assert!(Z_NAVMESH_OVERLAY < Z_POLYMESH_OVERLAY);
    assert!(Z_POLYMESH_OVERLAY < Z_UNIT_BASE - MAP_SIZE.y * Y_SORT_FACTOR);
    // Тот самый инвариант, который прозой не удержался (см. `Z_UNIT_BASE`).
    // Теперь база из него и выводится, так что проверка стережёт уже не её, а
    // будущую правку: сменится `Y_SORT_FACTOR`, `Z_BUILDING` или размер карты —
    // выражение подстроится, а вот потолок сверху проверить всё равно некому.
    assert!(Z_UNIT_BASE - MAP_SIZE.y * Y_SORT_FACTOR > Z_BUILDING);
    // …а самый южный (`y = 0`) — под искрами душ и под тенями крон: юнит в
    // тени затемняется
    assert!(Z_UNIT_BASE < Z_SOUL);
    assert!(Z_SOUL < Z_TREE_SHADOW);
    assert!(Z_TREE_SHADOW < Z_TREE);
    // дебаг-слой хвои накрывает кроны, которые объясняет
    assert!(Z_TREE < Z_CONIFER_NOISE_OVERLAY);
    // оверлеи дорог — над всем, что объясняют: сеть → контуры OSM → колея
    assert!(Z_CONIFER_NOISE_OVERLAY < Z_NETWORK_OVERLAY);
    assert!(Z_NETWORK_OVERLAY < Z_OSM_CONTOURS_OVERLAY);
    assert!(Z_OSM_CONTOURS_OVERLAY < Z_RUT_OVERLAY);
    // подсветка инспектора — над всеми оверлеями, она объясняет саму пробу
    assert!(Z_RUT_OVERLAY < Z_INSPECTOR_HIGHLIGHT);
};

/// Z юнита по его мировой y-координате.
pub fn unit_z(y: f32) -> f32 {
    Z_UNIT_BASE - y * Y_SORT_FACTOR
}
