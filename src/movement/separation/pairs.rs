//! Уровень пары: кто кому уступает, как делится коррекция и в какую сторону
//! обходить. Всё здесь — чистые функции от двух [`Pawn`] и настроек;
//! сетка, буферы и порядок обхода живут в [`super::solver`].

use bevy::prelude::*;

use super::SeparationLab;
use crate::rng::hash_fraction;

/// Участник одного прогона: снятая позиция плюс всё, что нужно паре.
#[derive(Clone, Copy)]
pub(super) struct Pawn {
    pub(super) entity: Entity,
    /// Личный номер пешки — ось разведения совпавших позиций (см.
    /// `solver::coincident_direction`).
    pub(super) pawn_id: u32,
    pub(super) position: Vec2,
    pub(super) radius: f32,
    /// Доля коррекции пары, пропорциональная подвижности: человек 1.0, демон
    /// [`DEMON_MOBILITY`], пожирающий 0.0 (толкает, но не двигается).
    pub(super) mobility: f32,
    /// Куда пешка идёт прямо сейчас, единичный; `ZERO` у стоящей. Нужен
    /// обходу встречного (см. [`sidestep`]) и придержке (`SeparationHolds`).
    pub(super) heading: Vec2,
    /// Модуль скорости ходьбы, м/с — нужен упреждению ([`anticipate`]), чтобы
    /// считать время до сближения. У стоящей не используется.
    pub(super) speed: f32,
    /// Придерживают только людей, см. `SeparationHolds`.
    pub(super) human: bool,
    /// Сколько виртуальных секунд подряд пешка упирается курсом в чужое тело —
    /// источник кратковременного сжатия ([`SeparationExperiments::stuck_compress`]).
    pub(super) stuck: f32,
}

/// Обход встречного: боковая добавка к толчку, чтобы двое идущих ЛОБ В ЛОБ
/// могли разойтись.
///
/// Без неё они расходиться не могут в принципе. Коррекция пары идёт строго
/// вдоль отрезка между центрами, а у лобовой встречи этот отрезок совпадает с
/// вектором движения обоих — то есть каждого толкает ровно НАЗАД по его же
/// пути, а на следующем тике движение снова закрывает зазор. Пара «слипается»
/// и топчется, пока симметрию не сломает что-то постороннее: разброс скоростей
/// (`Pace`), третья пешка рядом, смена waypoint'а. Боковой составляющей у
/// толчка нет ни в каком виде, поэтому шага в сторону не происходит никогда.
///
/// Добавка тем сильнее, чем более лобовая встреча (`frontal` — косинус между
/// курсом и направлением на соседа). Сторона — всегда ПРАВАЯ относительно
/// собственного курса, как у живых пешеходов: обход предсказуемый, а не в
/// случайную сторону. Величина — доля [`SEPARATION_SIDESTEP`] от продольной
/// коррекции той же пары.
///
/// Курс берётся у идущих; у стоящей пешки он `ZERO`, и добавки нет — стоящего
/// незачем «обходить», его достаточно раздвинуть.
///
/// Кому она достаётся — решают [`yields`] и «пара одна» на месте вызова; оба
/// ограничения существуют затем, чтобы обход не превращался во вращение, см.
/// их доки.
pub(super) fn sidestep(
    pawn: &Pawn,
    to_other: Vec2,
    correction: f32,
    strength: f32,
    left_share: f32,
) -> Vec2 {
    let frontal = pawn.heading.dot(to_other);
    if frontal <= 0.0 {
        return Vec2::ZERO;
    }
    side_of(pawn, left_share) * (correction * strength * frontal)
}

/// Кто из встречной пары обходит: обходит РОВНО ОДИН.
///
/// Если вправо уходят оба, обход не работает совсем — он вырождается в
/// вращение. Курсы у встречных противоположны, поэтому «вправо от себя» у них
/// в мировых координатах противоположно, и две одинаковые по величине боковые
/// добавки складываются в пару сил: связка проворачивается как твёрдое тело,
/// а ВЗАИМНАЯ геометрия — расстояние и угол между курсом и осью пары — остаётся
/// прежней. Пока контроллер пути держит курс на цель, лежащую за соседом (в
/// «воронке» цель у всех одна точка), конфигурация воспроизводится каждый кадр:
/// пара наматывает круги вокруг общего центра и не расходится никогда. Именно
/// это и видно на экране как «слиплись и ходят по кругу».
///
/// Обходит один — и инварианта нет: ось пары поворачивается вокруг того, кто
/// держит линию, `frontal` у обходящего падает, продольная коррекция получает
/// боковую составляющую, и пара разъезжается. Ровно так расходятся живые
/// пешеходы — в сторону уходит кто-то один, а не оба сразу.
///
/// Уступает более подвижный: у пожирающего демона (mobility 0) уступать нечем,
/// и в паре «человек — демон» обходит человек. При равной подвижности —
/// старший [`PawnId`], лишь бы выбор был устойчив от прогона к прогону (по
/// `PawnId`, а не по `Entity`, по той же причине, что в
/// [`coincident_direction`]).
pub(super) fn yields(a: &Pawn, b: &Pawn) -> bool {
    if a.mobility != b.mobility {
        return a.mobility > b.mobility;
    }
    a.pawn_id > b.pawn_id
}

/// Доли коррекции пары. По умолчанию — по подвижности (человек 1.0, демон
/// [`DEMON_MOBILITY`], пожирающий 0.0), но у ОЧЕРЕДИ всю коррекцию забирает
/// ЗАДНИЙ, а переднего не трогает никто.
///
/// Иначе догоняющий расталкивает того, кого догнал: передний, ничего не
/// сделав, получает толчок в спину и сходит с линии, по которой шёл. На экране
/// это читается как «его пихнули», и виноват всегда не тот. В жизни уступает
/// тот, кто пришёл вторым, — он и обходит.
///
/// Очередь — это ДВА условия, и второе не «почти то же самое».
///
/// Первое: курсы расходятся меньше чем на 90° (`dot > 0`). Порог намеренно
/// широкий — догоняют и под углом, полоса потока не прямая, и «примерно одним
/// курсом» здесь значит именно «менее 90°», а не «почти параллельно».
///
/// Второе: сосед СПЕРЕДИ ровно у одного — у догоняющего он спереди, у
/// переднего сзади. Если сосед спереди у ОБОИХ, пара не догоняет, а СХОДИТСЯ:
/// это `opposed` из [`super::solver`], случай, ради которого существует
/// [`sidestep`]. Одного лишь первого условия мало: пара, сходящаяся под 80°,
/// проходит его насквозь, и тогда всю коррекцию забирает тот, кто оказался в
/// паре первым, — то есть по порядку в сетке, а не по геометрии. Дороже
/// другое: обход считается как `overlap ·` доля УСТУПАЮЩЕГО, а уступающего
/// выбирает [`yields`] по `PawnId` — и в половине таких пар доля уступающего
/// оказывалась нулём, то есть обход умножался на ноль там, где он единственное,
/// что эту пару разводит.
///
/// Уступать может только подвижный: у пожирающего демона (mobility 0)
/// забирать нечего, и пара остаётся на долях по подвижности.
pub(super) fn shares(a: &Pawn, b: &Pawn, direction: Vec2) -> (f32, f32) {
    let weights = a.mobility + b.mobility;
    let by_mobility = (a.mobility / weights, b.mobility / weights);

    let aligned =
        a.heading != Vec2::ZERO && b.heading != Vec2::ZERO && a.heading.dot(b.heading) > 0.0;
    if !aligned {
        return by_mobility;
    }
    // `direction` смотрит от a к b: положительный dot — сосед впереди
    let a_facing = a.heading.dot(direction) > 0.0;
    let b_facing = b.heading.dot(-direction) > 0.0;
    if a_facing && b_facing {
        // сходятся, а не догоняют: очереди тут нет
        return by_mobility;
    }
    if a_facing && a.mobility > 0.0 {
        (1.0, 0.0)
    } else if b_facing && b.mobility > 0.0 {
        (0.0, 1.0)
    } else {
        by_mobility
    }
}

/// Придавить составляющую толчка ВДОЛЬ собственного курса пешки в `keep` раз;
/// поперечная остаётся целиком. У стоящей курса нет — её толчок не трогаем.
///
/// Ручка между двумя противоположными поломками, и обе видны глазом.
///
/// `keep` = 1 (ничего не давим) — продольный толчок цел, и в очереди
/// догоняющего отбрасывает НАЗАД по его же пути: на экране пешка
/// разворачивается, отходит и снова идёт вперёд, хотя ничего не решала.
///
/// `keep` = 0 (давим насмерть) — толчок становится строго поперечным, и тогда
/// толпа, идущая В ОДНУ ТОЧКУ, не может расшириться ВООБЩЕ: наружу — это назад
/// по курсу, а назад запрещено. Вся коррекция уходит в касательную, и затор не
/// рассасывается, а начинает вращаться вокруг общего центра. Ровно это и
/// случилось на сценарии «воронка»: 200 пешек в одном пятне, все 200 в
/// перекрытии.
///
/// Поэтому середина: продольная часть ослаблена (реверс в очереди перестаёт
/// бросаться в глаза), но не обнулена (сходящаяся толпа всё ещё умеет
/// раздаться). Подбирается ползунком на живой толпе, как и остальные.
pub(super) fn damp_along_heading(push: Vec2, heading: Vec2, keep: f32) -> Vec2 {
    if heading == Vec2::ZERO {
        return push;
    }
    let along = heading * push.dot(heading);
    push - along * (1.0 - keep)
}

/// Уклонение ОТ ЕЩЁ НЕ СЛУЧИВШЕГОСЯ столкновения: боковой снос за `dt`, который
/// пешка `a` даёт себе, увидев сближающегося `b`.
///
/// Реактивное расталкивание по построению опаздывает: оно включается, когда
/// тела уже перекрылись, то есть когда обходить поздно и остаётся расталкивать.
/// Отсюда и вся картинка «колонны»: встречные упираются, придерживаются,
/// протискиваются по одному. Живой пешеход решает раньше — по тому, КУДА
/// сосед идёт, а не где он стоит.
///
/// Считается классически (время до ближайшего сближения, оно же time to
/// closest approach): относительная скорость `v = v_a − v_b`, вектор до соседа
/// `rel`. Расходящихся (`rel · v ≤ 0`) пропускаем сразу — самый частый случай, и
/// он же самый дешёвый. Момент максимального сближения `t = (rel · v)/|v|²`;
/// дальше горизонта — не наше дело. Вектор `closest` — где сосед окажется
/// относительно нас в этот момент; если его длина меньше суммы радиусов (с
/// запасом [`SeparationExperiments::anticipate_margin`]), столкновение предсказано.
///
/// Уклоняемся **строго поперёк собственного курса**: продольная составляющая —
/// это торможение, а тормозить сдвигом позиции нельзя, на экране это рывок
/// назад (та же болезнь, ради которой существует [`damp_along_heading`]).
/// Скорость гасит придержка, и это её работа, а не этой функции.
///
/// Лобовая встреча вырождается — `closest` почти коллинеарен курсу, и
/// поперечной составляющей у него нет. Ровно ту же дыру у реактивной ветки
/// затыкает [`sidestep`]; здесь её затыкает [`SeparationExperiments::lane_bias`],
/// примешивая правую нормаль. Разница в том, что упреждение срабатывает за
/// секунду-полторы до контакта, когда сдвинуться вбок ничего не стоит.
///
/// Величина падает с приближением горизонта (`urgency`): дальний сосед двигает
/// слабо, ближний — сильно. Умножается на подвижность, так что пожирающий демон
/// (0) не уклоняется ни от кого.
pub(super) fn anticipate(a: &Pawn, b: &Pawn, lab: &SeparationLab, dt: f32) -> Vec2 {
    let Some((lateral, urgency)) = avoid_direction(a, b, lab) else {
        return Vec2::ZERO;
    };
    lateral * (lab.experiments.anticipation * urgency * a.mobility * dt)
}

/// Правая нормаль к курсу — сторона, в которую пешка обходит. `perp` в bevy —
/// поворот на +90° (влево), поэтому со знаком минус.
fn right_of(heading: Vec2) -> Vec2 {
    -heading.perp()
}

/// В какую сторону обходит ИМЕННО ЭТА пешка: правая нормаль к курсу, а у доли
/// [`SeparationLab::left_share`] пешек — левая.
///
/// Сторона личная и постоянная, а не случайная на прогон: она берётся хэшем
/// [`crate::rng::PawnId`], как ось разведения совпавших позиций
/// ([`coincident_direction`]). Пешка, каждый кадр выбирающая сторону заново, не
/// обходит, а дрожит — и на экране это хуже любой колонны.
pub(super) fn side_of(pawn: &Pawn, left_share: f32) -> Vec2 {
    if left_share > 0.0 && lefty_fraction(pawn.pawn_id) < left_share {
        pawn.heading.perp()
    } else {
        right_of(pawn.heading)
    }
}

/// Место пешки в [0, 1) — тем же хэшем, что и [`coincident_direction`], но со
/// своим множителем: иначе сторона обхода и ось разведения были бы одним и тем
/// же числом, и «левши» получали бы вдобавок одинаковую ось.
fn lefty_fraction(pawn_id: u32) -> f32 {
    hash_fraction(pawn_id.wrapping_mul(2246822519) ^ 0x9e37_79b9)
}

/// Куда и насколько срочно `a` уклоняется от `b`: единичный вектор ПОПЕРЁК
/// курса `a` плюс срочность 0…1 (1 — контакт вот-вот). `None` — уклоняться не
/// от чего. Ядро [`anticipate`], вынесенное отдельно, потому что тем же ответом
/// пользуется руление ([`SeparationSteer`]), а оно не толчок и масштабируется
/// иначе.
pub(super) fn avoid_direction(a: &Pawn, b: &Pawn, lab: &SeparationLab) -> Option<(Vec2, f32)> {
    if a.heading == Vec2::ZERO || a.mobility <= 0.0 || lab.experiments.horizon <= 0.0 {
        return None;
    }
    let rel = b.position - a.position;
    let velocity = a.heading * a.speed - b.heading * b.speed;
    let closing = rel.dot(velocity);
    if closing <= 0.0 {
        return None;
    }
    let speed_squared = velocity.length_squared();
    if speed_squared < 1e-6 {
        return None;
    }
    let time = closing / speed_squared;
    if time > lab.experiments.horizon {
        return None;
    }
    let closest = rel - velocity * time;
    let miss = closest.length();
    let clearance = (a.radius + b.radius) * lab.experiments.anticipate_margin;
    if miss >= clearance {
        return None;
    }
    let side = side_of(a, lab.left_share);
    let away = if miss > 1e-3 { -closest / miss } else { side };
    let biased = away + side * lab.experiments.lane_bias;
    let lateral = biased - a.heading * biased.dot(a.heading);
    let lateral = lateral.normalize_or_zero();
    if lateral == Vec2::ZERO {
        return None;
    }
    Some((lateral, 1.0 - time / lab.experiments.horizon))
}
