/// от кузова остаётся силуэт со скруглениями (стекло там уже меньше
/// пикселя); дальше — габаритный прямоугольник, самый дешёвый по вершинам.
pub const CAR_DETAIL_MAX_ZOOM: f32 = 0.18;
pub const CAR_SILHOUETTE_MAX_ZOOM: f32 = 0.4;

