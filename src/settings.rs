pub const Z_GROUND: f32 = 0.0;
pub const Z_PARK: f32 = 0.5;
/// Лес, луга и песок лежат внутри парковых полигонов — поверх заливки парка.
pub const Z_WOOD: f32 = 0.55;
/// Зелёная подложка аллеи (`natural=tree_row`) и её кант — свой слой, а не часть
/// леса: её стык/сглаживание/кант переключаются на лету, и лес ради этого
/// пересобирать незачем. Волосок над лесом, чтобы порядок двух одноцветных слоёв
/// не зависел от случая. Кант — прямо под заливкой, как у дорог.
pub const Z_TREE_ROW_BAND_CASING: f32 = 0.56;
pub const Z_TREE_ROW_BAND: f32 = 0.57;
pub const Z_GRASS: f32 = 0.6;
pub const Z_SAND: f32 = 0.7;
pub const Z_POND: f32 = 1.0;
/// Линейные водотоки — волосок над площадной водой: цвет у них общий, и там,
/// где ручей впадает в пруд, порядок двух одноцветных слоёв не должен зависеть
/// от случая. Ниже дорог и мостов, поэтому переход через русло по-прежнему
/// рисуется поверх воды.
pub const Z_WATERWAY: f32 = 1.05;
/// Кант аллеи/улицы — прямо под своей заливкой. Порядок получается верным сам
/// собой: кант улицы (1.9) кроет заливку аллеи (1.5), потому что улица старше
/// аллеи, а заливки (1.5 и 2.0) кроют оба канта — иначе кант резал бы каждый
/// перекрёсток пополам.
pub const Z_ALLEY_CASING: f32 = 1.4;
pub const Z_ALLEY: f32 = 1.5;
pub const Z_ROAD_CASING: f32 = 1.9;
pub const Z_ROAD: f32 = 2.0;
/// Мост (`bridge=yes`) — над обычными дорогами, чтобы эстакада крыла улицу,
/// которую пересекает, но под рельсами: трамвай, идущий по мосту, обязан
/// остаться виден. Бордюр — под настилом, по той же логике, что канты под
/// заливками: настилы всех мостов кроют бордюры всех мостов, и стык двух ways
/// на одном мосту не режется бордюрной полосой.
pub const Z_BRIDGE_CASING: f32 = 2.1;
pub const Z_BRIDGE: f32 = 2.2;
/// Ж/д путь поверх дорог: трамвайные пути в OSM висят на тех же ways, что и
/// улица, и обязаны лежать на ней, а не под ней. Штриховка — отдельным слоем
/// над всеми лентами, иначе компланарная геометрия в одном меше z-файтит и
/// штрих одного пути тонет под лентой соседнего.
pub const Z_RAIL: f32 = 2.4;
pub const Z_RAIL_DASH: f32 = 2.5;
/// Трамвай — свой слой над штриховкой ж/д: на пересечении с веткой линия
/// трамвая лежит сверху, а пересборка по ступени зума (`map/tram.rs`) не
/// трогает меши дорог и тяжёлых рельсов.
pub const Z_TRAM: f32 = 2.6;
pub const Z_CORPSE: f32 = 3.0;
pub const Z_PORTAL: f32 = 4.0;
pub const Z_BUILDING: f32 = 5.0;
/// Насколько z юнита падает на метр к северу (кто ниже — тот ближе).
pub const Y_SORT_FACTOR: f32 = 0.002;
/// Юниты: z = `Z_UNIT_BASE - y * Y_SORT_FACTOR`.
///
/// **Выводится, а не выбирается.** Весь диапазон обязан остаться над зданиями
/// при любом `y ≤ MAP_SIZE.y`, поэтому база — это потолок зданий плюс полная
/// просадка по карте плюс запас. Записанное числом, это уже один раз молча
/// разъехалось: база 10 при просадке 7.4 давала самому северному юниту z 2.6,
/// то есть ниже зданий (5), корпусов (3) и вровень с трамваем — вся северная
/// треть карты ходила под домами, хотя проза рядом с константой обещала
/// обратное. Числу неоткуда было узнать, что карта выросла; выражению — есть.
pub const Z_UNIT_BASE: f32 = Z_BUILDING + MAP_SIZE.y * Y_SORT_FACTOR + 1.0;
pub const Z_TREE: f32 = 20.0;
/// Тени крон — под самими кронами, но выше юнитов (юнит в тени затемняется).
pub const Z_TREE_SHADOW: f32 = 19.0;
/// Дебаг-слой поля хвои — поверх всего: он объясняет именно кроны, значит
/// обязан их накрывать, иначе лес под ним не сопоставить с пятнами шума.
pub const Z_CONIFER_NOISE_OVERLAY: f32 = 21.0;

// Порядок слоёв — один инвариант, разложенный на два десятка отдельных чисел.
// До этих проверок он держался только на прозе в комментариях выше, и один раз
// уже ломался молча: карту сделали больше, и северные юниты ушли под дороги.
// Числа правятся поштучно, а смысл у них общий — пусть его стережёт компилятор.
//
// Проверяется ровно то, что записано прозой рядом с константами; всё
// остальное — свобода, которую отбирать незачем.
const _: () = {
    // площадные заливки: земля → парк → лес → трава → песок → вода
    assert!(Z_GROUND < Z_PARK);
    assert!(Z_PARK < Z_WOOD);
    assert!(Z_WOOD < Z_TREE_ROW_BAND_CASING);
    assert!(Z_TREE_ROW_BAND_CASING < Z_TREE_ROW_BAND);
    assert!(Z_TREE_ROW_BAND < Z_GRASS);
    assert!(Z_GRASS < Z_SAND);
    assert!(Z_SAND < Z_POND);
    // водоток — волосок над площадной водой, но ниже дорог: переход через
    // русло рисуется поверх воды
    assert!(Z_POND < Z_WATERWAY);
    assert!(Z_WATERWAY < Z_ALLEY_CASING);
    // кант — прямо под своей заливкой, у всех трёх видов лент
    assert!(Z_ALLEY_CASING < Z_ALLEY);
    assert!(Z_ROAD_CASING < Z_ROAD);
    assert!(Z_BRIDGE_CASING < Z_BRIDGE);
    // кант улицы кроет заливку аллеи: улица старше аллеи
    assert!(Z_ALLEY < Z_ROAD_CASING);
    // мост над дорогами, но под рельсами: трамвай по мосту обязан быть виден
    assert!(Z_ROAD < Z_BRIDGE_CASING);
    assert!(Z_BRIDGE < Z_RAIL);
    // штриховка над своей лентой, трамвай — над штриховкой
    assert!(Z_RAIL < Z_RAIL_DASH);
    assert!(Z_RAIL_DASH < Z_TRAM);
    assert!(Z_TRAM < Z_CORPSE);
    assert!(Z_CORPSE < Z_PORTAL);
    assert!(Z_PORTAL < Z_BUILDING);
    // Тот самый инвариант, который прозой не удержался (см. `Z_UNIT_BASE`).
    // Теперь база из него и выводится, так что проверка стережёт уже не её, а
    // будущую правку: сменится `Y_SORT_FACTOR`, `Z_BUILDING` или размер карты —
    // выражение подстроится, а вот потолок сверху проверить всё равно некому.
    assert!(Z_UNIT_BASE - MAP_SIZE.y * Y_SORT_FACTOR > Z_BUILDING);
    // …а самый южный (`y = 0`) — под тенями крон: юнит в тени затемняется
    assert!(Z_UNIT_BASE < Z_TREE_SHADOW);
    assert!(Z_TREE_SHADOW < Z_TREE);
    // дебаг-слой хвои накрывает кроны, которые объясняет
    assert!(Z_TREE < Z_CONIFER_NOISE_OVERLAY);
};

