/// Радиусы «тела» для расталкивания — вдвое больше прежних 0.45/0.9, то есть
/// ЗАМЕТНО больше половины спрайта ([`HUMAN_SIZE`]/[`DEMON_SIZE`]). Так и
/// задумано: на прежнем радиусе дистанция покоя пары (0.9 м) была меньше
/// самого спрайта (1.0 м), и правильно разведённая толпа всё равно рисовалась
/// сплошной мозаикой из наезжающих друг на друга квадратов — «расталкивание не
/// работает» на глаз. Теперь между спрайтами в покое почти корпус зазора
/// (1.8 м против 1.0 м).
///
/// Значение подобрано ползунком `Body radius` на живой толпе — это вопрос вида,
/// а не расчёта, и ручка есть и в панели Human, и в демо-сцене
