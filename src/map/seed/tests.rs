//! Золотые числа посева.
//!
//! Replay-проверки этого репозитория сравнивают прогон с прогоном и оракулом
//! тут не являются: они поймают, что карта стала другой, но не скажут, какой
//! она была. Поэтому пара примитивов, от которых зависит расстановка всего
//! `map/*`, прибита числами — сдвиг ГПСЧ или посева от точки виден сразу и
//! именно здесь.

use super::*;

/// Первые три значения `Lcg::new(42)`. Мультипликатор 48271, модуль 2³¹−1 и
/// деление на него — контракт, а не деталь: их сдвиг пересевает все города.
#[test]
fn the_generator_starts_with_the_same_three_numbers() {
    let mut rng = Lcg::new(42);
    assert_eq!(rng.next_f32(), 0.000_944_073_3);
    assert_eq!(rng.next_f32(), 0.571_362_85);
    assert_eq!(rng.next_f32(), 0.256_809_4);
    // и то же самое в битах — десятичный литерал читается глазом, биты
    // ловят опечатку в нём самом
    let mut rng = Lcg::new(42);
    assert_eq!(rng.next_f32().to_bits(), 0x3a77_7bb0);
    assert_eq!(rng.next_f32().to_bits(), 0x3f12_44d6);
    assert_eq!(rng.next_f32().to_bits(), 0x3e83_7c86);
}

/// Посев от точки — три перемешивающих раунда по сантиметрам.
#[test]
fn a_point_seeds_the_same_number() {
    assert_eq!(seed_from_point(Vec2::new(12.34, 56.78)), 3_087_577_665);
}

/// На верхнем состоянии генератора деление `u32` на `2³¹−1` в `f32`
/// округляется вверх до ровно `1.0` — кламп в [`Lcg::next_f32`] закрывает
/// именно это. До клампа тест красный.
#[test]
fn the_top_state_stays_under_one() {
    // 247 665 088 · 48271 mod 2³¹−1 = 2 147 483 646, наибольшее состояние
    let mut rng = Lcg::new(247_665_088);
    let value = rng.next_f32();
    assert!(value < 1.0, "{value}");
    assert_eq!(value, 1.0 - f32::EPSILON / 2.0);
}

/// А вместе с ним не достаёт до `to` и `range` на коротком диапазоне.
#[test]
fn the_top_state_stays_under_the_range_end() {
    let mut rng = Lcg::new(247_665_088);
    let value = rng.range(0.0, 1.0);
    assert!(value < 1.0, "{value}");
}
