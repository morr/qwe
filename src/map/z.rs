//! Z-лестница карты — один инвариант, разложенный на отдельные отметки:
//! кто кого кроет на любом зуме, от голой земли до дебаг-оверлеев.
//!
//! Константы живут здесь, а не в `settings.rs`, по общему правилу владельца
//! (`CLAUDE.md`): смысл у лестницы один, и это инвариант **карты**, а не
//! число, которое читают два модуля; `settings.rs` остаётся для действительно
//! общих чисел — `MAP_SIZE`, проекция, симуляция. Читателей у отметок много
//! (слои карты, пешки, инспектор), и все ходят сюда: `crate::map::z::Z_*`.
//!
//! Порядок стережёт `const`-блок ассертов внизу файла. До этих проверок
//! инвариант держался только на прозе в доках выше, и один раз уже ломался
//! молча: карту сделали больше, и северные юниты ушли под дороги (см. док
//! `Z_UNIT_BASE`).

