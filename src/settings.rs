/// Радиус агента полигонального меша (панель Polymesh): инфляция препятствий
/// при триангуляции. Минимум ненулевой: по мешу теперь ходят пешки шириной
/// `HUMAN_SIZE`, а нулевой радиус даёт контур точно по нарисованной геометрии,
/// то есть путь впритирку к стене и через щели, в которые пешка не проходит.
/// Потолок — 0.6, а не «сколько влезет»: цель блуждания в четырёх случаях из
/// пяти это вершина контура дома, `find_passable_tile_near` сдвигает её на один
/// тайл (2 м), а меш раздувает тот же контур на радиус агента, — и начиная
/// примерно с 0.7 сдвинутая цель остаётся внутри инфляции, куда снап `locate`
/// уже не дотягивается. Промахи поиска по лестнице слайдера (Тула, 600
/// запросов, `examples/polymesh_miss_audit`): 0.5% на 0.2–0.3, 1.0% на 0.4,
/// 1.7% на 0.6, 2.7% на 0.7, дальше обрыв — 6.7%, 12.3%, 20.7%. Физика говорит
/// то же самое: человек здесь 0.5 м в поперечнике ([`HUMAN_SIZE`] — удвоенный
/// габарит для читаемости), то есть настоящий радиус агента 0.25 м, и 0.6 —
/// уже двукратный запас.
pub const POLYMESH_AGENT_RADIUS_MIN: f32 = 0.2;
pub const POLYMESH_AGENT_RADIUS_MAX: f32 = 0.6;
pub const POLYMESH_AGENT_RADIUS_STEP: f32 = 0.1;

/// Z юнита по его мировой y-координате.
pub fn unit_z(y: f32) -> f32 {
    Z_UNIT_BASE - y * Y_SORT_FACTOR
}
