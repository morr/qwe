//! Одна кривая плавного перехода 0 → 1 для всей карты и силуэтов.

/// Плавный переход 0 → 1 по доле `t` (smoothstep, `t` зажато в 0..1): одна
/// кривая на все переходы разметки и полотна — разводку половин
/// (`map/roads/network/pairs.rs`), кромку слияния (`map/roads/merges.rs`) и
/// раскладку полос на его клине (`map/roads/paint.rs::MergeRamp`), которые
/// обязаны идти друг по другу.
pub(crate) fn smoothstep(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}
