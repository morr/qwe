#!/usr/bin/env bash
# Прогон серии замеров «слоты + расталкивание» на сценарии ВОРОНКА
# (`examples/demos/crowd_demo/`, сценарий 2).
#
#   tools/separation_slots_lab/run.sh <файл-результатов> <подпись> [аргументы демо…]
#
# Базовые аргументы одни на всю серию — меняться от прогона к прогону должно
# ровно то, что меряют. Из вывода демо забирается строка `RESULT`; сцена
# выходит сама по истечении окна, убивать её снаружи не нужно.
set -euo pipefail

cd "$(dirname "$0")/../.."

results=$1
label=$2
shift 2

# зум 0.12: при окне 900 px по вертикали это ±54 м, то есть весь обод воронки
# (радиус 45 м) в кадре с нулевого кадра. За кадром расталкивания нет по
# построению, и стартовавший вне его хвост мерил бы систему там, где её нет.
#
# окно 8 РЕАЛЬНЫХ секунд на 5× — это ~40 виртуальных: пешке от обода до слота
# идти 34–45 м, то есть 12–16 с, и остаток окна показывает, ОСЕЛА ли толпа, а
# не только дошла ли.
base=(--scenario 2 --speed 5 --seconds 8 --zoom 0.12)

echo "=== $label ${*:-}" >&2
line=$(cargo run --quiet --example crowd_demo -- "${base[@]}" --label "$label" "$@" 2>/dev/null \
    | grep '^RESULT' || true)

if [[ -z $line ]]; then
    echo "!!! $label produced no RESULT line" >&2
    exit 1
fi

echo "$line ARGS=${*:-none}" | tee -a "$results"
