/// те же ~7 экранных пикселей, на которых машину уже снимают: порог свой, а не
/// общий с машинами (`map::wagons`), и в 2.5 раза дальше их 0.8.
pub const WAGON_MAX_ZOOM: f32 = 2.0;

/// Шаг и число шагов посадки конца запроса на меш: polyanya пробует сам
/// запрошенный конец, затем окружности радиусом `delta`, `2·delta`, … по
/// `10 · step` точек. Кольца идут `for step in 0..steps`, то есть последнее
/// имеет радиус `delta · (steps − 1)`: итоговый допуск —
/// `POLYMESH_SEARCH_DELTA · (POLYMESH_SEARCH_STEPS − 1)`, 0.75 м, чуть меньше половины навтайла
/// ([`DEFAULT_NAVTILE_SIZE`](crate::grid::DEFAULT_NAVTILE_SIZE)) — той
/// неопределённости, с которой цель приходит из
/// сетки. Цена платится только за конец, оказавшийся вне меша, и только
/// точечными запросами к BVH. Та же арифметика задаёт потолок
/// [`POLYMESH_AGENT_RADIUS_MAX`](crate::navigation::POLYMESH_AGENT_RADIUS_MAX):
/// допуск вытягивает цель, ушедшую внутрь инфляции меньше чем на 0.75 м, и с
/// ростом радиуса они встречаются.
pub const POLYMESH_SEARCH_DELTA: f32 = 0.25;
pub const POLYMESH_SEARCH_STEPS: u32 = 4;

/// Насколько прямоугольник клипа ШИРЕ границы карты. Препятствия обрезаются
/// снаружи от внешней границы триангуляции, а не внутрь: втянутый клип
/// оставлял бы вдоль кромки карты проходимую щель шириной в отступ, и путь
/// обходил бы по ней реку, упирающуюся в границу. Пересечение препятствием
/// внешней границы polyanya переваривает: проходимость треугольника — точечный
/// `contains` центра (внутри exterior и вне колец препятствий), так что
/// треугольники за границей непроходимы сами по себе, а клип лишь не даёт
/// хвостам OSM-геометрии за bbox раздувать триангуляцию
/// (`polyanya::input/triangulation.rs::as_layer`).
pub const POLYMESH_MAP_EDGE_MARGIN: f32 = 10.0;

/// Желаемая сторона чанка полигонального меша. Не жёсткая: если карта такая,
/// что чанков выйдет больше потолка слоёв (`polymesh::MAX_CHUNKS`), сторона
/// растёт, пока не уложится.
///
/// Полигонов во фронте поиска примерно `плотность × длина маршрута × сторона
/// чанка` — линейно по стороне. Но сторона зажата потолком снизу, и на нашей
/// карте весь доступный диапазон (295…467 м) меняет фронт всего в 1.6 раза,
/// тогда как любая точка диапазона даёт 18–24× против плоского поиска.
/// Поэтому целимся не в минимум: крупный чанк даёт более широкий коридор,
/// то есть путь ближе к оптимальному, и дешевле обходится при постройке.
///
/// Расходимости на чанках больше нет — её добили в два слоя: геометрию шва
/// (см. `SEAM_QUANTUM` и `seam_points`) и воронку самой polyanya — вершина-угол
/// на цепочке коллинеарных рёбер шва гоняла узлы равной стоимости по кольцу
/// полигонов бесконечно, лечится дедупликацией точных повторов в вендоренном
/// крейте (`vendor/polyanya`, `seen_nodes`). Замер на Туле, 2000 запросов,
/// 140 чанков: 0.7% промахов, среднее 5.3 мс, худший 42 мс, память ровная —
/// против зависания на первом же запросе с 5–140 ГБ до починки. Поэтому
/// иерархия включена по умолчанию: на том же наборе (Тула, 500 запросов,
/// радиус 0.2, `examples/polymesh_bench`) она не только не хуже плоского слоя,
/// а лучше по обоим числам — постройка 0.31 с против 5.72 с (каждый чанк
/// триангулируется от своего маленького набора рёбер), среднее 5.66 мс против
/// 6.18 мс, худший 43 мс против 104 мс, промахи одни и те же. Плоский слой
/// возвращается тумблером `Chunks` в панели (или `QWE_POLYMESH_CHUNK_M` для
/// офлайн-прогонов) — так разводятся «виновата иерархия» и «виновата
/// геометрия».
pub const POLYMESH_CHUNK_TARGET_METERS: f32 = 400.0;

/// Сторона чанка при выключенном тумблере `Chunks`: больше любой карты, то
/// есть один слой и никаких швов. Не `0` и не `Option` в конвейере — «чанк
/// размером с мир» и есть определение плоского меша, и весь код ниже остаётся
/// одним путём.
pub const POLYMESH_FLAT_CHUNK_METERS: f32 = 99_000.0;

// «Чанк размером с мир» обязан быть больше мира: сторона меньше карты молча
// вернула бы швы там, где тумблер `Chunks` обещает один слой.
const _: () = {
    assert!(POLYMESH_FLAT_CHUNK_METERS > MAP_SIZE.x && POLYMESH_FLAT_CHUNK_METERS > MAP_SIZE.y);
};

// Умолчание ползунка обязано лежать внутри его же диапазона, и проверяется это
// ассертом `const _: () = { assert!(..) }` рядом с самим диапазоном.
//
// Ради чего. Пара «умолчание» + «MIN/MAX/STEP» — это одна ручка, разложенная на
// четыре константы, и пока они лежали здесь, их разносило на сотни строк друг
// от друга: умолчание читал свой ресурс, границы — только панель. Связи между
// ними не было никакой, и умолчание вне диапазона обнаружилось бы лишь тем, что
// бегунок при первом же касании прыгает к границе, меняя настройку, которую
// никто не трогал.
//
// Общего блока ассертов здесь больше НЕТ: все диапазоны уехали к своим
// ресурсам и унесли ассерты с собой — у деревьев в `map/trees.rs`, у поля хвои
// рядом с `ConiferNoiseStyle`, у демона в `demon/components.rs`, и так далее.
// Правило, по которому диапазон принадлежит ресурсу, а не этому файлу,
// записано в `CLAUDE.md` и в `CONTEXT.md`. Новый диапазон, заведённый здесь по
// недосмотру, останется без ассерта — это и есть подсказка, что ему тут не
// место.

/// Z юнита по его мировой y-координате.
pub fn unit_z(y: f32) -> f32 {
    Z_UNIT_BASE - y * Y_SORT_FACTOR
}
