// Числа регулятора живут здесь: владелец у них ровно один — этот файл
// (`CLAUDE.md`, «Code Conventions»: число с одним владельцем лежит рядом с
// владельцем). Из `settings.rs` регулятор не берёт ничего.
//
// Порядок объявления — тот же, в котором они лежали в `settings.rs`, и это не
// вкус: `SIM_FRAME_SHARE`, `SIM_FRAME_BUDGET_MS` и `SIM_TICK_DEBT_CAP`
// считаются друг из друга и из `MAX_SIM_SPEED`, так что пересобранный в
// другом порядке блок собрался бы молча и дал другой бюджет кадра.

/// Частота кадров, ради которой существует регулятор скорости. Сама в его
/// формулу не входит: из неё выведена [`SIM_FRAME_SHARE`], а всё остальное
/// считается уже через долю.
///
/// Прежний регулятор был замкнут по этой величине напрямую — сравнивал
/// замеренный fps с ней и подкручивал скорость. Так делать нельзя, и не из-за
/// коэффициентов: **под vsync fps принимает только значения `refresh/n`**
/// (окно создаётся с `PresentMode::AutoVsync`). Пока кадр укладывается в
/// 16.7 мс, замер показывает ровно 60 и о приближении к пределу не сообщает
/// ничего — регулятор узнаёт о перегрузе только после того, как уже перелетел.
/// Отсюда и пила на графике, которую не лечили ни сглаживание, ни полоса
/// гистерезиса.
pub const MIN_SIM_FPS: f32 = 30.0;
/// Сколько кадра отдано всему, что **не** симуляция: отрисовка, UI, ввод,
/// сборка команд, реальные секунды.
///
/// Величина назначенная, а не замеренная, и это осознанно. Замерить её из игры
/// нечем: под vsync длительность кадра округляется вверх до кратной интервалу
/// развёртки, поэтому `кадр − симуляция` содержит ещё и сон и завышено тем
/// сильнее, чем больше у нас запаса. Регулятор, построенный на таком замере,
/// получает ложную обратную связь и сам себя загоняет в предельный цикл между
/// ступенями 60 и 30 — ровно ту пилу, ради которой всё и переделывалось.
pub const SIM_RENDER_BUDGET: f32 = 0.013;
/// Доля кадра, которую регулятор разрешает занять симуляции.
///
/// Это и есть вся его формула. Симуляция забирает `SIM_FRAME_SHARE` от **любого**
/// кадра, поэтому длительность кадра сходится к `остальное / (1 − доля)` —
/// сжатие с коэффициентом меньше единицы, то есть устойчиво при любом раскладе
/// и без обратной связи по fps. Пока не-симуляция укладывается в
/// [`SIM_RENDER_BUDGET`], кадры не опускаются ниже [`MIN_SIM_FPS`]; если не
/// укладывается — это уже вопрос к отрисовке, скоростью симуляции он не
/// решается.
pub const SIM_FRAME_SHARE: f32 = 1.0 - SIM_RENDER_BUDGET * MIN_SIM_FPS;
const _: () = assert!(SIM_FRAME_SHARE > 0.0 && SIM_FRAME_SHARE < 1.0);
/// Жёсткий бюджет симуляции на кадр, мс — та же доля, выраженная в целевом
/// кадре. Регулятор целит скорость так, чтобы прогон в бюджет укладывался,
/// но целит по сглаженному замеру, а всплеск (пачка заявок на путь, встающая
/// в `block_on`) приходит раньше, чем замер о нём узнаёт. На этот случай
/// бюджет охраняется и по факту: [`guard_frame_budget`] обрывает
/// прогон `FixedUpdate`, как только тот выел эти миллисекунды, и переносит
/// оставшиеся тики в долг следующим кадрам ([`TickDebt`]). Кадр
/// из-за симуляции ниже [`MIN_SIM_FPS`] уйти не может больше чем на один тик —
/// всплеск виден как временное отставание `actual`, а не как рывок картинки.
pub const SIM_FRAME_BUDGET_MS: f32 = 1000.0 * SIM_FRAME_SHARE / MIN_SIM_FPS;
/// Потолок долга тиков, накопленного предохранителем кадра, в секундах
/// **виртуального** времени. Долг существует, чтобы всплеск размазался по
/// соседним кадрам, а не потерялся; но мир, не тянущий бюджет даже на
/// минимальной скорости, копил бы его бесконечно и навсегда отставал от
/// виртуальных часов. Всё сверх потолка выбрасывается — та же философия, что
/// у [`MAX_FRAME_DELTA`]: досчитывать безнадёжно отставшее незачем.
pub(crate) const SIM_TICK_DEBT_CAP: f32 = MAX_FRAME_DELTA * MAX_SIM_SPEED;
/// Постоянная экспоненциального сглаживания замеров нагрузки (цены тика), с.
/// Считается по реальному времени, поэтому от частоты кадров не зависит.
pub(crate) const SIM_LOAD_SMOOTHING: f32 = 0.5;
/// Постоянная спада **пиковой** оценки ожидания конвейера, с. Вверх пик
/// прыгает мгновенно, вниз сползает к среднему за это время.
///
/// Потолок по конвейеру держится по пику, а не по среднему, и это размен,
/// выбранный сознательно: всплески ожидания приходят пачками с периодом в
/// единицы секунд, среднее размывает их раньше, чем интегральный ход успевает
/// ответить, и каждый всплеск оставлял свой зуб на графике кадров. По пику
/// скорость стоит ниже — зато с запасом ровно под тот всплеск, который уже
/// случался недавно.
pub const SIM_LOAD_PEAK_DECAY: f32 = 3.0;
/// За сколько реальных секунд регулятор удваивает скорость при разгоне.
///
/// Единственное место, где он ползёт, а не считает: цена тика отстаёт от
/// скорости. Разгон порождает заявки на поиск пути, их цена приходит через
/// секунду-другую, и прыжок сразу в посильную по сегодняшним замерам скорость
/// перелетел бы по завтрашним. Прежний шаг «5 % разрыва за кадр» разгонял с
/// посильных 1.6x до запрошенных 10x за ~0.6 с — вшестеро за то, что машина
/// тянет; отсюда и провалы.
pub const SPEED_CLIMB_DOUBLE_TIME: f32 = 0.75;
/// За сколько реальных секунд потолок по конвейеру поиска пути отрабатывает
/// **весь перебор**: занят вдвое сверх доли — за это время уполовинится, на
/// 10 % сверх — срежется на те же 10 %.
///
/// Не расчёт, а интегральный ход, и это принципиально. Пул поиска — очередь;
/// вблизи насыщения ожидание растёт как `1/(1 − загрузка)`, то есть с
/// неограниченным усилением, и любая формула «посчитать посильную скорость за
/// один шаг» там перелетает. Замер живьём: ожидание ходило 0.9…8.0 мс на шаг с
/// периодом около секунды при совершенно ровной цене по процессору.
///
/// Пропорциональность важна не меньше самого хода. Постоянный шаг («резать
/// вдвое за секунду, пока перебор») режет всё время, пока разгребается
/// очередь, — то есть заведомо перерезает, и заводит собственную пилу:
/// замерено как скорость 1.1…1.8x с периодом около двух секунд.
pub const SPEED_BACKOFF_TIME: f32 = 1.0;
/// То же время на пробу вверх, пока запас есть. Много медленнее отступления:
/// переполненная очередь разгребается, только если перестать в неё лить, а
/// лишняя осторожность стоит лишь секунд разгона.
pub(crate) const SPEED_PROBE_TIME: f32 = 6.0;
/// Мёртвая зона регулятора: расхождение меньше этой доли не трогаем.
///
/// Не косметика: вниз регулятор идёт сразу, вверх — ползёт, так что без
/// мёртвой зоны шум замера храповиком сползал бы вниз.
pub const SPEED_DEADBAND: f32 = 0.02;
/// Самый длинный кадр, который ещё считается честным
/// (`Time<Virtual>::max_delta`), в **реальных** секундах.
///
/// Клампится именно сырая дельта, до умножения на скорость
/// (`bevy_time/src/virt.rs::advance_with_raw_delta`), — то есть к скорости
/// симуляции константа отношения не имеет и потолка ей не задаёт. Её работа
/// одна: фриз (своп, блокирующий вызов, засыпание ноутбука) не должен
/// превратиться в лавину тиков. У `Time<Fixed>` своего предела шагов за кадр
/// нет (`bevy_time/src/fixed.rs::expend` крутится, пока хватает `overstep`),
/// так что эта величина — единственное, что стоит между длинным кадром и
/// `max_delta × скорость × 64` тиками в нём. Кадр длиннее — разница просто
/// теряется, и это правильно: досчитывать час подвешенной игры незачем.
///
/// Обратная сторона: кадр длиннее этой величины **молча** отдаёт симуляции
/// меньше времени, чем прошло, и `actual` уезжает ниже `effective`. Отсюда
/// размен, и 0.25 (дефолт самого Bevy) вместо прежних 0.5: полсекунды на
/// 10x — это до 320 тиков в одном кадре, а длинный кадр несёт больше
/// виртуального времени, значит и следующий будет длиннее. Яма получалась
/// самоподдерживающейся, глубиной ровно в эту константу.
pub const MAX_FRAME_DELTA: f32 = 0.25;

/// Регрессия на молчаливую потерю времени: кадр вчетверо длиннее целевого
/// обязан считаться честно. Иначе просадка отдаёт симуляции меньше времени,
/// чем прошло, и `actual` уезжает ниже `effective`. Ловилось живьём как
/// `effective` 0.46 при `actual` 0.14.
const _: () = assert!(MAX_FRAME_DELTA > 4.0 / MIN_SIM_FPS);
/// Нижняя граница автозамедления: ниже симуляция уже не идёт, а стоит.
pub const MIN_SIM_SPEED: f32 = 0.1;
/// Лесенка скоростей — единый ряд ступеней для кнопки Speed и хоткеев
/// `=`/`-`. Верхняя ступень — сознательный предел проекта, а не свойство
/// железа: выше 30x картинка перестаёт читаться, а `MAX_FRAME_DELTA` от неё
/// производен.
pub(crate) const SPEED_LADDER: [f32; 6] = [1.0, 2.0, 5.0, 10.0, 20.0, 30.0];
/// Жёсткий потолок запрошенной скорости — верх лесенки; выше `requested` не
/// поднять и записью по BRP (срез в `throttle_speed_to_frame_budget`).
pub const MAX_SIM_SPEED: f32 = SPEED_LADDER[SPEED_LADDER.len() - 1];
/// Окно усреднения фактической скорости (виртуальное время / реальное).
/// Копится по реальному времени, а не по кадрам: один кадр в 4 с должен
/// весить как 4 с, иначе просадка теряется в усреднении.
pub(crate) const ACTUAL_SPEED_WINDOW: f32 = 0.5;

/// Скорость симуляции: `requested` крутит пользователь лесенкой, `affordable`
/// насчитал регулятор по замеру нагрузки, `effective` выставляется в
/// `Time<Virtual>` (это `min` первых двух, доведённый ограничителем разгона),
/// `actual` — то, что в итоге получилось (замер виртуального времени против
/// реального).
///
/// Расходятся все пять, и разводить их стоит именно так: `affordable`
/// отвечает на «почему стоим на 4x» замером, а не догадкой, а `effective` —
/// команда регулятора, а не факт. Bevy режет виртуальную дельту кадра по
/// `max_delta`, поэтому фриз или затык (например, пока фоново строится сетка
/// northstar) отнимает у симуляции время помимо регулятора — видно это только
/// в `actual`.
#[derive(Resource, Reflect, Debug)]
#[reflect(Resource)]
pub struct SimSpeed {
    pub requested: f32,
    /// Потолок по конвейеру поиска пути — единственная величина регулятора с
    /// памятью: она не считается заново каждый кадр, а отступает и пробует
    /// (см. [`pipeline_limit`]).
    pub pipeline: f32,
    pub affordable: f32,
    pub effective: f32,
    pub actual: f32,
}

impl Default for SimSpeed {
    fn default() -> Self {
        Self {
            requested: 1.0,
            pipeline: MAX_SIM_SPEED,
            affordable: MAX_SIM_SPEED,
            effective: 1.0,
            actual: 1.0,
        }
    }
}

impl SimSpeed {
    /// Замедлено ли время против запрошенного (с запасом на дребезг замера).
    pub fn is_throttled(&self) -> bool {
        self.actual < self.requested * 0.95
    }
}

/// Часы симуляции: сколько виртуального времени прожил текущий мир.
///
/// Отсчёт идёт от входа в `PlayPhase::Live`, а не от старта приложения:
/// загрузка карты и прогрев проходят в реальном времени и к моменту симуляции
/// отношения не имеют. Смена города перезапускает мир, значит и часы.
///
/// Время виртуальное — стоит на паузе и бежит быстрее на ускорении. Это
/// «сколько прожил мир», а не сколько просидел за ним игрок.
#[derive(Resource, Reflect, Debug, Default)]
#[reflect(Resource)]
pub struct SimClock {
    /// `Time<Virtual>::elapsed` на момент входа в `Live`.
    started_at: f64,
    /// Прошедшее время симуляции, сек.
    pub elapsed: f64,
}

impl SimClock {
    /// Часы нового мира с нуля: за точку отсчёта берём текущее виртуальное
    /// время, а не обнуляем `Time<Virtual>` — тот общий, и его сброс сдвинул бы
    /// всем таймерам их дедлайны.
    pub fn restart(&mut self, now: f64) {
        self.started_at = now;
        self.elapsed = 0.0;
    }
}

/// Замер нагрузки симуляции: во сколько обходится один шаг `FixedUpdate`.
///
/// Цена тика — свойство мира (сколько в нём пешек, насколько они заняты), а
/// **не** скорости: скорость меняет число шагов за кадр, а не стоимость
/// каждого. Именно поэтому по ней можно решать уравнение вперёд, вместо того
/// чтобы искать посильную скорость на ощупь обратной связью по fps.
#[derive(Resource, Reflect, Default, Debug)]
#[reflect(Resource)]
pub struct SimLoad {
    /// Начало прогона `FixedUpdate` в текущем кадре.
    #[reflect(ignore)]
    started: Option<std::time::Instant>,
    /// `SimTick` на начало прогона — разница и есть число шагов за кадр.
    tick_at_start: u64,
    /// Работа и простой этого кадра, которые к **шагу** отношения не имеют:
    /// ожидание в `block_on` над поиском пути и системы, гейтящиеся «не чаще
    /// раза в кадр». Копится по ходу прогона, мс.
    frame_extra_ms: f32,
    /// Длительность прогона `FixedUpdate` в последнем кадре, мс — сырая, без
    /// сглаживания и без деления на шаги. Потребители: [`frame_overrun`] решает
    /// по ней, симуляция ли растянула кадр; репортёр спайков
    /// ([`report_tick_spike`]) — в паре с [`Self::frame_ticks`], дорогой ли
    /// был шаг.
    pub frame_sim_ms: f32,
    /// Число шагов в последнем кадре — вторая половина сырой пары
    /// ([`Self::frame_sim_ms`]): репортёр спайков делит одно на другое.
    pub frame_ticks: u64,
    /// Сглаженная цена одного шага **по процессору**, мс — без покадрового.
    pub tick_ms: f32,
    /// То же покадровое, разнесённое на шаг, мс.
    pub wait_ms: f32,
    /// Пиковое ожидание на шаг, мс: вверх — мгновенно, вниз — спадом за
    /// [`SIM_LOAD_PEAK_DECAY`] к среднему. Потолок по конвейеру держится по
    /// этой величине, а не по [`Self::wait_ms`]: всплески приходят пачками,
    /// среднее размывает их раньше, чем регулятор успевает ответить.
    pub wait_peak_ms: f32,
}

impl SimLoad {
    /// Прибавить время, потраченное в кадре, но не в шаге: простой в
    /// `block_on` над поиском пути (`movement::apply_pathfinding_results`) и
    /// покадровые системы внутри `FixedUpdate` (`movement::separation`).
    ///
    /// Делить такое на число шагов нельзя, и это не мелочь учёта: шагов в кадре
    /// тем больше, чем длиннее кадр, так что покадровая работа, размазанная по
    /// шагам, выглядела бы **дешевеющей** при просадке — регулятор разрешал бы
    /// больше, кадр становился бы длиннее, и так по кругу.
    ///
    /// Вне скобки прогона (`started` пуст) стоимость **выбрасывается**, молча:
    /// без [`SimTimePlugin`] — на стендах, в `replay_app` и в примерах — порт
    /// зовут штатно, а закрыть скобку там некому, так что предупреждение
    /// стреляло бы в каждом тесте детерминизма. Копить же нельзя: `observe`
    /// забирает накопленное целиком, и стоимость кадра, которого регулятор не
    /// мерил, уехала бы в следующий замер — а без замеров вовсе
    /// `frame_extra_ms` рос бы неограниченно.
    pub fn add_frame_cost(&mut self, spent: std::time::Duration) {
        if self.started.is_none() {
            return;
        }
        self.frame_extra_ms += spent.as_secs_f32() * 1000.0;
    }

    /// Учесть кадр: `sim_ms` — время его прогона `FixedUpdate`, `ticks` —
    /// сколько шагов в нём прошло, `dt` — реальная длительность кадра
    /// (она же шаг сглаживания).
    ///
    /// Ожидание вычитается, и это не мелочь учёта. Цена по процессору —
    /// свойство мира и от скорости не зависит; ожидание зависит от неё прямо:
    /// срок ответа отмерен в **тиках** (`PATHFINDING_RETIRE_TICKS`), так что
    /// чем быстрее идут тики, тем меньше у пула реального времени на ту же
    /// работу и тем дольше главный поток стоит. Смешать их в одно число —
    /// значит замкнуть регулятор на величину, которой он сам управляет: замер
    /// живьём показал ход цены тика 2.9…7.6 мс с периодом 2–4 с и скорость,
    /// ходившую за ним 1.3…3.4x.
    fn observe(&mut self, sim_ms: f32, ticks: u64, dt: f32) {
        let wait_ms = std::mem::take(&mut self.frame_extra_ms);
        if ticks == 0 {
            return;
        }
        let cpu = (sim_ms - wait_ms).max(0.0) / ticks as f32;
        let wait = wait_ms / ticks as f32;
        // первый замер кладётся целиком, а не подмешивается к нулю: ноль
        // означает «нагрузка неизвестна», а неизвестная нагрузка снимает
        // ограничение со скорости — пока фильтр полз бы от нуля, регулятор
        // успевал бы разогнаться мимо посильного и словить провал сразу после
        if self.tick_ms <= 0.0 {
            self.tick_ms = cpu;
            self.wait_ms = wait;
            self.wait_peak_ms = wait;
            return;
        }
        // сглаживание по реальному времени, а не по кадрам: иначе постоянная
        // фильтра меняется вместе с частотой кадров — то есть ровно тогда,
        // когда регулятор нужен больше всего
        let alpha = 1.0 - (-dt / SIM_LOAD_SMOOTHING).exp();
        self.tick_ms += (cpu - self.tick_ms) * alpha;
        self.wait_ms += (wait - self.wait_ms) * alpha;
        // пик несимметричен нарочно: сырой замер поднимает его без сглаживания,
        // а спадает он к среднему за свою, много более длинную постоянную
        let decay = 1.0 - (-dt / SIM_LOAD_PEAK_DECAY).exp();
        self.wait_peak_ms =
            (self.wait_peak_ms + (self.wait_ms - self.wait_peak_ms) * decay).max(wait);
    }
}

/// Долг тиков предохранителя кадра: виртуальное время, снятое с накопителя
/// `Time<Fixed>` посреди прогона, чтобы кадр не ушёл за бюджет
/// ([`SIM_FRAME_BUDGET_MS`]). Возвращается в накопитель в начале следующего
/// кадра — тики не теряются, а переезжают; логика мира этого не видит,
/// раскладка тиков по кадрам и так плавает вместе с длиной кадра.
///
/// `deferred` — счётчик всего перенесённого за сессию, только для телеметрии:
/// живой проверке нужно видеть, что предохранитель вообще срабатывает.
#[derive(Resource, Reflect, Default, Debug)]
#[reflect(Resource)]
pub struct TickDebt {
    owed: f32,
    pub deferred: f64,
}

pub struct SimTimePlugin;

/// Стена интервала между граничными пробами тика: разрез спайка по срезам
/// цепочки `FixedUpdate`. Пробы не несут команд и ничего не читают — только
/// копят секунды между своими прогонами; `end_sim_load` на спайке печатает
/// накопленное и гасит (`begin_sim_load` сбрасывает на каждом кадре).
#[derive(Resource, Default)]
pub struct TickSegments {
    since: Option<std::time::Instant>,
    pub parts: Vec<(&'static str, f32)>,
}

impl TickSegments {
    fn reset(&mut self) {
        self.since = None;
        self.parts.clear();
    }
}

/// Граница разреза: фиксирует стену от предыдущей пробы до себя.
pub(crate) fn tick_probe(name: &'static str) -> impl FnMut(ResMut<TickSegments>) {
    move |mut segments: ResMut<TickSegments>| {
        let now = std::time::Instant::now();
        if let Some(since) = segments.since {
            segments
                .parts
                .push((name, (now - since).as_secs_f32() * 1000.0));
        }
        segments.since = Some(now);
    }
}

impl Plugin for SimTimePlugin {
    fn build(&self, app: &mut App) {
        app.register_type::<SimSpeed>()
            .register_type::<SimClock>()
            .register_type::<SimLoad>()
            .register_type::<TickDebt>()
            .init_resource::<SimSpeed>()
            .init_resource::<SimClock>()
            .init_resource::<SimLoad>()
            .init_resource::<TickDebt>()
            .init_resource::<TickSegments>()
            // порог тик-спайка читается из окружения один раз при сборке;
            // дальше он ресурс — виден и правится по BRP на живом прогоне
            .insert_resource(TickSpikeThreshold(
                std::env::var("QWE_PERF_FRAME_SPIKES")
                    .ok()
                    .and_then(|ms| ms.parse().ok())
                    .unwrap_or(0.0),
            ))
            .register_type::<TickSpikeThreshold>()
            .add_systems(
                RunFixedMainLoop,
                (
                    begin_sim_load.in_set(RunFixedMainLoopSystems::BeforeFixedMainLoop),
                    end_sim_load.in_set(RunFixedMainLoopSystems::AfterFixedMainLoop),
                    report_tick_spike
                        .in_set(RunFixedMainLoopSystems::AfterFixedMainLoop)
                        .after(end_sim_load),
                ),
            )
            // предохранитель — стадия `Guard`, первая в перечне тика: решение
            // «оборвать прогон» принимается до того, как очередной тик начнёт
            // тратить время
            .add_systems(FixedUpdate, guard_frame_budget.in_set(TickStage::Guard))
            .add_systems(Startup, pin_max_delta)
            .add_systems(Last, archetype_census)
            // новый прогон — часы и долг тиков с нуля (и по R, и по смене
            // города: оба пути триггерят `WorldStarted`)
            .add_observer(on_world_started)
            .add_systems(
                Update,
                (
                    // пробел, `-` и `=` — символы, пока курсор в поле ввода
                    modify_time.run_if(not(crate::ui::typing_in_text_input)),
                    throttle_speed_to_frame_budget,
                    measure_actual_speed,
                    tick_sim_clock.run_if(in_state(PlayPhase::Live)),
                )
                    .chain(),
            );

        // граничные пробы разреза тика — циклом по перечню стадий: проба после
        // стадии мерит её сегмент, «head» — всё до первой. Рёбра к соседним
        // стадиям обязательны: без них исполнитель вправо перемешать пробу
        // с системами стадии, и сегмент замерил бы чужое
        app.add_systems(FixedUpdate, tick_probe("head").before(TickStage::Guard));
        for pair in TickStage::ORDER.windows(2) {
            app.add_systems(
                FixedUpdate,
                tick_probe(pair[0].probe_name())
                    .after(pair[0])
                    .before(pair[1]),
            );
        }
        if let Some(&tail) = TickStage::ORDER.last() {
            app.add_systems(FixedUpdate, tick_probe(tail.probe_name()).after(tail));
        }
    }
}

/// Самый длинный честный кадр — константа, и от скорости симуляции она не
/// зависит (см. [`MAX_FRAME_DELTA`]). Прибита явно, чтобы молчаливая смена
/// дефолта Bevy не поменяла поведение на фризах.
fn pin_max_delta(mut time: ResMut<Time<Virtual>>) {
    time.set_max_delta(std::time::Duration::from_secs_f32(MAX_FRAME_DELTA));
}

/// Перепись архетипов раз в 5 секунд: волны вставок/снятий компонент рождает
/// новые сочетания, и exploded-число архетипов объяснило бы и дорогие
/// `Changed`-сканы, и дорогие применения команд. Раз в 5 с — чтобы строка
/// в логе ложилась рядом со спайками по таймстампу, а не сыпалась.
fn archetype_census(world: &mut World) {
    #[derive(Resource, Default)]
    struct NextCensus(f32);
    let Some(time) = world.get_resource::<Time<Virtual>>() else {
        return;
    };
    let elapsed = time.elapsed_secs();
    let mut next = world.get_resource_or_insert_with(NextCensus::default);
    if elapsed < next.0 {
        return;
    }
    next.0 = elapsed + 5.0;
    info!("archetype census: {} total", world.archetypes().len());
}

/// Новый прогон начинается с чистых часов и чистого регулятора.
///
/// Долг тиков принадлежит прошлому миру: вливать его тики в свежепостроенный —
/// значит начать новый мир рывком. Замер нагрузки и бэкофф конвейера — тоже
/// его: после смены города унаследованный потолок насчитан вовсе про другой
/// мир, и новый стартовал бы придушенным без единого своего замера. Взять
/// старт слишком высоко ничем не грозит — вниз регулятор ходит мгновенно, а
/// кадр держит предохранитель бюджета ([`guard_frame_budget`]).
fn on_world_started(
    _event: On<WorldStarted>,
    mut clock: ResMut<SimClock>,
    mut debt: ResMut<TickDebt>,
    mut speed: ResMut<SimSpeed>,
    mut load: ResMut<SimLoad>,
    mut time: ResMut<Time<Virtual>>,
) {
    clock.restart(time.elapsed_secs_f64());
    debt.owed = 0.0;
    *load = SimLoad::default();
    speed.pipeline = MAX_SIM_SPEED;
    speed.affordable = MAX_SIM_SPEED;
    speed.requested = sane_requested(speed.requested);
    speed.effective = speed.requested;
    time.set_relative_speed(speed.effective);
}

/// На паузе виртуальная дельта нулевая, поэтому часы сами стоят.
fn tick_sim_clock(mut clock: ResMut<SimClock>, time: Res<Time<Virtual>>) {
    clock.elapsed = time.elapsed_secs_f64() - clock.started_at;
}

fn modify_time(
    mut time: ResMut<Time<Virtual>>,
    mut speed: ResMut<SimSpeed>,
    keys: Res<ButtonInput<KeyCode>>,
) {
    if keys.just_pressed(KeyCode::Space) {
        toggle_pause(&mut time);
    }
    if keys.just_pressed(KeyCode::Equal) {
        speed.requested = next_time_scale(speed.requested);
    }
    if keys.just_pressed(KeyCode::Minus) {
        speed.requested = previous_time_scale(speed.requested);
    }
}

pub fn toggle_pause(time: &mut Time<Virtual>) {
    if time.is_paused() {
        time.unpause();
    } else {
        time.pause();
    }
}

/// Ступень для кнопки Speed: та же лесенка, но по кругу — с верхней ступени
/// возвращаемся к 1x. Кнопка одна, и без замыкания сверху было бы не
/// выбраться иначе как хоткеем.
pub fn cycle_time_scale(speed: f32) -> f32 {
    if speed >= MAX_SIM_SPEED {
        1.0
    } else {
        next_time_scale(speed)
    }
}

/// Следующая ступень лесенки: первая строго выше текущей скорости, с верхней
/// ступени — остаёмся на ней. Произвольное значение (по BRP `requested` пишут
/// любым) прижимается к ближайшей ступени сверху.
pub fn next_time_scale(speed: f32) -> f32 {
    SPEED_LADDER
        .into_iter()
        .find(|&step| step > speed)
        .unwrap_or(MAX_SIM_SPEED)
}

/// Предыдущая ступень лесенки: последняя строго ниже текущей скорости,
/// с нижней ступени — остаёмся на ней.
pub fn previous_time_scale(speed: f32) -> f32 {
    SPEED_LADDER
        .into_iter()
        .rev()
        .find(|&step| step < speed)
        .unwrap_or(SPEED_LADDER[0])
}

