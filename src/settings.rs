/// Доля перекрытия, разрешаемая за секунду виртуального времени: пара
/// расходится за ~1/8 с сим-времени, «дыхание» толпы, а не щелчок.
pub const SEPARATION_RATE: f32 = 8.0;
/// Насколько сильно встречные обходят друг друга боком, в долях продольной
/// коррекции той же пары (см. `separation::sidestep`). 0 — прежнее поведение,
/// когда лобовая пара умеет только пятиться и потому «слипается»; 1.0 — на
/// строго лобовой встрече толчок уходит под 45°, то есть пешка столько же
/// шагает вбок, сколько назад. Больше единицы — обход становится заметнее
/// расталкивания и выглядит как рывок в сторону.
///
/// Величина — только половина вопроса; вторая половина в том, КОМУ добавка
/// достаётся, и там ручки нет, потому что обе поломки не про силу, а про
/// симметрию: обходят оба — пара вращается вместо того, чтобы разъехаться
/// (`separation::yields`); обходит вся давка сразу — вращается затор целиком
/// (гейт «пара одна» в `separation::resolve_pushes`).
pub const SEPARATION_SIDESTEP: f32 = 1.0;
/// Какая доля толчка ВДОЛЬ курса пешки доживает до применения
/// (`separation::damp_along_heading`). **1.0 — ничего не давим**, и это не
/// «пока не дошли руки», а результат замера.
///
/// Давить продольную часть напрашивается: именно она отбрасывает догоняющего
/// назад по его же пути, и на экране это читается как разворот. Но она же —
/// единственное, чем сходящаяся толпа может РАЗДАТЬСЯ: наружу из давки это
/// всегда «назад по курсу». Замер на сценарии «воронка» (200 пешек в одну
/// точку, перекрывшихся пар / худшее перекрытие):
///
/// | backstep | пар | худшее |
/// |---|---|---|
/// | 0.0 | 630…2251 | 1.79 м |
/// | 0.3 | 223…456 | 1.39 м |
/// | 0.6 | 154…281 | 1.38 м |
/// | 1.0 | 100…204 | 0.92 м |
///
/// Монотонно: чем сильнее давим, тем хуже. Разворот догоняющего лечится не
/// здесь, а долями коррекции (`separation::shares`) — уступает и отходит тот,
/// кто догнал, а переднего не толкают вовсе. Ручка оставлена, чтобы это можно
/// было перепроверить ползунком, а не пересборкой.
pub const SEPARATION_BACKSTEP: f32 = 1.0;
/// Какая доля шага ходьбы остаётся у придержанной пешки — той, чей курс на
/// последнем прогоне расталкивания упирался в перекрытого соседа, СТОЯЩЕГО или
/// ВСТРЕЧНОГО (`separation::SeparationHolds`; попутных и поперечных придержка
/// не касается — см. док ресурса).
///
/// Ручка мощности упора «ходьба против расталкивания». Пока обе стороны в
/// полную силу, пара встаёт на равновесии
/// `скорость / (SEPARATION_RATE · доля коррекции)` ≈ 0.35 м перекрытия — и
/// висит на нём вечно: пешка «идёт» на месте, дрожа на шаг за кадр. Доля `F`
/// опускает равновесие до `F ·` того же, то есть при 0.2 — до ~0.07 м,
/// которых на экране не видно. Ноль не берётся намеренно: полный стоп
/// превращает плотный перекрёсток в стоп-кадры — толпа перестаёт течь и
/// движется рывками от прогона к прогону.
/// **1.0 — придержки нет, и это результат замера, а не недосмотр.** Придержка
/// существовала ровно затем, чтобы упёршаяся пешка перестала давить в чужое
/// тело; ту же задачу лучше решает руление ([`SEPARATION_STEER`]) — оно уводит
/// её вбок вместо того, чтобы тормозить. На стенде
/// (`tools/crowd_tuning_lab/REPORT.md`) любая доля меньше единицы роняет
/// сходимость: при 0.4 на воронке доходят 156 пешек из 200, а на встречном
/// потоке медианный прогресс падает со 174 до 26 м.
///
/// Остаётся у придержки одна роль, и она не про скорость: придержанный в
/// пределах дистанции покоя от цели засчитывается дошедшим
/// (`movement::systems::move_moving_entities`) — иначе он толкался бы с тем, кто
/// занял его место, до скончания века.
pub const SEPARATION_HOLD: f32 = 1.0;
/// Потолок СКОРОСТИ расталкивания, м/с (`SeparationLab::max_speed`).
///
/// Толчок пары равен `перекрытие × SEPARATION_RATE`: при перекрытии 0.9 м это
/// 7.2 м/с, то есть в два с половиной раза быстрее ходьбы — расталкивание не
/// поправляет ходьбу, а перебивает её. `SEPARATION_MAX_STEP` от этого не
/// спасает: 0.3 м на прогон при 60 fps — это 18 м/с, потолком он не работает
/// практически никогда.
pub const SEPARATION_MAX_SPEED: f32 = 1.4;
/// Сила РУЛЕНИЯ: насколько курс ходьбы отклоняется вбок от того, кто встал на
/// дороге (`SeparationLab::steer`, `movement::SeparationSteer`).
///
/// Толчок двигает ПОЗИЦИЮ, а ходьба тут же везёт пешку обратно к цели — две
/// силы работают друг против друга, и весь результат уходит в намотанный путь.
/// Руление меняет НАПРАВЛЕНИЕ той же ходьбы: пешка обходит по дуге, не теряя
/// скорости. Без него симметричный встречный поток не расходится в принципе.
pub const SEPARATION_STEER: f32 = 1.0;
/// Во сколько раз ужимается дистанция покоя в паре «ИДУЩАЯ + СТОЯЩАЯ»
/// (`SeparationLab::pass_squeeze`). Пара «оба стоят» и пара «оба идут» держат
/// полную — сжимается ПРОХОД сквозь толпу, а не сама толпа.
///
/// Ради чего. Шаг решётки слотов — 2.0 м, а идущей пешке между двумя осевшими
/// нужен просвет `2 ×` дистанции покоя = 3.6 м: внутренние слоты недостижимы в
/// принципе. При 0.6 просвет становится 2.16 м, то есть решётка проходима, а
/// осевшая толпа и встречный поток по-прежнему держат полные 1.8 м.
pub const SEPARATION_PASS_SQUEEZE: f32 = 0.6;
/// Доля пешек, обходящих препятствие ВЛЕВО (`SeparationLab::left_share`).
/// Сторона личная и постоянная — хэш `PawnId`.
///
/// Одинаковая сторона у всех — источник двух картинок, которых в жизни не
/// бывает: попутный поток складывается в сплошную колонну, а недошедшие вокруг
/// плотной толпы едут одной каруселью. На стенде пятая часть левшей — лучший
/// результат по времени в расталкивании (0.61 против 0.75) и единственное, что
/// реально разбивает колонну (разброс 2.94 против 2.55).
pub const SEPARATION_LEFT_SHARE: f32 = 0.2;
/// Кламп сдвига одной пешки за прогон, м: давка у портала растекается за
/// несколько кадров, а не разлетается телепортом; треть человека за кадр на
/// глаз — плавный разъезд.
pub const SEPARATION_MAX_STEP: f32 = 0.3;
/// НИЖНЯЯ ГРАНИЦА ячейки одноразовой мелкой сетки соседей, м. Настоящий
/// размер считает `SeparationStyle::cell()` от текущего радиуса: ячейка обязана
/// быть не меньше максимальной суммы радиусов (демон+демон), иначе
/// перекрывшаяся пара может не попасть в общие 3 × 3 ячейки и её просто не
/// найдут. Константой это быть перестало, когда радиус стал ручкой.
pub const SEPARATION_CELL: f32 = 2.4;

/// Докуда ищется свободный слот назначения, м (`movement::destination`).
///
/// Радиус кольцевого поиска, а не число слотов: при `NavtileBase::M1` и при
/// сдвинутом ползунке радиуса шаг решётки слотов меняется, а физический охват
/// поиска обязан остаться прежним. 16 м — это 17 × 17 слотов на дефолтном шаге
/// 2 м, то есть 289 мест: с запасом на 200 пешек «воронки» из демо и на любую
/// давку у портала. Дальше искать незачем: цель, уехавшая от задуманной больше
/// чем на 16 м, — это уже не та цель, которую выбирало поведение.
pub const CLAIM_SEARCH_METERS: f32 = 16.0;

/// На сколько метров осевшую пешку должно оттолкнуть от её слота, чтобы она
/// пошла обратно (`movement::SlotLab::regroup`).
///
/// Дошедшую пешку толкают проходящие мимо, и вернуться ей нечем: маршрут
/// исчерпан. Дальше возмущение расходится по толпе — сошедшая перекрывается с
/// соседкой, та отъезжает, и так до края. На стенде возврат — единственное, что
/// доводит первый критерий до конца: 200 пешек из 200 стоят на СВОИХ слотах при
/// плотной решётке 2 м, тогда как без него их 54.
///
/// Метр — половина шага решётки: меньше, и пешка дёргается от каждого касания;
/// больше, и она остаётся стоять почти в соседнем слоте.
pub const SLOT_REGROUP_METERS: f32 = 1.0;

/// Границы ползунков групп толпы панели Navigation для механизмов, которые
/// замер вывел в дефолты (`tools/crowd_tuning_lab/REPORT.md`). Ползунки, а не
/// константы, по той же причине, что у радиуса тела: правильное значение у
/// каждого — это компромисс, и проверяется он глазом на живой толпе.
///
/// У протискивания снизу не ноль: при нём идущая проходит сквозь стоящую
/// насквозь. 1.0 — «не ужимается вовсе», то есть поведение до этого замера.
pub const SEPARATION_PASS_SQUEEZE_MIN: f32 = 0.3;
pub const SEPARATION_PASS_SQUEEZE_MAX: f32 = 1.0;
pub const SEPARATION_PASS_SQUEEZE_STEP: f32 = 0.05;
/// Половина — это уже не «немного левшей», а вторая такая же толпа навстречу
/// первой; выше ставить незачем, ниже нуля не бывает.
pub const SEPARATION_LEFT_SHARE_MIN: f32 = 0.0;
pub const SEPARATION_LEFT_SHARE_MAX: f32 = 0.5;
pub const SEPARATION_LEFT_SHARE_STEP: f32 = 0.05;

// --- Скорость симуляции ---
/// Частота кадров, ради которой существует регулятор скорости. Сама в его
/// формулу не входит: из неё выведена [`SIM_FRAME_SHARE`], а всё остальное
/// считается уже через долю.
///
/// Прежний регулятор был замкнут по этой величине напрямую — сравнивал
/// замеренный fps с ней и подкручивал скорость. Так делать нельзя, и не из-за
/// коэффициентов: **под vsync fps принимает только значения `refresh/n`**
/// (окно создаётся с `PresentMode::AutoVsync`). Пока кадр укладывается в
/// 16.7 мс, замер показывает ровно 60 и о приближении к пределу не сообщает
/// ничего — регулятор узнаёт о перегрузе только после того, как уже перелетел.
/// Отсюда и пила на графике, которую не лечили ни сглаживание, ни полоса
/// гистерезиса.
pub const MIN_SIM_FPS: f32 = 30.0;
/// Сколько кадра отдано всему, что **не** симуляция: отрисовка, UI, ввод,
/// сборка команд, реальные секунды.
///
/// Величина назначенная, а не замеренная, и это осознанно. Замерить её из игры
/// нечем: под vsync длительность кадра округляется вверх до кратной интервалу
/// развёртки, поэтому `кадр − симуляция` содержит ещё и сон и завышено тем
/// сильнее, чем больше у нас запаса. Регулятор, построенный на таком замере,
/// получает ложную обратную связь и сам себя загоняет в предельный цикл между
/// ступенями 60 и 30 — ровно ту пилу, ради которой всё и переделывалось.
pub const SIM_RENDER_BUDGET: f32 = 0.013;
/// Доля кадра, которую регулятор разрешает занять симуляции.
///
/// Это и есть вся его формула. Симуляция забирает `SIM_FRAME_SHARE` от **любого**
/// кадра, поэтому длительность кадра сходится к `остальное / (1 − доля)` —
/// сжатие с коэффициентом меньше единицы, то есть устойчиво при любом раскладе
/// и без обратной связи по fps. Пока не-симуляция укладывается в
/// [`SIM_RENDER_BUDGET`], кадры не опускаются ниже [`MIN_SIM_FPS`]; если не
/// укладывается — это уже вопрос к отрисовке, скоростью симуляции он не
/// решается.
pub const SIM_FRAME_SHARE: f32 = 1.0 - SIM_RENDER_BUDGET * MIN_SIM_FPS;
const _: () = assert!(SIM_FRAME_SHARE > 0.0 && SIM_FRAME_SHARE < 1.0);
/// Жёсткий бюджет симуляции на кадр, мс — та же доля, выраженная в целевом
/// кадре. Регулятор целит скорость так, чтобы прогон в бюджет укладывался,
/// но целит по сглаженному замеру, а всплеск (пачка заявок на путь, встающая
/// в `block_on`) приходит раньше, чем замер о нём узнаёт. На этот случай
/// бюджет охраняется и по факту: `sim_time::guard_frame_budget` обрывает
/// прогон `FixedUpdate`, как только тот выел эти миллисекунды, и переносит
/// оставшиеся тики в долг следующим кадрам ([`sim_time::TickDebt`]). Кадр
/// из-за симуляции ниже [`MIN_SIM_FPS`] уйти не может больше чем на один тик —
/// всплеск виден как временное отставание `actual`, а не как рывок картинки.
pub const SIM_FRAME_BUDGET_MS: f32 = 1000.0 * SIM_FRAME_SHARE / MIN_SIM_FPS;
/// Потолок долга тиков, накопленного предохранителем кадра, в секундах
/// **виртуального** времени. Долг существует, чтобы всплеск размазался по
/// соседним кадрам, а не потерялся; но мир, не тянущий бюджет даже на
/// минимальной скорости, копил бы его бесконечно и навсегда отставал от
/// виртуальных часов. Всё сверх потолка выбрасывается — та же философия, что
/// у [`MAX_FRAME_DELTA`]: досчитывать безнадёжно отставшее незачем.
pub const SIM_TICK_DEBT_CAP: f32 = MAX_FRAME_DELTA * MAX_SIM_SPEED;
/// Постоянная экспоненциального сглаживания замеров нагрузки (цены тика), с.
/// Считается по реальному времени, поэтому от частоты кадров не зависит.
pub const SIM_LOAD_SMOOTHING: f32 = 0.5;
/// Постоянная спада **пиковой** оценки ожидания конвейера, с. Вверх пик
/// прыгает мгновенно, вниз сползает к среднему за это время.
///
/// Потолок по конвейеру держится по пику, а не по среднему, и это размен,
/// выбранный сознательно: всплески ожидания приходят пачками с периодом в
/// единицы секунд, среднее размывает их раньше, чем интегральный ход успевает
/// ответить, и каждый всплеск оставлял свой зуб на графике кадров. По пику
/// скорость стоит ниже — зато с запасом ровно под тот всплеск, который уже
/// случался недавно.
pub const SIM_LOAD_PEAK_DECAY: f32 = 3.0;
/// За сколько реальных секунд регулятор удваивает скорость при разгоне.
///
/// Единственное место, где он ползёт, а не считает: цена тика отстаёт от
/// скорости. Разгон порождает заявки на поиск пути, их цена приходит через
/// секунду-другую, и прыжок сразу в посильную по сегодняшним замерам скорость
/// перелетел бы по завтрашним. Прежний шаг «5 % разрыва за кадр» разгонял с
/// посильных 1.6x до запрошенных 10x за ~0.6 с — вшестеро за то, что машина
/// тянет; отсюда и провалы.
pub const SPEED_CLIMB_DOUBLE_TIME: f32 = 0.75;
/// За сколько реальных секунд потолок по конвейеру поиска пути отрабатывает
/// **весь перебор**: занят вдвое сверх доли — за это время уполовинится, на
/// 10 % сверх — срежется на те же 10 %.
///
/// Не расчёт, а интегральный ход, и это принципиально. Пул поиска — очередь;
/// вблизи насыщения ожидание растёт как `1/(1 − загрузка)`, то есть с
/// неограниченным усилением, и любая формула «посчитать посильную скорость за
/// один шаг» там перелетает. Замер живьём: ожидание ходило 0.9…8.0 мс на шаг с
/// периодом около секунды при совершенно ровной цене по процессору.
///
/// Пропорциональность важна не меньше самого хода. Постоянный шаг («резать
/// вдвое за секунду, пока перебор») режет всё время, пока разгребается
/// очередь, — то есть заведомо перерезает, и заводит собственную пилу:
/// замерено как скорость 1.1…1.8x с периодом около двух секунд.
pub const SPEED_BACKOFF_TIME: f32 = 1.0;
/// То же время на пробу вверх, пока запас есть. Много медленнее отступления:
/// переполненная очередь разгребается, только если перестать в неё лить, а
/// лишняя осторожность стоит лишь секунд разгона.
pub const SPEED_PROBE_TIME: f32 = 6.0;
/// Мёртвая зона регулятора: расхождение меньше этой доли не трогаем.
///
/// Не косметика: вниз регулятор идёт сразу, вверх — ползёт, так что без
/// мёртвой зоны шум замера храповиком сползал бы вниз.
pub const SPEED_DEADBAND: f32 = 0.02;
/// Самый длинный кадр, который ещё считается честным
/// (`Time<Virtual>::max_delta`), в **реальных** секундах.
///
/// Клампится именно сырая дельта, до умножения на скорость
/// (`bevy_time/src/virt.rs::advance_with_raw_delta`), — то есть к скорости
/// симуляции константа отношения не имеет и потолка ей не задаёт. Её работа
/// одна: фриз (своп, блокирующий вызов, засыпание ноутбука) не должен
/// превратиться в лавину тиков. У `Time<Fixed>` своего предела шагов за кадр
/// нет (`bevy_time/src/fixed.rs::expend` крутится, пока хватает `overstep`),
/// так что эта величина — единственное, что стоит между длинным кадром и
/// `max_delta × скорость × 64` тиками в нём. Кадр длиннее — разница просто
/// теряется, и это правильно: досчитывать час подвешенной игры незачем.
///
/// Обратная сторона: кадр длиннее этой величины **молча** отдаёт симуляции
/// меньше времени, чем прошло, и `actual` уезжает ниже `effective`. Отсюда
/// размен, и 0.25 (дефолт самого Bevy) вместо прежних 0.5: полсекунды на
/// 10x — это до 320 тиков в одном кадре, а длинный кадр несёт больше
/// виртуального времени, значит и следующий будет длиннее. Яма получалась
/// самоподдерживающейся, глубиной ровно в эту константу.
pub const MAX_FRAME_DELTA: f32 = 0.25;

/// Регрессия на молчаливую потерю времени: кадр вчетверо длиннее целевого
/// обязан считаться честно. Иначе просадка отдаёт симуляции меньше времени,
/// чем прошло, и `actual` уезжает ниже `effective`. Ловилось живьём как
/// `effective` 0.46 при `actual` 0.14.
const _: () = assert!(MAX_FRAME_DELTA > 4.0 / MIN_SIM_FPS);
/// Нижняя граница автозамедления: ниже симуляция уже не идёт, а стоит.
pub const MIN_SIM_SPEED: f32 = 0.1;
/// Лесенка скоростей — единый ряд ступеней для кнопки Speed и хоткеев
/// `=`/`-`. Верхняя ступень — сознательный предел проекта, а не свойство
/// железа: выше 30x картинка перестаёт читаться, а `MAX_FRAME_DELTA` от неё
/// производен.
pub const SPEED_LADDER: [f32; 6] = [1.0, 2.0, 5.0, 10.0, 20.0, 30.0];
/// Жёсткий потолок запрошенной скорости — верх лесенки; выше `requested` не
/// поднять и записью по BRP (срез в `throttle_speed_to_frame_budget`).
pub const MAX_SIM_SPEED: f32 = SPEED_LADDER[SPEED_LADDER.len() - 1];
/// Зум (мировых метров на логический пиксель), выше которого мирные гуляющие
/// считаются «не на экране» и путь от диспетчера не получают: пешка на таком
/// отдалении — точка, её простой не виден, а «в кадре» иначе означала бы
/// полкарты — все ~17k мирных разом топили бы пул pathfinding-тасков.
/// Демонов и убегающих отсечка не касается (они URGENT при любом зуме).
pub const WANDER_DISPATCH_MAX_ZOOM: f32 = 0.75;

/// Через сколько тиков после подачи заявки её ответ применяется в
/// детерминированном режиме. Задержка фиксирована: заявка с тика `T`
/// приземляется ровно на `T + PATHFINDING_RETIRE_TICKS`, успел поиск
/// посчитаться к этому моменту или нет (не успел — его дожидаются `block_on`).
///
/// Восемь тиков при шаге 1/64 с — это 125 мс реального времени на скорости 1×,
/// то есть примерно та же задержка, что даёт сегодняшний конвейер «заявка →
/// диспетчер → таск → приёмка» (2–3 кадра), — поведение пешек не меняется.
///
/// Пропускной способности эта константа не задаёт: сколько поисков уходит за
/// тик, решают [`PATHFINDING_WANDER_UNITS_PER_TICK`] и
/// [`PATHFINDING_URGENT_UNITS_PER_TICK`]. `K` покупает пачке реальное время до
/// `block_on` — и платит за это устареванием пути: путь, проложенный на тике
/// `T`, выходит из точки, где пешка стояла на `T`, а идти начинает с `T + K`.
///
/// Константа, а не производная от скорости симуляции: `SimSpeed` крутит
/// пользователь, и содержимое повтора не имеет права от неё зависеть. На 30×
/// пачки перестают успевать за реальное время, `block_on` притормаживает
/// кадр, и `throttle_speed_to_frame_budget` сам опускает эффективную
/// скорость — это осознанный размен режима, а не сбой.
pub const PATHFINDING_RETIRE_TICKS: u64 = 8;

/// Возраст pathfinding-таска, после которого приёмник паникует
/// (`listen_for_pathfinding_tasks`): живой поиск отвечает за миллисекунды, а
/// расходящийся падает по собственному бюджету шагов (`polymesh::bounded_path`)
/// — таск, доживший до этого порога, завис каким-то новым способом (лок,
/// дедлок, цикл в бэкенде), и тихое вечное ожидание превращало бы дефект в
/// «пешки замирают, конвейер пуст, CPU занят». Порог щедрый: при насыщенном
/// пуле (постройка northstar на старте — ~11 с всех ядер) здоровый таск может
/// простоять в очереди исполнителя заметные секунды.
pub const PATHFINDING_TASK_HANG_SECS: f32 = 20.0;

/// Сколько навтайлов расстояния стоят одну единицу бюджета диспетчера.
///
/// Бюджет считается не в заявках, а в предсказанной цене поиска, потому что
/// цены расходятся на порядок с лишним: замер на Туле (polymesh, 24 747
/// полигонов) даёт **0.26 мс** на короткую прогулку в 20–40 м и **5.3 мс** на
/// поручение через город. Числа, которого хватает, чтобы пропустить залп из
/// 20 000 коротких прогулок за пару секунд, хватило бы и на 20 000 поручений —
/// а это 85 с процессорного времени, то есть ровно та яма, из-за которой
/// бюджет и вводится.
///
/// Цена заявки — `1 + расстояние_в_тайлах / PATHFINDING_UNIT_TILES` по
/// Чебышёву между `start_tile` и `end_tile`. Расстояние целое, метрика
/// целочисленная: сумма float зависела бы от порядка обхода. При 64 (128 м на
/// навтайле M2) прогулка стоит 1 единицу, поручение через город — около 20,
/// то есть отношение цен то же, что у измеренных 0.26 и 5.3 мс.
pub const PATHFINDING_UNIT_TILES: i32 = 64;

/// Темп выдачи мирных заявок, единиц цены за тик (см.
/// [`PATHFINDING_UNIT_TILES`]).
///
/// Выводится из того, сколько пул успевает сжевать, а не из того, как быстро
/// хочется опустошить очередь:
///
/// ```text
/// потоки × шаг тика × доля пула / цена = бюджет
/// 5      × 15.625 мс × 0.45        / 0.26 мс ≈ 128 коротких заявок
/// 5      × 15.625 мс × 0.45        / 5.3 мс  ≈ 6.4 поручения
/// ```
///
/// Потоков именно 5, а не 8: `main.rs` переопределяет политику пула
/// (`percent: 0.5`), и на десяти логических ядрах `AsyncCompute` получает
/// половину. Оба случая по построению упираются в одни и те же ~35 мс
/// процессорного времени на тик — это и есть смысл единицы цены.
///
/// Темп **за тик**, а не за реальную секунду: тик — часы симуляции, и от
/// `SimSpeed` содержимое повтора зависеть не имеет права. Следствие честное:
/// на 30× тиков в тридцать раз больше, машина столько не считает, и
/// `throttle_speed_to_frame_budget` опускает эффективную скорость.
///
/// Длинная очередь при таком темпе — штатное состояние, а не затор: залп из
/// 16 000 поручений расходится за ~2500 тиков (39 виртуальных секунд). Это не
/// цена бюджета, а физика — те же 16 000 поисков стоят 85 с процессорного
/// времени, то есть 17 с на пяти потоках, как их ни раскладывай.
pub const PATHFINDING_WANDER_UNITS_PER_TICK: u32 = 128;

/// Темп выдачи срочных заявок (демоны и убегающие), единиц цены за тик.
///
/// Отдельный счётчик, а не общий с мирными: приоритета мало. Общий бюджет
/// голодал бы в обе стороны — толпа демонов у портала останавливала бы город,
/// а очередь города задерживала бы панику. Два счётчика делают невозможным и
/// то и другое.
///
/// Запас против спроса трёхкратный: 385 демонов с перепрокладкой раз в 0.4 с
/// дают ~15 заявок на тик, убегающие с периодом 0.7–1.2 с — ещё несколько.
/// Поиски у обоих короткие (погоня и бегство — на десятки метров), поэтому
/// почти каждая заявка стоит одну единицу.
pub const PATHFINDING_URGENT_UNITS_PER_TICK: u32 = 64;
/// Окно усреднения фактической скорости (виртуальное время / реальное).
/// Копится по реальному времени, а не по кадрам: один кадр в 4 с должен
/// весить как 4 с, иначе просадка теряется в усреднении.
pub const ACTUAL_SPEED_WINDOW: f32 = 0.5;

