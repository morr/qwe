//! Двор симуляции — сборка мира для стендов поведения.
//!
//! Стенд лестницы вида (`human::behavior`, `demon::behavior`) поднимает `App`
//! не ради расписания, а ради четырёх вещей, без которых система не пройдёт
//! валидацию параметров: снимка бэкенда, сетки под ним, стора диагностик и
//! часов. Собиралось это в обоих модулях порознь и совпадало на восемь строк
//! из тринадцати; расходились они только тем, чья пространственная сетка нужна
//! и какой ресурс стиля читает система.
//!
//! Сборка чего-то большего сюда не поедет намеренно. Настоящий двор прогона —
//! [`determinism::replay::replay_app`](crate::determinism::replay::replay_app):
//! он собирает плагины, и **список исключённых плагинов записан там же**,
//! потому что именно он очерчивает, что видит страж сбросов
//! `tests/determinism.rs::a_restart_replays_the_run`. Два двора — не дубль:
//! этот отвечает на «сработала ли ступень лестницы», тот — на «повторяется ли
//! прогон целиком».

use std::sync::{Arc, RwLock};

use bevy::prelude::*;

use crate::navigation::{ArcNavmesh, Backend, Navmesh};

/// Пустой проходимый мир: ни меша, ни иерархии, ни препятствий.
///
/// `Backend` и [`ArcNavmesh`] держат **один и тот же** `Arc`, как и в игре:
/// правка сетки через `ArcNavmesh` видна снимку сразу, и стенд может ставить
/// стены после сборки.
pub fn behavior_yard() -> App {
    let mut app = App::new();
    let navmesh = Arc::new(RwLock::new(Navmesh::default()));
    app.insert_resource(Backend::from_grid(navmesh.clone()))
        .insert_resource(ArcNavmesh(navmesh))
        // системы поведения пишут диагностику; без стора их параметры не
        // валидируются, и система молча не выполняется — то есть стенд
        // проверяет неподвижный мир и проходит
        .init_resource::<bevy::diagnostic::DiagnosticsStore>()
        .init_resource::<Time>();
    app
}
