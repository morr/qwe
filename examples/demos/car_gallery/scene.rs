/// Центр клетки по её номеру: сетка идёт слева направо и сверху вниз.
pub(crate) fn centre(index: usize) -> Vec2 {
    Vec2::new(
        (index % COLUMNS) as f32 * CELL_PITCH.x,
        -((index / COLUMNS) as f32) * CELL_PITCH.y,
    )
}
