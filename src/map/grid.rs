//! Равномерная сетка-индекс: «что лежит рядом с этой точкой» за один взгляд в
//! `HashMap` вместо прохода по всему городу.
//!
//! Таких индексов на карте полтора десятка — двери, посадка деревьев,
//! водоёмы, стыки дорог, вагоны, гаражи, тени домов, кварталы для машин,
//! ленты мостов. Арифметика у всех одна, и до этого модуля она была написана
//! заново в каждом: двойной цикл «положить во все задетые ячейки» существовал
//! в семи копиях, ключ был то `(i32, i32)`, то `IVec2`, а шаг ячейки ездил
//! отдельным аргументом на каждый вызов — так что вставка и запрос могли
//! разойтись размером ячейки, и никто бы этого не заметил.
//!
//! Здесь шаг принадлежит сетке. Разойтись паре «положил / спросил» больше
//! негде, а размер ячейки остаётся решением потребителя — он аргумент
//! конструктора, а не константа модуля: у дверей это 60 м по дорогам и 30 по
//! контурам домов, у теней 48, у кварталов 120, и эти числа про предметную
//! область, а не про сетку.
//!
//! **Чего здесь нет.** Сетка пешеходов (`spatial.rs`) устроена иначе и сюда не
//! переезжает: у неё плотный `Vec` на всю карту, обратный индекс
//! «сущность → ячейка» и переезд по одной сущности каждый тик, а не сборка
//! один раз на загрузку. Общее у них только слово «сетка».
//!
//! И это **не `crate::grid`**, с которым модуль делит имя: тот про
//! навигационные тайлы — две функции пересчёта «метры ↔ тайл» с одним на всю
//! карту шагом `navtile_size()`, и никакого индекса значений в нём нет. Здесь
//! шаг у каждой сетки свой, а хранятся в ней значения потребителя.

use std::collections::HashMap;

use bevy::prelude::*;

/// Равномерная сетка значений с шагом `size`.
///
/// Два примитива и три удобства над ними. Примитивы — [`Grid::cell`] (одна
/// ячейка по её координате) и [`Grid::near_each`] (всё, что лежит в задетых
/// рамкой ячейках, как есть); удобства — [`Grid::at`], [`Grid::near`] и
/// [`Grid::pairs`].
pub struct Grid<T> {
    size: f32,
    cells: HashMap<IVec2, Vec<T>>,
}

impl<T> Grid<T> {
    /// Пустая сетка с шагом `size`, м.
    pub fn new(size: f32) -> Self {
        debug_assert!(size > 0.0, "шаг сетки {size} — не длина");
        Self {
            size,
            cells: HashMap::new(),
        }
    }

    /// Ячейка, в которую попадает точка.
    ///
    /// Наружу — ради одного потребителя, `entrances::RoadIndex`: он обходит
    /// ячейки **кольцами** от центра наружу и останавливается, как только
    /// найденное ближе всего, что может лежать в следующем кольце. Эта
    /// стратегия принадлежит ему, а не сетке, и заводить ради неё метод
    /// `rings` значило бы перенести сюда его алгоритм целиком.
    pub fn cell_of(&self, at: Vec2) -> IVec2 {
        (at / self.size).floor().as_ivec2()
    }

    /// Что лежит в этой ячейке. Пустая ячейка — пустой срез, а не `None`:
    /// у всех потребителей «нет ничего рядом» — обычный ответ, а не случай.
    pub fn cell(&self, cell: IVec2) -> &[T] {
        self.cells.get(&cell).map_or(&[], Vec::as_slice)
    }

    /// Что лежит в ячейке этой точки.
    ///
    /// **Одной ячейки достаточно** — и это не приближение, а следствие
    /// правила вставки: значение кладётся во все ячейки, которые задевает его
    /// рамка, раздутая на собственный радиус. Значит любая точка, до которой
    /// значению есть дело, лежит в одной из тех ячеек. Ни допуска, ни обхода
    /// соседей не нужно; ошибка в правиле вставки, наоборот, тихо вернула бы
    /// неполный ответ — ровно поэтому оно живёт здесь, в одном месте.
    pub fn at(&self, point: Vec2) -> &[T] {
        self.cell(self.cell_of(point))
    }

    /// Всё, что лежит в ячейках, задетых рамкой, **как есть**: значение,
    /// попавшее в несколько задетых ячеек, придёт несколько раз.
    ///
    /// Порядок при этом полностью определён — ячейки обходятся по возрастанию
    /// x, затем y, внутри ячейки порядок вставки, — так что обход `HashMap`
    /// наружу не протекает. Для значений, которые можно сравнивать, есть
    /// [`Grid::near`] с дедупом; это — для тех, которые нельзя (`Vec2` не
    /// `Ord`), и для тех, кому повторы безразличны.
    pub fn near_each(&self, min: Vec2, max: Vec2) -> impl Iterator<Item = &T> {
        let (low, high) = (self.cell_of(min), self.cell_of(max));
        (low.x..=high.x)
            .flat_map(move |x| (low.y..=high.y).map(move |y| IVec2::new(x, y)))
            .flat_map(|cell| self.cell(cell))
    }
}

impl<T: Copy> Grid<T> {
    /// Значение кладётся во **все** ячейки, которые задевает его рамка.
    ///
    /// Это главный инвариант сетки: только благодаря ему спрашивающему хватает
    /// одной ячейки ([`Grid::at`]) и ничего не теряется на границе ячеек.
    /// Рамку раздувает **вызывающий** — на радиус, в котором значению есть
    /// дело до точки (вылет ленты, зазор сцепки, длина тени): сетка про
    /// предметный радиус ничего не знает.
    pub fn insert(&mut self, min: Vec2, max: Vec2, value: T) {
        let (low, high) = (self.cell_of(min), self.cell_of(max));
        for x in low.x..=high.x {
            for y in low.y..=high.y {
                self.cells.entry(IVec2::new(x, y)).or_default().push(value);
            }
        }
    }

    /// То же для **звена ломаной**: рамка отрезка `from`–`to`, раздутая на
    /// `pad` — тот радиус, в котором значению есть дело до точки.
    ///
    /// Своим методом, а не строчкой у вызывающего, потому что
    /// `from.min(to) - pad, from.max(to) + pad` — это десять индексов карты
    /// (двери, посадка, вода, стыки дорог, вагоны, три сетки парса, ленты
    /// мостов), и разъехавшийся `pad` даёт ровно ту тихую неполноту ответа, от
    /// которой сетка и заводилась: рамка считается там же, где считаются
    /// ячейки. `pad = 0.0` там, где радиус знает не вставка, а запрос.
    pub fn insert_segment(&mut self, from: Vec2, to: Vec2, pad: f32, value: T) {
        self.insert(from.min(to) - pad, from.max(to) + pad, value);
    }
}

impl<T: Copy + Ord> Grid<T> {
    /// Значения из ячеек, задетых рамкой: **отсортированы и без повторов**.
    ///
    /// Сортировка — не удобство вызывающего, а инвариант. Значение лежит во
    /// всех ячейках своей рамки, так что без `dedup` соседа вернуло бы
    /// несколько раз; а собранный по такому ответу меш обязан быть одним и тем
    /// же от запуска к запуску.
    pub fn near(&self, min: Vec2, max: Vec2) -> Vec<T> {
        let mut found: Vec<T> = self.near_each(min, max).copied().collect();
        found.sort_unstable();
        found.dedup();
        found
    }

    /// Все пары значений, встретившихся в одной ячейке, — отсортированы и без
    /// повторов.
    ///
    /// Это не пространственный запрос, а перебор кандидатов: «какие двое
    /// вообще могут задевать друг друга». Два потребителя, и обоим важна
    /// именно детерминированность списка — гаражи сшиваются в ленты
    /// (`buildings::garages`), дома сравниваются попарно на перекрытие
    /// (`buildings::order`), и порядок обхода `HashMap` не должен решать ни
    /// то, ни другое.
    ///
    /// **Пара упорядочена внутри себя** (`(min, max)`), и это не косметика:
    /// без этого одни и те же двое, попавшие в разные ячейки в разном
    /// порядке, дали бы `(a, b)` и `(b, a)`, которые `dedup` не склеит. Оба
    /// потребителя кладут значения по возрастанию и получают то же самое, что
    /// и раньше, — но теперь это свойство сетки, а не их привычки.
    pub fn pairs(&self) -> Vec<(T, T)> {
        let mut pairs: Vec<(T, T)> = Vec::new();
        for bucket in self.cells.values() {
            for (offset, &a) in bucket.iter().enumerate() {
                for &b in &bucket[offset + 1..] {
                    pairs.push(if a <= b { (a, b) } else { (b, a) });
                }
            }
        }
        pairs.sort_unstable();
        pairs.dedup();
        pairs
    }
}

