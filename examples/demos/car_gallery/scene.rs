//! Клетки витрины — восемь форм улицы, на которых ряд ломался.
//!
//! Каждая клетка описана в **своих** координатах, вокруг нуля, и после этого
//! сдвигается в свою ячейку сетки. Так формы можно читать по одной, а числа в
//! них остаются теми, о которых идёт речь: «десять звеньев по 10 м» здесь
//! буквально десять звеньев по десять метров.
//!
//! Клетки нарочно не выдуманы: каждая — случай, на котором прежняя расстановка
//! была неправа, и в подписи под ней сказано, что именно надо увидеть.

use bevy::prelude::*;
use qwe::map::osm::{RoadLine, fixture};

/// Шаг сетки клеток, м. По x — самая длинная улица витрины плюс поле, по y —
/// самая высокая клетка (перекрёсток с примыкающей улицей) плюс место под
/// заголовок и подпись.
pub(crate) const CELL_PITCH: Vec2 = Vec2::new(300.0, 220.0);
/// Клеток в ряду: улицы витрины длинные и низкие (240 м на 150), так что
/// восемь клеток в 3 × 3 ближе всего по пропорциям к окну — в два столбца
/// сетка выходит узкой колонкой посреди пустого экрана.
pub(crate) const COLUMNS: usize = 3;

/// Заголовок клетки над ней и подпись под ней, м от центра клетки.
pub(crate) const HEADER_RISE: f32 = 88.0;
pub(crate) const CAPTION_DROP: f32 = 84.0;

/// Одна клетка витрины.
pub(crate) struct Cell {
    /// Что это за форма улицы.
    pub(crate) title: &'static str,
    /// Что на ней надо увидеть — то, ради чего клетка здесь и стоит.
    pub(crate) note: &'static str,
    /// Улицы клетки в её собственных координатах.
    pub(crate) roads: Vec<RoadLine>,
}

fn street(points: Vec<Vec2>, width: f32) -> RoadLine {
    fixture::street(points, width)
}

fn oneway(points: Vec<Vec2>, width: f32) -> RoadLine {
    RoadLine {
        oneway: true,
        ..street(points, width)
    }
}

fn bridge(points: Vec<Vec2>, width: f32) -> RoadLine {
    fixture::bridge(points, width)
}

/// Дуга из `links` звеньев по `link` метров, поворачивающая на `turn` градусов
/// на каждом стыке: улица, у которой между вершинами меньше двух отступов —
/// ровно тот случай, который посегментный обход выбрасывал целиком.
fn arc(links: usize, link: f32, turn: f32) -> Vec<Vec2> {
    let mut points = vec![Vec2::ZERO];
    let mut heading = Rot2::degrees(-turn * links as f32 / 2.0) * Vec2::X;
    for _ in 0..links {
        let last = *points.last().expect("дуга начата с точки");
        points.push(last + heading * link);
        heading = Rot2::degrees(turn) * heading;
    }
    // дуга строилась от края — сдвигаем её центром в ноль клетки
    let centre = (points[0] + points[points.len() - 1]) / 2.0;
    points.iter().map(|point| *point - centre).collect()
}

