/// Река Упа: полосы воды (центр-линия, ширина). Непроходима.
pub const RIVERS: &[(Vec2, Vec2, f32)] =
    &[(Vec2::new(2150.0, 1800.0), Vec2::new(2400.0, 1520.0), 90.0)];

/// Расстояние от точки до отрезка — для растеризации реки в navmesh.
pub fn distance_to_segment(point: Vec2, from: Vec2, to: Vec2) -> f32 {
    let segment = to - from;
    let t = ((point - from).dot(segment) / segment.length_squared()).clamp(0.0, 1.0);
    point.distance(from + segment * t)
}

pub fn is_in_river(pos: Vec2) -> bool {
    RIVERS
        .iter()
        .any(|&(from, to, width)| distance_to_segment(pos, from, to) <= width / 2.0)
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum BuildingKind {
    /// Многоэтажка-«пластина», 12 м в глубину.
    Slab,
    /// Частный дом 8 × 10 м.
    House,
    /// Стена Тульского кремля — кирпично-красная.
    Kremlin,
}

#[derive(Clone, Copy)]
pub struct Building {
    pub min: Vec2,
    pub size: Vec2,
    pub kind: BuildingKind,
}

impl Building {
    pub fn center(&self) -> Vec2 {
        self.min + self.size / 2.0
    }

    pub fn max(&self) -> Vec2 {
        self.min + self.size
    }
}

const fn slab(x: f32, y: f32, w: f32, h: f32) -> Building {
    Building {
        min: Vec2::new(x, y),
        size: Vec2::new(w, h),
        kind: BuildingKind::Slab,
    }
}

