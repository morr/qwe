/// [`HumanStyle::body_radius`](crate::human::HumanStyle), а не в настройках
/// расталкивания: радиус — свойство ТЕЛА, и читает его не только расталкивание,
/// но и решётка слотов назначения (`movement::destination`), которая работает и
/// с выключенным расталкиванием.
///
/// Сумма радиусов демон+человек (2.7 м) больше [`KILL_DISTANCE`] — это не
/// мешает убийству, потому что смыкается демон в фазе броска, а бросок из
