// --- Конвейер поиска пути ---
/// Зум (мировых метров на логический пиксель), выше которого мирные гуляющие
/// считаются «не на экране» и путь от диспетчера не получают: пешка на таком
/// отдалении — точка, её простой не виден, а «в кадре» иначе означала бы
/// полкарты — все ~17k мирных разом топили бы пул pathfinding-тасков.
/// Демонов и убегающих отсечка не касается (они URGENT при любом зуме).
pub const WANDER_DISPATCH_MAX_ZOOM: f32 = 0.75;

/// Через сколько тиков после **диспетчеризации** заявки её ответ применяется
/// в детерминированном режиме. Срок фиксирован от того тика, на котором
/// заявка уехала: ушедшая с тика `D` приземляется ровно на
/// `D + PATHFINDING_RETIRE_TICKS`, успел поиск посчитаться к этому моменту или
/// нет (не успел — его дожидаются `block_on`).
///
/// Отсчёт идёт не от подачи ([`crate::movement::RequestedAt`]): до диспетчера
/// заявка стоит в FIFO-очереди, а длинная очередь — штатное состояние режима,
/// так что сквозная задержка «подал → поехал» есть «ожидание в очереди + K» и
/// у разных заявок разная. Гарантируется не она, а сам срок: и `D`, и `D + K`
/// суть функции целочисленного состояния, поэтому тик, на котором пешка
/// трогается с места, в повторе тот же. Отсчёт от подачи сделал бы срок
/// простоявшей заявки прошедшим, и `block_on` ждал бы весь поиск целиком.
///
/// Восемь тиков при шаге 1/64 с — это 125 мс реального времени на скорости 1×,
/// то есть примерно та же задержка, что даёт конвейер живого режима «заявка →
/// диспетчер → таск → приёмка» (2–3 кадра), — поведение пешки после
/// диспетчеризации не меняется.
///
/// Пропускной способности эта константа не задаёт: сколько поисков уходит за
/// тик, решают [`PATHFINDING_WANDER_UNITS_PER_TICK`] и
/// [`PATHFINDING_URGENT_UNITS_PER_TICK`]. `K` покупает пачке реальное время до
/// `block_on` — и платит за это устареванием пути: путь, проложенный на тике
/// `D`, выходит из точки, где пешка стояла на `D`, а идти начинает с `D + K`.
///
/// Константа, а не производная от скорости симуляции: `SimSpeed` крутит
/// пользователь, и содержимое повтора не имеет права от неё зависеть. На 30×
/// пачки перестают успевать за реальное время, `block_on` притормаживает
/// кадр, и `throttle_speed_to_frame_budget` сам опускает эффективную
/// скорость — это осознанный размен режима, а не сбой.
pub const PATHFINDING_RETIRE_TICKS: u64 = 8;

/// Возраст pathfinding-таска, после которого приёмник паникует
/// (`listen_for_pathfinding_tasks`): живой поиск отвечает за миллисекунды, а
/// расходящийся падает по собственному бюджету шагов (`polymesh::bounded_path`)
/// — таск, доживший до этого порога, завис каким-то новым способом (лок,
/// дедлок, цикл в бэкенде), и тихое вечное ожидание превращало бы дефект в
/// «пешки замирают, конвейер пуст, CPU занят». Порог щедрый: при насыщенном
/// пуле (постройка northstar на старте — ~11 с всех ядер) здоровый таск может
/// простоять в очереди исполнителя заметные секунды.
pub const PATHFINDING_TASK_HANG_SECS: f32 = 20.0;

/// Сколько навтайлов расстояния стоят одну единицу бюджета диспетчера.
///
/// Бюджет считается не в заявках, а в предсказанной цене поиска, потому что
/// цены расходятся на порядок с лишним: замер на Туле (polymesh, 24 747
/// полигонов) даёт **0.26 мс** на короткую прогулку в 20–40 м и **5.3 мс** на
/// поручение через город. Числа, которого хватает, чтобы пропустить залп из
/// 20 000 коротких прогулок за пару секунд, хватило бы и на 20 000 поручений —
/// а это 85 с процессорного времени, то есть ровно та яма, из-за которой
/// бюджет и вводится.
///
/// Цена заявки — `1 + расстояние_в_тайлах / PATHFINDING_UNIT_TILES` по
/// Чебышёву между `start_tile` и `end_tile`. Расстояние целое, метрика
/// целочисленная: сумма float зависела бы от порядка обхода. При 64 (128 м на
/// навтайле M2) прогулка стоит 1 единицу, поручение через город — около 20,
/// то есть отношение цен то же, что у измеренных 0.26 и 5.3 мс.
pub const PATHFINDING_UNIT_TILES: i32 = 64;

/// Темп выдачи мирных заявок, единиц цены за тик (см.
/// [`PATHFINDING_UNIT_TILES`]).
///
/// Выводится из того, сколько пул успевает сжевать, а не из того, как быстро
/// хочется опустошить очередь:
///
/// ```text
/// потоки × шаг тика × доля пула / цена = бюджет
/// 5      × 15.625 мс × 0.45        / 0.26 мс ≈ 128 коротких заявок
/// 5      × 15.625 мс × 0.45        / 5.3 мс  ≈ 6.4 поручения
/// ```
///
/// Потоков именно 5, а не 8: `main.rs` переопределяет политику пула
/// (`percent: 0.5`), и на десяти логических ядрах `AsyncCompute` получает
/// половину. Оба случая по построению упираются в одни и те же ~35 мс
/// процессорного времени на тик — это и есть смысл единицы цены.
///
/// Темп **за тик**, а не за реальную секунду: тик — часы симуляции, и от
/// `SimSpeed` содержимое повтора зависеть не имеет права. Следствие честное:
/// на 30× тиков в тридцать раз больше, машина столько не считает, и
/// `throttle_speed_to_frame_budget` опускает эффективную скорость.
///
/// Длинная очередь при таком темпе — штатное состояние, а не затор: залп из
/// 16 000 поручений расходится за ~2500 тиков (39 виртуальных секунд). Это не
/// цена бюджета, а физика — те же 16 000 поисков стоят 85 с процессорного
/// времени, то есть 17 с на пяти потоках, как их ни раскладывай.
pub const PATHFINDING_WANDER_UNITS_PER_TICK: u32 = 128;

/// Темп выдачи срочных заявок (демоны и убегающие), единиц цены за тик.
///
/// Отдельный счётчик, а не общий с мирными: приоритета мало. Общий бюджет
/// голодал бы в обе стороны — толпа демонов у портала останавливала бы город,
/// а очередь города задерживала бы панику. Два счётчика делают невозможным и
/// то и другое.
///
/// Запас против спроса трёхкратный: 385 демонов с перепрокладкой раз в 0.4 с
/// дают ~15 заявок на тик, убегающие с периодом 0.7–1.2 с — ещё несколько.
/// Поиски у обоих короткие (погоня и бегство — на десятки метров), поэтому
/// почти каждая заявка стоит одну единицу.
pub const PATHFINDING_URGENT_UNITS_PER_TICK: u32 = 64;

