/// Участник одного прогона: снятая позиция плюс всё, что нужно паре.
#[derive(Clone, Copy)]
struct Pawn {
    entity: Entity,
    /// Личный номер пешки — ось разведения совпавших позиций (см.
    /// [`coincident_direction`]).
    pawn_id: u32,
    position: Vec2,
    radius: f32,
    /// Доля коррекции пары, пропорциональная подвижности: человек 1.0, демон
    /// [`DEMON_MOBILITY`], пожирающий 0.0 (толкает, но не двигается).
    mobility: f32,
    /// Куда пешка идёт прямо сейчас, единичный; `ZERO` у стоящей. Нужен
    /// обходу встречного (см. [`sidestep`]) и придержке ([`SeparationHolds`]).
    heading: Vec2,
    /// Модуль скорости ходьбы, м/с — нужен упреждению ([`anticipate`]), чтобы
    /// считать время до сближения. У стоящей не используется.
    speed: f32,
    /// Придерживают только людей, см. [`SeparationHolds`].
    human: bool,
    /// Сколько виртуальных секунд подряд пешка упирается курсом в чужое тело —
    /// источник кратковременного сжатия ([`SeparationLab::stuck_compress`]).
    stuck: f32,
}

/// Обход встречного: боковая добавка к толчку, чтобы двое идущих ЛОБ В ЛОБ
/// могли разойтись.
///
/// Без неё они расходиться не могут в принципе. Коррекция пары идёт строго
/// вдоль отрезка между центрами, а у лобовой встречи этот отрезок совпадает с
/// вектором движения обоих — то есть каждого толкает ровно НАЗАД по его же
/// пути, а на следующем тике движение снова закрывает зазор. Пара «слипается»
/// и топчется, пока симметрию не сломает что-то постороннее: разброс скоростей
/// (`Pace`), третья пешка рядом, смена waypoint'а. Боковой составляющей у
/// толчка нет ни в каком виде, поэтому шага в сторону не происходит никогда.
///
/// Добавка тем сильнее, чем более лобовая встреча (`frontal` — косинус между
/// курсом и направлением на соседа). Сторона — всегда ПРАВАЯ относительно
/// собственного курса, как у живых пешеходов: обход предсказуемый, а не в
/// случайную сторону. Величина — доля [`SEPARATION_SIDESTEP`] от продольной
/// коррекции той же пары.
///
/// Курс берётся у идущих; у стоящей пешки он `ZERO`, и добавки нет — стоящего
/// незачем «обходить», его достаточно раздвинуть.
///
/// Кому она достаётся — решают [`yields`] и «пара одна» на месте вызова; оба
/// ограничения существуют затем, чтобы обход не превращался во вращение, см.
/// их доки.
fn sidestep(pawn: &Pawn, to_other: Vec2, correction: f32, strength: f32, left_share: f32) -> Vec2 {
    let frontal = pawn.heading.dot(to_other);
    if frontal <= 0.0 {
        return Vec2::ZERO;
    }
    side_of(pawn, left_share) * (correction * strength * frontal)
}

/// Кто из встречной пары обходит: обходит РОВНО ОДИН.
///
/// Если вправо уходят оба, обход не работает совсем — он вырождается в
/// вращение. Курсы у встречных противоположны, поэтому «вправо от себя» у них
/// в мировых координатах противоположно, и две одинаковые по величине боковые
/// добавки складываются в пару сил: связка проворачивается как твёрдое тело,
/// а ВЗАИМНАЯ геометрия — расстояние и угол между курсом и осью пары — остаётся
/// прежней. Пока контроллер пути держит курс на цель, лежащую за соседом (в
/// «воронке» цель у всех одна точка), конфигурация воспроизводится каждый кадр:
/// пара наматывает круги вокруг общего центра и не расходится никогда. Именно
/// это и видно на экране как «слиплись и ходят по кругу».
///
/// Обходит один — и инварианта нет: ось пары поворачивается вокруг того, кто
/// держит линию, `frontal` у обходящего падает, продольная коррекция получает
/// боковую составляющую, и пара разъезжается. Ровно так расходятся живые
/// пешеходы — в сторону уходит кто-то один, а не оба сразу.
///
/// Уступает более подвижный: у пожирающего демона (mobility 0) уступать нечем,
/// и в паре «человек — демон» обходит человек. При равной подвижности —
/// старший [`PawnId`], лишь бы выбор был устойчив от прогона к прогону (по
/// `PawnId`, а не по `Entity`, по той же причине, что в
/// [`coincident_direction`]).
fn yields(a: &Pawn, b: &Pawn) -> bool {
    if a.mobility != b.mobility {
        return a.mobility > b.mobility;
    }
    a.pawn_id > b.pawn_id
}

/// Доли коррекции пары. По умолчанию — по подвижности (человек 1.0, демон
/// [`DEMON_MOBILITY`], пожирающий 0.0), но у пары, идущей ПРИМЕРНО ОДНИМ
/// КУРСОМ, всю коррекцию забирает ЗАДНИЙ, а переднего не трогает никто.
///
/// Иначе догоняющий расталкивает того, кого догнал: передний, ничего не
/// сделав, получает толчок в спину и сходит с линии, по которой шёл. На экране
/// это читается как «его пихнули», и виноват всегда не тот. В жизни уступает
/// тот, кто пришёл вторым, — он и обходит.
///
/// Кто задний, видно по курсу: если сосед у пешки СПЕРЕДИ (курс смотрит в его
/// сторону), значит эта пешка — догоняющая. Уступать может только подвижный:
/// у пожирающего демона (mobility 0) забирать нечего, и пара остаётся на
/// долях по подвижности.
fn shares(a: &Pawn, b: &Pawn, direction: Vec2) -> (f32, f32) {
    let weights = a.mobility + b.mobility;
    let by_mobility = (a.mobility / weights, b.mobility / weights);

    let aligned =
        a.heading != Vec2::ZERO && b.heading != Vec2::ZERO && a.heading.dot(b.heading) > 0.0;
    if !aligned {
        return by_mobility;
    }
    // `direction` смотрит от a к b: положительный dot — b впереди a
    if a.heading.dot(direction) > 0.0 && a.mobility > 0.0 {
        (1.0, 0.0)
    } else if b.heading.dot(-direction) > 0.0 && b.mobility > 0.0 {
        (0.0, 1.0)
    } else {
        by_mobility
    }
}

/// Придавить составляющую толчка ВДОЛЬ собственного курса пешки в `keep` раз;
/// поперечная остаётся целиком. У стоящей курса нет — её толчок не трогаем.
///
/// Ручка между двумя противоположными поломками, и обе видны глазом.
///
/// `keep` = 1 (ничего не давим) — продольный толчок цел, и в очереди
/// догоняющего отбрасывает НАЗАД по его же пути: на экране пешка
/// разворачивается, отходит и снова идёт вперёд, хотя ничего не решала.
///
/// `keep` = 0 (давим насмерть) — толчок становится строго поперечным, и тогда
/// толпа, идущая В ОДНУ ТОЧКУ, не может расшириться ВООБЩЕ: наружу — это назад
/// по курсу, а назад запрещено. Вся коррекция уходит в касательную, и затор не
/// рассасывается, а начинает вращаться вокруг общего центра. Ровно это и
/// случилось на сценарии «воронка»: 200 пешек в одном пятне, все 200 в
/// перекрытии.
///
/// Поэтому середина: продольная часть ослаблена (реверс в очереди перестаёт
/// бросаться в глаза), но не обнулена (сходящаяся толпа всё ещё умеет
/// раздаться). Подбирается ползунком на живой толпе, как и остальные.
fn damp_along_heading(push: Vec2, heading: Vec2, keep: f32) -> Vec2 {
    if heading == Vec2::ZERO {
        return push;
    }
    let along = heading * push.dot(heading);
    push - along * (1.0 - keep)
}

/// Уклонение ОТ ЕЩЁ НЕ СЛУЧИВШЕГОСЯ столкновения: боковой снос за `dt`, который
/// пешка `a` даёт себе, увидев сближающегося `b`.
///
/// Реактивное расталкивание по построению опаздывает: оно включается, когда
/// тела уже перекрылись, то есть когда обходить поздно и остаётся расталкивать.
/// Отсюда и вся картинка «колонны»: встречные упираются, придерживаются,
/// протискиваются по одному. Живой пешеход решает раньше — по тому, КУДА
/// сосед идёт, а не где он стоит.
///
/// Считается классически (время до ближайшего сближения, оно же time to
/// closest approach): относительная скорость `v = v_a − v_b`, вектор до соседа
/// `rel`. Расходящихся (`rel · v ≤ 0`) пропускаем сразу — самый частый случай, и
/// он же самый дешёвый. Момент максимального сближения `t = (rel · v)/|v|²`;
/// дальше горизонта — не наше дело. Вектор `closest` — где сосед окажется
/// относительно нас в этот момент; если его длина меньше суммы радиусов (с
/// запасом [`SeparationLab::anticipate_margin`]), столкновение предсказано.
///
/// Уклоняемся **строго поперёк собственного курса**: продольная составляющая —
/// это торможение, а тормозить сдвигом позиции нельзя, на экране это рывок
/// назад (та же болезнь, ради которой существует [`damp_along_heading`]).
/// Скорость гасит придержка, и это её работа, а не этой функции.
///
/// Лобовая встреча вырождается — `closest` почти коллинеарен курсу, и
/// поперечной составляющей у него нет. Ровно ту же дыру у реактивной ветки
/// затыкает [`sidestep`]; здесь её затыкает [`SeparationLab::lane_bias`],
/// примешивая правую нормаль. Разница в том, что упреждение срабатывает за
/// секунду-полторы до контакта, когда сдвинуться вбок ничего не стоит.
///
/// Величина падает с приближением горизонта (`urgency`): дальний сосед двигает
/// слабо, ближний — сильно. Умножается на подвижность, так что пожирающий демон
/// (0) не уклоняется ни от кого.
fn anticipate(a: &Pawn, b: &Pawn, lab: &SeparationLab, dt: f32) -> Vec2 {
    let Some((lateral, urgency)) = avoid_direction(a, b, lab) else {
        return Vec2::ZERO;
    };
    lateral * (lab.anticipation * urgency * a.mobility * dt)
}

/// Правая нормаль к курсу — сторона, в которую пешка обходит. `perp` в bevy —
/// поворот на +90° (влево), поэтому со знаком минус.
fn right_of(heading: Vec2) -> Vec2 {
    -heading.perp()
}

/// В какую сторону обходит ИМЕННО ЭТА пешка: правая нормаль к курсу, а у доли
/// [`SeparationLab::left_share`] пешек — левая.
///
/// Сторона личная и постоянная, а не случайная на прогон: она берётся хэшем
/// [`crate::rng::PawnId`], как ось разведения совпавших позиций
/// ([`coincident_direction`]). Пешка, каждый кадр выбирающая сторону заново, не
/// обходит, а дрожит — и на экране это хуже любой колонны.
fn side_of(pawn: &Pawn, left_share: f32) -> Vec2 {
    if left_share > 0.0 && lefty_fraction(pawn.pawn_id) < left_share {
        pawn.heading.perp()
    } else {
        right_of(pawn.heading)
    }
}

/// Место пешки в [0, 1) — тем же хэшем, что и [`coincident_direction`], но со
/// своим множителем: иначе сторона обхода и ось разведения были бы одним и тем
/// же числом, и «левши» получали бы вдобавок одинаковую ось.
fn lefty_fraction(pawn_id: u32) -> f32 {
    let hash = pawn_id.wrapping_mul(2246822519) ^ 0x9e37_79b9;
    (hash >> 8) as f32 / (u32::MAX >> 8) as f32
}

/// Куда и насколько срочно `a` уклоняется от `b`: единичный вектор ПОПЕРЁК
/// курса `a` плюс срочность 0…1 (1 — контакт вот-вот). `None` — уклоняться не
/// от чего. Ядро [`anticipate`], вынесенное отдельно, потому что тем же ответом
/// пользуется руление ([`SeparationSteer`]), а оно не толчок и масштабируется
/// иначе.
fn avoid_direction(a: &Pawn, b: &Pawn, lab: &SeparationLab) -> Option<(Vec2, f32)> {
    if a.heading == Vec2::ZERO || a.mobility <= 0.0 || lab.horizon <= 0.0 {
        return None;
    }
    let rel = b.position - a.position;
    let velocity = a.heading * a.speed - b.heading * b.speed;
    let closing = rel.dot(velocity);
    if closing <= 0.0 {
        return None;
    }
    let speed_squared = velocity.length_squared();
    if speed_squared < 1e-6 {
        return None;
    }
    let time = closing / speed_squared;
    if time > lab.horizon {
        return None;
    }
    let closest = rel - velocity * time;
    let miss = closest.length();
    let clearance = (a.radius + b.radius) * lab.anticipate_margin;
    if miss >= clearance {
        return None;
    }
    let side = side_of(a, lab.left_share);
    let away = if miss > 1e-3 { -closest / miss } else { side };
    let biased = away + side * lab.lane_bias;
    let lateral = biased - a.heading * biased.dot(a.heading);
    let lateral = lateral.normalize_or_zero();
    if lateral == Vec2::ZERO {
        return None;
    }
    Some((lateral, 1.0 - time / lab.horizon))
}

/// Буферы прогона — в `Local`, чтобы steady state обходился без аллокаций.
/// `pub(super)` — тип стоит в сигнатуре системы, которую регистрирует `mod.rs`.
#[derive(Default)]
pub(super) struct SeparationState {
    /// Кадр последнего прогона: гейт «не чаще раза в кадр».
    last_frame: Option<u32>,
    /// Виртуальное время, накопленное тиками с последнего прогона.
    pending_dt: f32,
    pawns: Vec<Pawn>,
    /// Мелкая сетка соседей: голова цепочки по ячейке + связный список по
    /// индексам `pawns` — ни одного `Vec` на ячейку.
    heads: HashMap<IVec2, u32>,
    next: Vec<u32>,
    /// Пары этого прогона, каждая по разу: индексы плюс признак «уже
    /// перекрылись». Неперекрывшиеся сюда попадают только при включённом
    /// упреждении ([`SeparationLab::horizon`]) и только те, что в пределах
    /// горизонта. Собираются отдельным проходом, потому что толчок пары зависит
    /// от того, сколько соседей у её участников (см. `contacts`), а это
    /// известно только когда найдены все.
    pairs: Vec<(u32, u32, bool)>,
    /// Сколько перекрытий у каждой пешки в этом прогоне.
    contacts: Vec<u32>,
    /// Кто в этом прогоне упирался курсом в перекрытого соседа — источник
    /// [`SeparationHolds`].
    held: Vec<bool>,
    pushes: Vec<Vec2>,
    /// Толчки ТВЁРДОГО ЯДРА — отдельно от мягких, потому что ограничены они
    /// по-разному ([`SeparationLab::hard_core`]).
    core_pushes: Vec<Vec2>,
    /// Сколько пар этого прогона уже перекрылись — остальные попали только в
    /// упреждение. Считается на месте, в проходе толчков.
    overlapping: usize,
    /// Сумма направлений на перегородивших — источник [`SeparationBlock`].
    /// Копится ненормированной и нормируется в конце, как и `steers`.
    blocks: Vec<Vec2>,
    /// Сумма сторон обхода по всем соседям — источник [`SeparationSteer`].
    /// Складывается ненормированной и нормируется один раз в конце: пешка,
    /// зажатая с двух сторон, должна получить их сумму, а не последнюю.
    steers: Vec<Vec2>,
    /// Сколько виртуальных секунд подряд каждая пешка упирается курсом в чужое
    /// тело — единственное, что живёт МЕЖДУ прогонами: залипание это именно
    /// длительность. Пуста, пока [`SeparationLab::stuck_compress`] не тронут.
    stuck: bevy::ecs::entity::EntityHashMap<f32>,
    /// Та же карта, собранная заново этим прогоном: ушедший из вьюпорта или
    /// прошедший затор выпадает из неё сам, без отдельной уборки.
    stuck_next: bevy::ecs::entity::EntityHashMap<f32>,
}

fn fine_cell(pos: Vec2, cell: f32) -> IVec2 {
    (pos / cell).floor().as_ivec2()
}

/// Детерминированное направление разведения точно совпавших позиций — хэш
/// [`PawnId`], тот же трюк, что `personal_spread` у веера бегства: пара держит
/// свою ось от прогона к прогону, а не дрожит случайной.
///
/// По `PawnId`, а не по `Entity`, по той же причине, что и там: индексы
/// сущностей после рестарта переиспользуются в другом порядке.
fn coincident_direction(pawn_id: u32) -> Vec2 {
    let hash = pawn_id.wrapping_mul(2654435761);
    let angle = (hash >> 8) as f32 / (u32::MAX >> 8) as f32 * std::f32::consts::TAU;
    Vec2::from_angle(angle)
}

/// Толчки всех пар текущего набора — чистая функция над буферами, без ECS
/// (тестируется напрямую). `fraction` — доля перекрытия, разрешаемая этим
/// прогоном; в `pushes` — суммарный сдвиг каждой пешки, ещё без клампа.
/// Ручки одного прогона: доля перекрытия, разрешаемая к снятию, плюс то, что
/// задаёт [`SeparationStyle`]. Отдельной структурой, чтобы у чистой функции не
/// росла череда безымянных `f32`.
#[derive(Clone, Copy)]
struct Tuning {
    fraction: f32,
    /// Виртуальное время, прошедшее с прошлого прогона: упреждение считает снос
    /// в м/с, а не в долях перекрытия.
    dt: f32,
    sidestep: f32,
    cell: f32,
    lab: SeparationLab,
}

/// Радиус тела с поправкой на давку: чем больше у пешки одновременных
/// перекрытий, тем сильнее она «ужимается» ([`SeparationLab::compress`]).
///
/// Зачем. Дистанция покоя 1.8 м — это личное пространство свободно идущего
/// человека, и в узком месте она физически недостижима: суммарной ширины
/// не хватает, коррекции всех пар складываются в затор, и поток встаёт.
/// Живая толпа в этом месте не встаёт, а прижимается. Ужимается ТОЛЬКО
/// величина коррекции: набор пар и, значит, `contacts` считаются по полному
/// радиусу — иначе загрузка зависела бы сама от себя.
///
/// При `compress = 0` возвращает радиус без изменений, то есть нынешнее
/// поведение.
fn squeezed_radius(pawn: &Pawn, contacts: u32, lab: &SeparationLab) -> f32 {
    let mut radius = pawn.radius;
    if lab.compress > 0.0 && lab.compress_at > 0.0 {
        let load = (contacts as f32 / lab.compress_at).min(1.0);
        radius *= 1.0 - lab.compress * load;
    }
    radius * (1.0 - lab.stuck_compress * stuck_load(pawn.stuck, lab))
}

/// Насколько пешка «залипла» — 0…1 по времени непрерывного упора
/// ([`SeparationLab::stuck_after`], [`SeparationLab::stuck_ramp`]).
///
/// Отдельно от числа контактов намеренно: сжатие по контактам получает вся
/// плотная толпа, в том числе стоящая и никуда не идущая, и её равновесие
/// оказывается перекрытым навсегда. Сжатие по времени упора получает только
/// тот, кто уже несколько раз подряд ткнулся в чужое тело и не прошёл, —
/// протискивание длится ровно столько, сколько длится тупик.
fn stuck_load(stuck: f32, lab: &SeparationLab) -> f32 {
    if lab.stuck_compress <= 0.0 {
        return 0.0;
    }
    let over = stuck - lab.stuck_after;
    if over <= 0.0 {
        return 0.0;
    }
    if lab.stuck_ramp <= 0.0 {
        return 1.0;
    }
    (over / lab.stuck_ramp).min(1.0)
}

/// Отпустило ли скольжение эту пешку: она упирается дольше, чем
/// [`SeparationLab::slide_release`], и запрет «не лезь в тело» с неё снят.
fn slide_released(pawn: &Pawn, lab: &SeparationLab) -> bool {
    lab.slide_release > 0.0 && pawn.stuck >= lab.slide_release
}

/// Дистанция покоя пары с поправкой на то, КТО в ней идёт.
///
/// Идущая мимо стоящей ужимается до [`SeparationLab::pass_squeeze`] — это
/// проход сквозь осевшую толпу, см. док ручки. Пара «оба стоят» и пара «оба
/// идут» не трогаются: плотность осевшей толпы и ширина потока — это то, ради
/// чего радиус тела вообще существует.
fn rest_distance(a: &Pawn, b: &Pawn, contacts: (u32, u32), lab: &SeparationLab) -> f32 {
    let full = squeezed_radius(a, contacts.0, lab) + squeezed_radius(b, contacts.1, lab);
    let a_walking = a.heading != Vec2::ZERO;
    let b_walking = b.heading != Vec2::ZERO;
    if lab.pass_squeeze < 1.0 && (a_walking != b_walking) {
        return full * lab.pass_squeeze;
    }
    full
}

fn resolve_pushes(state: &mut SeparationState, tuning: Tuning) {
    let Tuning {
        fraction,
        dt,
        sidestep: sidestep_strength,
        cell: cell_size,
        lab,
    } = tuning;
    state.heads.clear();
    state.next.clear();
    state.pairs.clear();
    state.contacts.clear();
    state.contacts.resize(state.pawns.len(), 0);
    state.held.clear();
    state.held.resize(state.pawns.len(), false);
    state.pushes.clear();
    state.pushes.resize(state.pawns.len(), Vec2::ZERO);
    state.core_pushes.clear();
    state.core_pushes.resize(state.pawns.len(), Vec2::ZERO);
    state.steers.clear();
    state.steers.resize(state.pawns.len(), Vec2::ZERO);
    state.blocks.clear();
    state.blocks.resize(state.pawns.len(), Vec2::ZERO);
    state.overlapping = 0;

    // Насколько далеко имеет смысл смотреть на ещё не перекрывшегося соседа: за
    // горизонт `t` секунд самая быстрая пара сближается на сумму скоростей.
    // 0 при выключенном упреждении — тогда проход ниже не берёт ни одной лишней
    // пары и остаётся тем же, что был.
    //
    // Ячейка мелкой сетки от него РАСТЁТ: соседей ищут в 3 × 3 ячейках, и пара,
    // разнесённая дальше ячейки, туда просто не попадёт. Это и есть цена
    // упреждения — площадь просмотра растёт как квадрат горизонта (при 1.5 с и
    // 3.5 м/с ячейка 10.5 м против нынешних 2.4 м, то есть ~19× кандидатов на
    // пешку). Проверять этот счёт — работа стенда, а не догадки.
    let lookahead = if lab.horizon > 0.0 && lab.anticipation > 0.0 {
        let fastest = state
            .pawns
            .iter()
            .map(|pawn| pawn.speed)
            .fold(0.0f32, f32::max);
        lab.horizon * 2.0 * fastest
    } else {
        0.0
    };
    let cell_size = cell_size.max(lookahead);

    for (i, pawn) in state.pawns.iter().enumerate() {
        let head = state
            .heads
            .insert(fine_cell(pawn.position, cell_size), i as u32);
        state.next.push(head.unwrap_or(NONE));
    }

    // проход 1 — кто с кем перекрылся, кто с кем сближается, и сколько соседей
    // у каждого. `contacts` считает ТОЛЬКО перекрытия: он кормит гейт `alone` у
    // обхода и загрузку у сжатия радиуса, и упреждающие пары там не при чём
    for i in 0..state.pawns.len() {
        let a = state.pawns[i];
        let cell = fine_cell(a.position, cell_size);
        for dx in -1..=1 {
            for dy in -1..=1 {
                let Some(&head) = state.heads.get(&(cell + IVec2::new(dx, dy))) else {
                    continue;
                };
                let mut j = head;
                while j != NONE {
                    // пара встречается с обеих сторон — обрабатываем один раз
                    if j > i as u32 {
                        let b = state.pawns[j as usize];
                        let min_distance = a.radius + b.radius;
                        let gap_squared = (b.position - a.position).length_squared();
                        let overlapping = gap_squared < min_distance * min_distance;
                        if a.mobility + b.mobility > 0.0 {
                            if overlapping {
                                state.pairs.push((i as u32, j, true));
                                state.contacts[i] += 1;
                                state.contacts[j as usize] += 1;
                            } else if gap_squared < lookahead * lookahead {
                                state.pairs.push((i as u32, j, false));
                            }
                        }
                    }
                    j = state.next[j as usize];
                }
            }
        }
    }

    // проход 2 — толчки
    for pair in 0..state.pairs.len() {
        let (i, j, overlapping) = state.pairs[pair];
        let (a, b) = (state.pawns[i as usize], state.pawns[j as usize]);
        // сближающиеся, но ещё не сомкнувшиеся: только уклонение, и каждый
        // считает своё — доли пары тут ни при чём
        if !overlapping {
            state.pushes[i as usize] += anticipate(&a, &b, &lab, dt);
            state.pushes[j as usize] += anticipate(&b, &a, &lab, dt);
            if lab.steer > 0.0 {
                // руление копит ту же сторону, но взвешенную срочностью, а не
                // временем прогона: это доля курса, а не метры
                for (pawn, other, index) in [(&a, &b, i), (&b, &a, j)] {
                    if let Some((lateral, urgency)) = avoid_direction(pawn, other, &lab) {
                        state.steers[index as usize] += lateral * urgency;
                    }
                }
            }
            continue;
        }
        state.overlapping += 1;
        let min_distance = rest_distance(
            &a,
            &b,
            (state.contacts[i as usize], state.contacts[j as usize]),
            &lab,
        );
        let offset = b.position - a.position;
        let distance = offset.length();
        let direction = if distance > 1e-4 {
            offset / distance
        } else {
            coincident_direction(a.pawn_id)
        };
        // `max(0)` — из-за сжатия радиуса ([`squeezed_radius`]): в давке
        // дистанция покоя падает ниже фактической, и без клампа пара, которую
        // перекрытой посчитал проход 1, получила бы толчок ВНУТРЬ
        let overlap = (min_distance - distance).max(0.0) * fraction;
        let correction = direction * overlap;
        // Твёрдое ядро — отдельным слагаемым, и это не педантизм: мягкая часть
        // ограничена потолком скорости расталкивания (доли метра за прогон), а
        // встречная пара на полном ходу сближается за тот же прогон на впятеро
        // больше. Ядро, попавшее под общий потолок, работать не успевает — на
        // стенде это видно как сотни пар, сошедшихся ближе половины спрайта,
        // при формально включённом ядре. См. [`SeparationLab::hard_core`]
        let core_overlap = if lab.hard_core > 0.0 {
            ((a.radius + b.radius) * lab.hard_core - distance).max(0.0)
        } else {
            0.0
        };
        let (share_a, share_b) = shares(&a, &b, direction);
        // не «да/нет», а НАСКОЛЬКО в лоб: косинус между курсом и осью пары.
        // Скольжению ([`SeparationBlock`]) нужна именно величина — сосед,
        // задевший плечом, запрещает идти вперёд не так же, как вставший
        // ровно на пути, а сумма одинаковых «да» от полудюжины боковых даёт
        // равнодействующую точно по курсу и останавливает пешку там, где
        // прохода на самом деле никто не перекрывал
        let a_facing = a.heading.dot(direction);
        let b_facing = b.heading.dot(-direction);
        let a_frontal = a_facing > 0.0;
        let b_frontal = b_facing > 0.0;
        // Придержка — только упёршемуся в СТОЯЩЕГО или ВСТРЕЧНОГО: там напор
        // бесполезен — ходьба давит ровно против коррекции этой же пары, и оба
        // усилия взаимно гасятся навечно (см. [`SeparationHolds`]). Попутного
        // и поперечного соседа это не касается: первый вариант правила
        // придерживал за любое касание, и поток целиком полз на доле шага —
        // группа попутчиков душила сама себя.
        let a_blocked = a_frontal && (b.heading == Vec2::ZERO || b_frontal);
        let b_blocked = b_frontal && (a.heading == Vec2::ZERO || a_frontal);
        if a.human && a_blocked {
            state.held[i as usize] = true;
        }
        if b.human && b_blocked {
            state.held[j as usize] = true;
        }
        // запрет копится по тому же условию, что придержка, и у ВСЕХ, а не
        // только у людей: демон в погоне тоже не обязан входить в чужое тело
        if lab.slide > 0.0 {
            if a_blocked && !slide_released(&a, &lab) {
                state.blocks[i as usize] += direction * a_facing;
            }
            if b_blocked && !slide_released(&b, &lab) {
                state.blocks[j as usize] -= direction * b_facing;
            }
        }
        // Руление у СОМКНУВШЕЙСЯ пары. Условие то же, что у придержки, и это не
        // совпадение: придержка — «упёрся, перестань давить», руление — «упёрся,
        // возьми вбок». Упреждение здесь не помощник: тела уже соприкоснулись,
        // и обходить по его расчёту поздно. Сторона — своя правая, как у живых
        // пешеходов; ВСТРЕЧНЫМ она даёт противоположные стороны мира, то есть
        // ровно расхождение, а не вращение (вращение получалось у ТОЛЧКА, где
        // боковая добавка шла вместе с продольной коррекцией — здесь продольной
        // составляющей нет вовсе, курс только доворачивается).
        if lab.steer > 0.0 {
            if a_blocked && a.mobility > 0.0 {
                state.steers[i as usize] += side_of(&a, lab.left_share);
            }
            if b_blocked && b.mobility > 0.0 {
                state.steers[j as usize] += side_of(&b, lab.left_share);
            }
        }
        // обход — только встречным: догоняющего сзади ничто не держит, а
        // боковая добавка расползлась бы по всей очереди, идущей в одну сторону
        let opposed = a_frontal && b_frontal;
        // …и только паре, у которой нет других соседей. Обход разводит ДВОИХ,
        // симметрию которых больше сломать некому; в куче симметрию ломает сама
        // многотельная геометрия, а одинаковый разворот вправо у полусотни
        // перекрывшихся складывается в общее вращение — затор начинает крутиться
        // вместо того, чтобы рассасываться.
        //
        // [`SeparationLab::crowd_sidestep`] — ручка ровно на этот гейт: при 0
        // всё как сейчас, при >0 куча тоже обходит, но ослабленной долей.
        // Гипотеза, которую ей проверяют: боковой добавки в куче не хватает
        // именно там, где встречный поток обязан расслоиться на полосы, а
        // вращение — цена, которая, может быть, не наступает, пока добавка
        // мала.
        let alone = state.contacts[i as usize] == 1 && state.contacts[j as usize] == 1;
        let crowd = if alone { 1.0 } else { lab.crowd_sidestep };
        let (side_a, side_b) = if opposed && crowd > 0.0 {
            let strength = sidestep_strength * crowd;
            // уступает один: вправо уходят оба — и пара вращается, см. [`yields`]
            if yields(&a, &b) {
                (
                    sidestep(&a, direction, overlap * share_a, strength, lab.left_share),
                    Vec2::ZERO,
                )
            } else {
                (
                    Vec2::ZERO,
                    sidestep(&b, -direction, overlap * share_b, strength, lab.left_share),
                )
            }
        } else {
            (Vec2::ZERO, Vec2::ZERO)
        };
        state.pushes[i as usize] -= correction * share_a - side_a;
        state.pushes[j as usize] += correction * share_b + side_b;
        if core_overlap > 0.0 {
            let core = direction * core_overlap;
            state.core_pushes[i as usize] -= core * share_a;
            state.core_pushes[j as usize] += core * share_b;
        }
    }
}

/// Прогон расталкивания: гейты → сбор видимых из грубых сеток → толчки →
/// применение с проверкой проходимости. Порядок в тике — строго после
/// `move_moving_entities` (см. цепочку в `movement/mod.rs`).
#[allow(clippy::too_many_arguments)]
pub fn separate_pawns(
    mut diagnostics: bevy::diagnostic::Diagnostics,
    style: Res<SeparationStyle>,
    // радиус тела живёт в настройках ЛЮДЕЙ, а не расталкивания: это свойство
    // тела, а расталкивание — лишь один из его читателей (второй — слоты
    // назначения, которые работают и когда расталкивание выключено)
    human_style: Res<crate::human::HumanStyle>,
    lab: Res<SeparationLab>,
    mut stats: ResMut<SeparationStats>,
    frames: Res<FrameCount>,
    time: Res<Time>,
    navmesh: Res<crate::navigation::ArcNavmesh>,
    mut humans: ResMut<SpatialGrid<Human>>,
    demons: Res<SpatialGrid<Demon>>,
    camera: Single<&Transform, With<Camera2d>>,
    window: Single<&Window, With<PrimaryWindow>>,
    mut out: SeparationOutput,
    mut pawns: Query<
        (
            &mut SimPosition,
            &crate::rng::PawnId,
            &crate::movement::Movable,
            Has<crate::movement::MovableStateMovingTag>,
            Has<Demon>,
            Has<DemonDevourTag>,
        ),
        (Or<(With<Human>, With<Demon>)>, Without<DemonLungeTag>),
    >,
    mut state: Local<SeparationState>,
) {
    if !style.enabled {
        state.pending_dt = 0.0;
        out.clear();
        return;
    }
    state.pending_dt += time.delta_secs();
    // не чаще раза в кадр: остальные тики того же кадра только копят dt, а
    // придержанные остаются придержанными до следующего прогона
    if state.last_frame == Some(frames.0) {
        return;
    }
    state.last_frame = Some(frames.0);
    let dt = state.pending_dt;
    let fraction = (lab.rate * dt).min(1.0);
    state.pending_dt = 0.0;
    // на таком отдалении пешка — 1–2 пикселя, перекрытие не читается; вместе
    // с расталкиванием выключается и придержка — иначе пешки, придержанные
    // последним прогоном перед отзумом, остались бы придержанными навсегда
    if camera.scale.x >= SEPARATION_MAX_ZOOM {
        out.clear();
        return;
    }

    let started = std::time::Instant::now();
    let camera_position = camera.translation.truncate();
    let half_view = Vec2::new(window.width(), window.height()) / 2.0 * camera.scale.x * VIEW_MARGIN;
    let min = camera_position - half_view;
    let max = camera_position + half_view;

    let human_radius = human_style.body_radius;
    let demon_radius = demon_radius(human_radius);

    // разыменование ОДИН раз: через `Local` каждое обращение к полю заимствует
    // весь ресурс, и «сложить в один буфер, читая соседний» не даст компилятор
    let state = &mut *state;
    state.pawns.clear();
    {
        let pawn_buffer = &mut state.pawns;
        let stuck_seen = &state.stuck;
        let mut collect = |entity: Entity| {
            // мимо запроса — бросок, труп, пешка чужого вида в чужой сетке
            let Ok((sim_position, pawn_id, movable, is_moving, is_demon, is_devouring)) =
                pawns.get(entity)
            else {
                return;
            };
            let position = sim_position.0;
            if position.x < min.x || position.x > max.x || position.y < min.y || position.y > max.y
            {
                return;
            }
            let (radius, mobility) = if is_devouring {
                (demon_radius, 0.0)
            } else if is_demon {
                (demon_radius, DEMON_MOBILITY)
            } else {
                (human_radius, 1.0)
            };
            // осевшая пешка упирается: см. [`SeparationLab::idle_mobility`].
            // Множителем, а не заменой, — иначе ручка перебивала бы и
            // подвижность демона, которая выражает совсем другое
            let mobility = if is_moving {
                mobility
            } else {
                mobility * lab.idle_mobility
            };
            pawn_buffer.push(Pawn {
                entity,
                pawn_id: pawn_id.0,
                position,
                radius,
                mobility,
                // у стоящей курс не берём: `last_direction` у неё остался от
                // прошлой ходьбы и увёл бы обход в сторону, куда она уже не идёт
                heading: if is_moving {
                    movable.last_direction.normalize_or_zero()
                } else {
                    Vec2::ZERO
                },
                speed: movable.speed,
                human: !is_demon,
                stuck: stuck_seen.get(&entity).copied().unwrap_or(0.0),
            });
        };
        humans.for_each_in_rect(min, max, &mut collect);
        demons.for_each_in_rect(min, max, &mut collect);
    }

    resolve_pushes(
        state,
        Tuning {
            fraction,
            dt,
            sidestep: style.sidestep,
            cell: separation_cell(human_radius),
            lab: *lab,
        },
    );

    // залипание — то же самое, но со временем: карта пересобирается прогоном
    // целиком, и упор, прервавшийся хоть на прогон, начинает счёт заново.
    // Пока ручка не тронута, обе карты пусты и цикл ниже в них не заглядывает
    // карта залипания нужна двум механизмам сразу — сжатию и отпусканию
    // скольжения; пока не тронут ни один, она пуста и не стоит ничего
    if lab.stuck_compress > 0.0 || lab.slide_release > 0.0 {
        // буфер вынимается из состояния целиком: заполнять его, читая рядом
        // `state.pawns` и `state.held`, иначе не даст заимствование
        let mut next = std::mem::take(&mut state.stuck_next);
        next.clear();
        for (index, pawn) in state.pawns.iter().enumerate() {
            if state.held[index] {
                next.insert(pawn.entity, pawn.stuck + dt);
            }
        }
        state.stuck_next = std::mem::replace(&mut state.stuck, next);
    } else if !state.stuck.is_empty() {
        state.stuck.clear();
    }

    // придержанные — с чистого листа каждый прогон: ушедший из вьюпорта или
    // разошедшийся с соседом освобождается сам, без отдельной уборки
    out.clear();
    for (index, pawn) in state.pawns.iter().enumerate() {
        if state.held[index] {
            out.holds.0.insert(pawn.entity);
        }
        let blocked = state.blocks[index].normalize_or_zero();
        if blocked != Vec2::ZERO {
            out.block.0.insert(pawn.entity, blocked);
        }
        // нормируем один раз здесь: в буфере лежит СУММА сторон по всем
        // соседям, и зажатая с двух сторон пешка получает их равнодействующую
        let lateral = state.steers[index].normalize_or_zero();
        if lateral != Vec2::ZERO {
            out.steer.0.insert(pawn.entity, lateral * lab.steer);
        }
    }

    let navmesh = navmesh.read();
    for i in 0..state.pawns.len() {
        let pawn = state.pawns[i];
        let push = damp_along_heading(state.pushes[i], pawn.heading, style.backstep);
        // ядро не давится вдоль курса: придавливать выталкивание ИЗ ТЕЛА нечем,
        // это не личное пространство, а геометрия
        let core = state.core_pushes[i];
        if push == Vec2::ZERO && core == Vec2::ZERO {
            continue;
        }
        let ceiling = if lab.max_speed > 0.0 {
            lab.max_step.min(lab.max_speed * dt)
        } else {
            lab.max_step
        };
        // ядро не ограничено потолком СКОРОСТИ (иначе оно не успевает за
        // сближением и не работает вовсе), но общий сдвиг по-прежнему не больше
        // `max_step`: это тот потолок, по которому считается «телепорта нет»
        let step = (push.clamp_length_max(ceiling) + core).clamp_length_max(lab.max_step);
        let target = pawn.position + step;
        let tile = world_to_tile(target);
        // толчок в непроходимое отбрасывается: спасение (`rescue_*`) ловит
        // только провал поиска пути, задавленную в стену пешку оно бы не нашло
        if !navmesh.is_passable(tile.x, tile.y) {
            continue;
        }
        let Ok((mut sim_position, _, _, _, is_demon, _)) = pawns.get_mut(pawn.entity) else {
            continue;
        };
        sim_position.0 = target;
        let length = step.length();
        stats.push_metres += length as f64;
        stats.worst_push = stats.worst_push.max(length);
        // сетка людей инкрементальна; толчки мелкие, но стоячую пешку они
        // могут за много прогонов увести через границу 60-метровой ячейки
        if !is_demon && crate::spatial::cell_of(target) != crate::spatial::cell_of(pawn.position) {
            humans.insert(pawn.entity, target);
        }
    }
    stats.runs += 1;
    // счёт снят проходом толчков, а не отдельным обходом `pairs`: обход стоил бы
    // столько же итераций, сколько сам решатель, ради числа, которое в игре не
    // читает никто
    stats.overlapping_pairs += state.overlapping as u64;
    stats.anticipated_pairs += (state.pairs.len() - state.overlapping) as u64;
    crate::diagnostics::measure_ms(
        &mut diagnostics,
        &crate::diagnostics::SIM_SEPARATION_MS,
        started,
    );
}

