//! Стенд кузовов — девятая клетка витрины: пять типов машин на три ступени
//! подробности.
//!
//! Клетки-улицы отвечают на вопрос «где стоит ряд», стенд — на вопрос «что
//! именно стоит в ряду». Порознь, потому что и решается это порознь: место
//! выбирает расстановка (`park_cars`), а вид кузова — [`CarShape`] и ступень
//! зума, и ни то, ни другое по улице не прочитать: тип машины там выпадает
//! ГПСЧ, и фургона можно не дождаться вовсе.
//!
//! Поэтому здесь — единственное место витрины, где тип кузова **заказан**, а
//! не выпал: как витрина кровель заказывает материал (`RoofLook::new`), потому
//! что до всех сочетаний зерно не достаёт. Геометрия при этом всё та же
//! игровая: [`body::push_body`] и [`body::push_shadow`] — те же вызовы, что
//! делает слой города.
//!
//! Стенд нарисован в **метрах**, как всё остальное, и увеличен трансформом
//! ([`SCALE`]): рядом с улицами в сотни метров машина в четыре с половиной
//! иначе не видна, а масштабировать саму геометрию значило бы показывать не
//! игровую.

use bevy::prelude::*;
use qwe::map::cars::{Car, CarDetail, CarShape, body};
use qwe::map::{MeshBuilder, shadow_dir, shadow_length_scale};

/// Во сколько раз стенд увеличен трансформом — лупа над игровой геометрией.
/// Больше не выйдет: стенд обязан остаться внутри своей ячейки сетки
/// (`scene::CELL_PITCH`), рядом с которой стоят подписи соседей.
pub(crate) const SCALE: f32 = 12.0;
/// Шаг стенда в метрах: по x — самый длинный кузов плюс поле, по y — ширина
/// плюс место под тень.
const COLUMN: f32 = 6.6;
const ROW: f32 = 3.6;

/// Типы кузовов сверху вниз — от самого частого к самому редкому, тем же
/// порядком, каким они стоят в таблице `CarShape::from_share`. Строками, а не
/// столбцами, потому что подпись типа — одно слово и слева от строки читается,
/// а три ступени подряд в строке — это ровно то сравнение, ради которого
/// стенд и заведён.
pub(crate) const SHAPES: [(CarShape, &str); 5] = [
    (CarShape::Sedan, "Седан"),
    (CarShape::Hatch, "Хэтчбек"),
    (CarShape::Wagon, "Универсал"),
    (CarShape::Crossover, "Кроссовер"),
    (CarShape::Van, "Фургон"),
];

/// Доля палитры кузовов ([`body::color_from_share`]) на строку — цвет строки
/// заказан, как и её тип.
///
/// Один цвет на все три ступени строки обязателен: иначе строку не прочитать
/// как одну машину на трёх зумах. Но **какой** — не всё равно, и номер строки
/// сюда не годится. Стенд заведён ради разметки кабины (лобовое, крыша,
/// заднее), а она нарисована стёклами постоянного цвета: на тёмном кузове
/// `GLASS_BACK` совпадает с самим кузовом, а крыша — с `GLASS_FRONT`, и
/// показывать становится нечего. Поэтому взяты светлые слоты палитры (доля
/// берётся серединой слота, чтобы округление не съезжало на соседний), а
/// разнообразие красок улица и так показывает: там цвет выпадает ГПСЧ.
const ROW_COLOR: [f32; SHAPES.len()] = [0.05, 0.15, 0.25, 0.35, 0.95];

/// Ступени подробности слева направо — в том порядке, в каком их отдаёт зум:
/// ближняя первой.
///
/// Без подписей рядом: заголовок столбца — имя самой ступени, и берётся оно
/// её же `Debug` (`params::detail_name` подписывает ручку `Detail` тем же
/// способом). Вторая, ручная копия тех же трёх слов разошлась бы с игрой на
/// первом же переименовании — ровно та причина, по которой и сама лестница
/// ступеней живёт в игре (`cars::detail_for`), а не здесь.
pub(crate) const DETAILS: [CarDetail; 3] =
    [CarDetail::Full, CarDetail::Silhouette, CarDetail::Block];

/// Место машины в собственных координатах стенда, метры: ступень задаёт
/// столбец, тип — строку.
pub(crate) fn at(detail: usize, shape: usize) -> Vec2 {
    Vec2::new(
        (detail as f32 - (DETAILS.len() as f32 - 1.0) / 2.0) * COLUMN,
        ((SHAPES.len() as f32 - 1.0) / 2.0 - shape as f32) * ROW,
    )
}

/// Полуразмер стенда в собственных координатах — по нему подписи стоят слева
/// от строк и над столбцами.
pub(crate) fn half_size() -> Vec2 {
    Vec2::new(
        DETAILS.len() as f32 * COLUMN / 2.0,
        SHAPES.len() as f32 * ROW / 2.0,
    )
}

/// Меш стенда: тени всех машин, потом кузова — тем же порядком, каким их
/// кладёт слой города, иначе тень соседа легла бы на кузов.
pub(crate) fn mesh() -> MeshBuilder {
    let mut builder = MeshBuilder::default();
    let stretch = shadow_dir() * shadow_length_scale();
    let cars: Vec<(Car, CarDetail)> = SHAPES
        .iter()
        .enumerate()
        .flat_map(|(row, &(shape, _))| {
            DETAILS.iter().enumerate().map(move |(column, &detail)| {
                (
                    Car {
                        at: at(column, row),
                        along: Vec2::X,
                        // цвет по строке, а не случайный: у одного кузова на
                        // трёх ступенях он обязан быть один, иначе строку не
                        // прочитать как одну машину на трёх зумах
                        color: body::color_from_share(ROW_COLOR[row]),
                        shape,
                    },
                    detail,
                )
            })
        })
        .collect();
    for (car, detail) in &cars {
        body::push_shadow(&mut builder, car, stretch * car.shape.height(), *detail);
    }
    for (car, detail) in &cars {
        body::push_body(&mut builder, car, *detail);
    }
    builder
}
