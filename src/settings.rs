//! Все размеры и скорости — метры и м/с. Пиксели существуют только в
//! константах рендера (`PIXELS_PER_METER`) и настройках зума камеры.

use bevy::math::DVec2;
use bevy::prelude::*;

/// Пиксельная плотность ассетов: 16 px = 1 м.
pub const PIXELS_PER_METER: f32 = 16.0;

/// Карта: реальные данные OpenStreetMap вокруг гео-центра выбранного города
/// (`City`). Размер общий для всех городов — от него зависит `GRID_SIZE`.
/// Начало координат — юго-западный угол bbox.
pub const MAP_SIZE: Vec2 = Vec2::new(5600.0, 3700.0);

/// Гео-центр Тулы (от Мясново на западе до Пролетарского моста на востоке,
/// Кремль — в правой части кадра). Проекция — локальная равнопромежуточная:
/// метры от юго-западного угла bbox. `(широта, долгота)`.
pub const TULA_GEO_CENTER: DVec2 = DVec2::new(54.18969, 37.59148);
/// Гео-центр Нью-Йорка: Ист-Ривер у Бруклинского моста, в кадре — Даунтаун
/// Манхэттена и северо-западный Бруклин.
pub const NY_GEO_CENTER: DVec2 = DVec2::new(40.70979, -73.97284);
/// Париж: Иль-де-ла-Сите, Сена делит кадр надвое.
pub const PARIS_GEO_CENTER: DVec2 = DVec2::new(48.85565, 2.34612);
/// Берлин: Митте, Музейный остров.
pub const BERLIN_GEO_CENTER: DVec2 = DVec2::new(52.51900, 13.40133);
/// Лондон: Ковент-Гарден, Темза в южной части кадра.
pub const LONDON_GEO_CENTER: DVec2 = DVec2::new(51.51190, -0.12240);
/// Токио: Ёцуя между Синдзюку и Императорским дворцом — сплошная застройка,
/// Токийский залив за восточным краем bbox.
pub const TOKYO_GEO_CENTER: DVec2 = DVec2::new(35.68950, 139.72900);
/// Метров в градусе широты (и долготы на экваторе).
pub const METERS_PER_DEG_LAT: f64 = 111_320.0;

/// Ячейка навигации, м.
pub const NAVTILE_SIZE: f32 = 2.0;

/// Размер навигационной сетки в тайлах: `MAP_SIZE / NAVTILE_SIZE`.
pub const GRID_SIZE: IVec2 = IVec2::new(2800, 1850);

/// Потолок ширины прорезаемой арки, м. Проезд сквозь дом размечен обычной
/// дорогой (чаще `service`, 5 м), но сама арка уже проезжей части — без
/// потолка коридор съедал бы кусок фасада по обе стороны от проёма.
pub const PASSAGE_MAX_WIDTH: f32 = 4.0;

/// Центр портала — хинт; при загрузке снапится к ближайшему проходимому
/// тайлу. Тула: гео-точка (54.1908, 37.5836) — перекрёсток к северу от
/// Центрального парка.
pub const TULA_PORTAL_POS: Vec2 = Vec2::new(2284.0, 1969.0);
/// Нью-Йорк: Чайнатаун / Ист-Сайд. В самом центре bbox — Ист-Ривер, поэтому
/// хинт сдвинут на сушу, а не взят серединой карты.
pub const NY_PORTAL_POS: Vec2 = Vec2::new(1352.0, 2263.0);
/// Остальные города центрированы по суше — хинту хватает середины карты.
pub const MAP_CENTER_PORTAL_POS: Vec2 = Vec2::new(MAP_SIZE.x / 2.0, MAP_SIZE.y / 2.0);
pub const PORTAL_DIAMETER: f32 = 36.0;

// --- Люди ---
/// 20000 на карте центра Тулы (изначальная цель MVP была 5000 [Q5]).
pub const HUMAN_COUNT: usize = 20000;
/// Визуальный габарит ×2 против реального (0.5 м) — иначе слишком мелко.
pub const HUMAN_SIZE: f32 = 1.0;
/// Скорости ×2 против реализма — так живее.
pub const HUMAN_WALK_SPEED: f32 = 2.8;
pub const HUMAN_FLEE_SPEED: f32 = 8.0;
/// Радиус, в котором человек замечает демона и паникует.
pub const HUMAN_PANIC_RADIUS: f32 = 60.0;
/// Блуждание: случайная точка в 20–40 м, затем пауза 2–10 сек.
pub const HUMAN_WANDER_RANGE: (f32, f32) = (20.0, 40.0);
pub const HUMAN_WANDER_PAUSE: (f32, f32) = (2.0, 10.0);

// --- Демоны ---
/// Визуальный габарит ×2 против фигуры-заглушки 1 × 1 м.
pub const DEMON_SIZE: f32 = 2.0;
/// Единая скорость демона: всегда +35% к скорости убегающего человека,
/// и в блуждании, и в погоне.
pub const DEMON_SPEED: f32 = HUMAN_FLEE_SPEED * 1.35;
/// Радиус агро демона.
pub const DEMON_AGGRO_RADIUS: f32 = 45.0;
/// Дистанция «броска»: внутри неё демон идёт напрямую к текущей позиции
/// жертвы, минуя тайловый путь. Обязана быть заметно больше диагонали тайла
/// (2.83 м) — путь ведёт к центру тайла, а жертва внутри него продолжает
/// двигаться, и остаток до `KILL_DISTANCE` иначе не покрывается никогда.
pub const DEMON_LUNGE_RANGE: f32 = 6.0;
/// Пауза «пожирания» после убийства, сек.
pub const DEMON_DEVOUR_PAUSE: (f32, f32) = (1.5, 2.0);
/// Дистанция убийства.
pub const KILL_DISTANCE: f32 = 1.0;
/// Спавн: стартовый залп, затем интервал, кап.
pub const DEMON_INITIAL_BURST: usize = 8;
pub const DEMON_SPAWN_INTERVAL: f32 = 5.0;
pub const DEMON_CAP: usize = 100;

/// Гистерезис выхода из погони/паники: множитель радиуса.
pub const RADIUS_HYSTERESIS: f32 = 1.5;

// --- Скорость симуляции ---
/// Сколько виртуального времени отдаётся `FixedUpdate` за один кадр
/// (`Time<Virtual>::max_delta`, дефолт Bevy). Из него выведен потолок скорости:
/// `S ≤ fps × MAX_FRAME_DELTA`, при 60 fps — 15x.
pub const MAX_FRAME_DELTA: f32 = 0.25;
/// Доля разрыва до целевой скорости, закрываемая за кадр (экспоненциальное
/// сглаживание регулятора) при разгоне.
pub const SPEED_SETTLE_RATE: f32 = 0.05;
/// То же при замедлении: сбрасывать нагрузку надо быстрее, чем набирать, —
/// пока регулятор ползёт вниз, кадры уже упираются в `MAX_FRAME_DELTA` и
/// симуляция молча теряет время.
pub const SPEED_DROP_RATE: f32 = 0.25;
/// Нижняя граница автозамедления: ниже симуляция уже не идёт, а стоит.
pub const MIN_SIM_SPEED: f32 = 0.1;
/// Окно усреднения фактической скорости (виртуальное время / реальное).
/// Копится по реальному времени, а не по кадрам: один кадр в 4 с должен
/// весить как 4 с, иначе просадка теряется в усреднении.
pub const ACTUAL_SPEED_WINDOW: f32 = 0.5;

// --- Z-слои (см. y-сортировку юнитов) ---
pub const Z_GROUND: f32 = 0.0;
pub const Z_PARK: f32 = 0.5;
/// Лес, луга и песок лежат внутри парковых полигонов — поверх заливки парка.
pub const Z_WOOD: f32 = 0.55;
pub const Z_GRASS: f32 = 0.6;
pub const Z_SAND: f32 = 0.7;
pub const Z_POND: f32 = 1.0;
pub const Z_ALLEY: f32 = 1.5;
pub const Z_ROAD: f32 = 2.0;
pub const Z_CORPSE: f32 = 3.0;
pub const Z_PORTAL: f32 = 4.0;
pub const Z_BUILDING: f32 = 5.0;
/// Юниты: z = `Z_UNIT_BASE - y * Y_SORT_FACTOR` (кто ниже — тот ближе).
/// Диапазон обязан оставаться над зданиями (5) при любом y ≤ MAP_SIZE.y,
/// иначе северные юниты ныряют под дороги и мосты.
pub const Z_UNIT_BASE: f32 = 10.0;
pub const Y_SORT_FACTOR: f32 = 0.002;
pub const Z_TREE: f32 = 20.0;
/// Тени крон — под самими кронами, но выше юнитов (юнит в тени затемняется).
pub const Z_TREE_SHADOW: f32 = 19.0;

// --- Деревья (кроны в стиле Watabou, см. TREE_ALGO.md) ---
/// Сколько уникальных геометрий крон переиспользуется на все деревья.
pub const TREE_VARIANTS: usize = 12;
/// Форма `Mixed`: одно хвойное дерево на столько деревьев (10 % хвои).
pub const TREE_MIXED_CONIFER_EVERY: usize = 10;
/// Толщина чернильного контура кроны, доля радиуса (у watabou ~1/8 радиуса).
pub const TREE_OUTLINE_STROKE: f32 = 0.12;
/// Толщина внутренних пунктирных дуг, доля радиуса — вдвое тоньше контура.
pub const TREE_DETAIL_STROKE: f32 = 0.06;

/// Z юнита по его мировой y-координате.
pub fn unit_z(y: f32) -> f32 {
    Z_UNIT_BASE - y * Y_SORT_FACTOR
}
