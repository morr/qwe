// --- Скорость симуляции ---
/// Сколько виртуального времени отдаётся `FixedUpdate` за один кадр
/// (`Time<Virtual>::max_delta`). Из него выведен потолок скорости:
/// `S ≤ fps × MAX_FRAME_DELTA`, при 60 fps — 30x.
///
/// Было 0.25 (дефолт Bevy) — при vsync-овых 60 fps потолок выходил ровно 15x,
/// без запаса: любой дребезг fps вниз ронял `effective`, и запрошенные 15x
/// держались «на грани». 0.5 даёт двукратный запас — даже просадка до 35 fps
/// не выбивает 15x, а на ровных 60 fps достижимы ~30x (дальше упирается уже
/// стоимость тиков, см. `sim/*_ms`).
pub const MAX_FRAME_DELTA: f32 = 0.5;
/// Доля разрыва до целевой скорости, закрываемая за кадр (экспоненциальное
/// сглаживание регулятора) при разгоне.
pub const SPEED_SETTLE_RATE: f32 = 0.05;
/// То же при замедлении: сбрасывать нагрузку надо быстрее, чем набирать, —
/// пока регулятор ползёт вниз, кадры уже упираются в `MAX_FRAME_DELTA` и
/// симуляция молча теряет время.
pub const SPEED_DROP_RATE: f32 = 0.25;
/// Нижняя граница автозамедления: ниже симуляция уже не идёт, а стоит.
pub const MIN_SIM_SPEED: f32 = 0.1;
/// Лесенка скоростей — единый ряд ступеней для кнопки Speed и хоткеев
/// `=`/`-`. Верхняя ступень равна аппаратному потолку `fps × MAX_FRAME_DELTA`
/// на ровных 60 fps: просить выше нечего — регулятор всё равно срежет, а
/// панель показывала бы недостижимое число.
pub const SPEED_LADDER: [f32; 6] = [1.0, 2.0, 5.0, 10.0, 20.0, 30.0];
/// Жёсткий потолок запрошенной скорости — верх лесенки; выше `requested` не
/// поднять и записью по BRP (срез в `throttle_speed_to_fps`).
pub const MAX_SIM_SPEED: f32 = SPEED_LADDER[SPEED_LADDER.len() - 1];
/// Зум (мировых метров на логический пиксель), выше которого мирные гуляющие
/// считаются «не на экране» и путь от диспетчера не получают: пешка на таком
/// отдалении — точка, её простой не виден, а «в кадре» иначе означала бы
/// полкарты — все ~17k мирных разом топили бы пул pathfinding-тасков.
/// Демонов и убегающих отсечка не касается (они URGENT при любом зуме).
pub const WANDER_DISPATCH_MAX_ZOOM: f32 = 0.75;
/// Окно усреднения фактической скорости (виртуальное время / реальное).
/// Копится по реальному времени, а не по кадрам: один кадр в 4 с должен
/// весить как 4 с, иначе просадка теряется в усреднении.
pub const ACTUAL_SPEED_WINDOW: f32 = 0.5;

