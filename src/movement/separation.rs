/// Подвижность демона относительно человека: в паре человек забирает 4/5
/// коррекции — толпа обтекает демона, а не демон толпу.
const DEMON_MOBILITY: f32 = 0.25;

/// «Конец цепочки» в связных списках мелкой сетки.
const NONE: u32 = u32::MAX;

/// Тумблер расталкивания — панель World. Выбор пользователя, переживает
/// рестарт и смену города (тот же контракт, что у `DemonStyle`). Выключение
/// ничего не откатывает: уже разведённые позиции просто остаются как есть.
#[derive(Resource, Reflect, SettingsGroup, Clone, Copy, PartialEq, Debug)]
#[reflect(Resource, SettingsGroup, Default)]
#[settings_group(group = "separation")]
pub struct SeparationStyle {
    pub enabled: bool,
    /// Сила обхода встречного в долях продольной коррекции (см. [`sidestep`]).
    /// Ручка, а не константа, потому что у неё узкое окно между двумя разными
    /// поломками — ниже слипание, выше карусель — и подбирается она только
    /// замером в толпе (`examples/demos/crowd_demo.rs`).
    pub sidestep: f32,
    /// Какая доля продольного толчка доживает до применения (см.
    /// [`damp_along_heading`]). 1 — ничего не давим, и догоняющий в очереди
    /// заметно пятится; 0 — толчок строго поперечный, и толпа, идущая в одну
    /// точку, схлопывается в пятно и вращается вместо того, чтобы раздаться.
    pub backstep: f32,
    /// Какая доля шага ходьбы остаётся у придержанной пешки (см.
    /// [`SeparationHolds`]): 1 — придержки нет и ходьба давит в упор до
    /// равновесия, 0 — полный стоп и рваное движение толпы. Дефолт и разбор
    /// компромисса — [`SEPARATION_HOLD`].
    pub hold: f32,
}

/// Пешки, упёршиеся курсом в перекрытого соседа, который СТОИТ или ИДЁТ
/// НАВСТРЕЧУ: до следующего прогона их шаг ходьбы ослаблен долей
/// [`SeparationStyle::hold`] (`systems::move_moving_entities`). Ровно эти два
/// случая, а не любое касание: попутный и поперечный сосед проходятся полным
/// шагом — их разводит само расталкивание, а придержка за касание заставляла
/// ползти весь поток (группа попутчиков душила сама себя).
///
/// Это разрыв равновесия «ходьба против расталкивания» — источника сразу двух
/// картинок: кучи, вставшей колом и дрожащей на месте (все давят внутрь, и
/// толчки в точности гасят шаги), и пары, наматывающей круги друг вокруг
/// друга (обоих везёт вперёд собственная ходьба, а боковой обход только
/// вращает связку). Пешка, упёршаяся в тело, перестаёт с ним бороться — и
/// расталкиванию хватает одного-двух прогонов развести затор.
///
/// Придерживаются только люди: демону в погоне смыкаться обязательно, а
/// «толпа обтекает демона» уже выражено подвижностью.
///
/// Наполняется только прогоном расталкивания, то есть под его гейтами —
/// вьюпорт, зум, полигональная навигация ([`separation_runs`]); выключение и
/// отзум чистят набор. В детерминированном прогоне и на сеточной навигации
/// набор пуст с входа в мир, и движение от него не зависит.
#[derive(Resource, Default)]
pub struct SeparationHolds(pub bevy::ecs::entity::EntityHashSet);

/// Вход в мир начинается без придержанных: набор пережил бы смену города
/// (сущности в нём уже мертвы) и рестарт с переключением режима.
pub fn reset_separation_holds(mut holds: ResMut<SeparationHolds>) {
    holds.0.clear();
}

/// Работает ли расталкивание в текущем режиме мира — вопрос не тумблера
/// [`SeparationStyle`], а того, чем считается путь и повторяем ли прогон.
///
/// Два «нет», и оба не про вкус пользователя:
/// - **детерминированный режим** — механизм завязан на камеру, зум и
///   `FrameCount`, то есть на всё, от чего повтор прогона обязан не зависеть;
/// - **сеточная навигация** (панель Navmesh, `PolymeshDebug::enabled`
///   выключен) — путь по сетке идёт центрами навтайлов, и `move_moving_entities`
///   ставит пешку на waypoint каждый шаг: разведённая пара возвращается на те
///   же два центра к следующему тику, а всё, что успело набежать, — это
///   дрожь и придержки ([`SeparationHolds`]) на ровном месте. Личное
///   пространство имеет смысл там, где waypoint'ы метрические, то есть на
///   полигональном меше.
///
/// Тумблер, а не готовность меша: пока меш строится (0.3–20 с), запросы
/// обслуживает сетка, но мигать расталкиванием на этом переходе хуже, чем
/// доработать полсекунды по-старому.
///
/// `Option` у обоих ресурсов — та же причина, что у
/// [`deterministic`](crate::determinism::deterministic): `MovementPlugin`
/// используется в тестах и демо-сценах без соседних плагинов.
pub fn separation_runs(
    determinism: Option<Res<crate::determinism::Determinism>>,
    polymesh: Option<Res<crate::navigation::PolymeshDebug>>,
) -> bool {
    separation_allowed_by_mode(
        determinism.is_some_and(|mode| mode.0),
        polymesh.is_some_and(|polymesh| polymesh.enabled),
    )
}

/// То же правило в чистом виде — для панели World: строка тумблера гаснет
/// ровно тогда, когда система не работает, и это должно быть одно правило, а
/// не две разъезжающиеся копии (`ui/stats.rs`).
pub fn separation_allowed_by_mode(deterministic: bool, polymesh_nav: bool) -> bool {
    !deterministic && polymesh_nav
}

/// Во столько раз радиус демона больше человеческого — как и спрайты
/// ([`DEMON_SIZE`] против [`HUMAN_SIZE`]).
pub const DEMON_RADIUS_RATIO: f32 = DEMON_BODY_RADIUS / HUMAN_BODY_RADIUS;

/// Радиус тела демона по радиусу тела человека — не отдельная ручка: он всегда
/// вдвое больше, как и спрайт.
pub fn demon_radius(human_radius: f32) -> f32 {
    human_radius * DEMON_RADIUS_RATIO
}

/// Сторона одноразовой мелкой сетки соседей. Считается от радиуса, а не
/// берётся константой: ячейка ОБЯЗАНА быть не меньше максимальной суммы
/// радиусов (демон+демон), иначе перекрывшаяся пара не попадёт в общие
/// 3 × 3 ячейки и её не найдут. С ручкой радиуса константа рано или поздно
/// оказалась бы мала.
pub fn separation_cell(human_radius: f32) -> f32 {
    (demon_radius(human_radius) * 2.0).max(SEPARATION_CELL)
}

impl Default for SeparationStyle {
    fn default() -> Self {
        Self {
            enabled: true,
            sidestep: SEPARATION_SIDESTEP,
            backstep: SEPARATION_BACKSTEP,
            hold: SEPARATION_HOLD,
        }
    }
}

impl Eq for SeparationStyle {}

/// Экспериментальные ручки расталкивания — то, что в игре зафиксировано
/// константами, а в замерах перебирается.
///
/// **Дефолт воспроизводит нынешнее поведение игры точь-в-точь**: `rate` и
/// `max_step` равны своим константам, а всё остальное — нули, то есть
/// выключено. Пока ресурс не тронут, `resolve_pushes` идёт ровно теми же
/// ветками, что и до появления этого типа.
///
/// Намеренно НЕ [`SettingsGroup`], в отличие от [`SeparationStyle`]: это стенд
/// для замеров (`examples/demos/crowd_demo.rs`), а не выбор пользователя, и
/// уезжать в `settings.toml` ему незачем.
#[derive(Resource, Reflect, Clone, Copy, PartialEq, Debug)]
#[reflect(Resource, Default)]
pub struct SeparationLab {
    /// Какая доля перекрытия снимается за виртуальную секунду
    /// ([`SEPARATION_RATE`]).
    pub rate: f32,
    /// Потолок сдвига за один прогон ([`SEPARATION_MAX_STEP`]).
    ///
    /// Обратите внимание, ЧТО он ограничивает на самом деле: прогон идёт раз в
    /// кадр, так что 0.3 м на прогон при 60 fps — это 18 м/с, вшестеро быстрее
    /// бега. Потолком он не работает почти никогда; настоящий предел задаёт
    /// [`SeparationLab::max_speed`].
    pub max_step: f32,
    /// Потолок СКОРОСТИ расталкивания, м/с — в отличие от `max_step`, не
    /// зависит от частоты кадров и сравним со скоростью ходьбы (2.8 м/с).
    /// 0 — выключен, ограничивает только `max_step`, как сейчас.
    ///
    /// Ради чего. Толчок пары равен `перекрытие × rate`, а `rate` — 8/с: при
    /// перекрытии в 0.9 м это 7.2 м/с, то есть в два с половиной раза быстрее
    /// ходьбы. В плотном встречном потоке расталкивание не поправляет ходьбу,
    /// а перебивает её: пешку швыряет назад быстрее, чем она идёт вперёд, она
    /// доходит обратно, и так по кругу. Отсюда 24 км намотанного пути на 2.4 км
    /// продвижения в базовом прогоне стенда.
    pub max_speed: f32,
    /// Горизонт упреждения, с: насколько вперёд смотреть на СБЛИЖАЮЩЕГОСЯ, но
    /// ещё не перекрывшегося соседа. 0 — упреждения нет, механизм чисто
    /// реактивный, как сейчас. См. [`anticipate`].
    pub horizon: f32,
    /// Сила упреждения, м/с бокового сноса.
    pub anticipation: f32,
    /// Во сколько радиусов считается «мимо»: предсказанный промах меньше
    /// `anticipate_margin × (r_a + r_b)` — повод уклоняться.
    pub anticipate_margin: f32,
    /// Примесь правой нормали в направление уклонения (0…1). Лобовая встреча
    /// вырождается — предсказанный контакт лежит на курсе, и «уклоняться»
    /// некуда; примесь задаёт сторону, как у живых пешеходов.
    pub lane_bias: f32,
    /// На сколько ужимается радиус тела в давке (0 — не ужимается, 0.4 — на
    /// 40% при полной загрузке). Толпа в узком месте сжимается, а не встаёт.
    pub compress: f32,
    /// Сколько одновременных перекрытий считается полной загрузкой для
    /// [`SeparationLab::compress`].
    pub compress_at: f32,
    /// Доля обхода встречного, которая достаётся паре В КУЧЕ (у пары, которая
    /// одна, обход работает всегда). 0 — нынешний гейт `alone`.
    pub crowd_sidestep: f32,
    /// Сила РУЛЕНИЯ, доли: насколько курс ходьбы отклоняется вбок от того, кто
    /// стоит на дороге. 0 — руления нет, и `move_moving_entities` идёт ровно
    /// тем кодом, что и раньше. См. [`SeparationSteer`].
    pub steer: f32,
    /// Подвижность СТОЯЩЕЙ пешки в паре — доля коррекции, которая ей достаётся
    /// (1 — как сейчас, наравне с идущей; 0 — стоящую не сдвинуть вовсе).
    ///
    /// Зачем. Пешка, дошедшая до своего слота, дошла ОКОНЧАТЕЛЬНО: её слот
    /// заявлен, ничей больше путь в нём не кончается, и всё, что с ней может
    /// случиться дальше, — это толчки от проходящих мимо. Каждый такой толчок
    /// уводит её со слота, а вернуться ей нечем: маршрут кончился, новую цель
    /// в этом сценарии никто не выдаёт. Толпа, которая должна была осесть,
    /// вместо этого весь остаток окна расползается — второй критерий стенда
    /// («никто не двигается») не выполняется никогда, а третий (пройденный
    /// путь) растёт из ничего.
    ///
    /// Стоящий, которого не сдвинуть, — это ещё и то, как ведут себя живые
    /// люди: протискивается тот, кто идёт, а не тот, кто стоит. Ровно этим
    /// уже выражена «толпа обтекает демона» ([`DEMON_MOBILITY`]).
    ///
    /// Ноль брать опасно: в куче, где НИКТО не идёт (сценарий 1), стоят все, и
    /// при нулевой подвижности она не разойдётся вовсе. Отсюда ручка, а не
    /// правило.
    pub idle_mobility: f32,
    /// Во сколько раз дистанция покоя, на которой ПРИДЕРЖАННАЯ пешка
    /// засчитывается дошедшей (`systems::move_moving_entities`), меньше
    /// настоящей. 1 — как сейчас.
    ///
    /// Зачем ручка. Допуск существует ради затора: упёршуюся в чужое тело
    /// пешку ближе к цели всё равно не пустят, и без засчитанного прихода она
    /// толкалась бы вечно. Но допуск — це́лая дистанция покоя, а шаг решётки
    /// слотов — ровно она же (1.8 м покоя при шаге 2 м): пешка, вставшая на
    /// краю допуска, стоит почти В СОСЕДНЕМ слоте. Соседи после этого
    /// перекрыты навсегда, толкают друг друга без надежды разойтись (обоим
    /// «дойти» уже некуда) — и осевшая толпа не замирает, а тихо ползёт весь
    /// остаток прогона.
    pub arrive_slack: f32,
    /// Какая доля составляющей шага, ведущей В перегородившее тело, снимается
    /// (0 — не снимается ничего, как сейчас; 1 — в тело не идём вовсе).
    /// См. [`SeparationBlock`].
    pub slide: f32,
    /// Ближе этого расстояния до waypoint'а руление выключается, м. Иначе
    /// пешка, которую уводит вбок у самой точки, начинает наматывать вокруг
    /// неё круги вместо того, чтобы её пройти: `move_moving_entities` снимает
    /// waypoint только когда бюджет шага накрывает остаток, а отклонённый курс
    /// этот остаток не сокращает.
    pub steer_release: f32,
}

/// Куда пешке ОТВЕРНУТЬ на ходу — единичный вектор поперёк её курса, домноженный
/// на [`SeparationLab::steer`]. Читает `move_moving_entities` и подмешивает в
/// направление шага; наполняет прогон расталкивания, как и [`SeparationHolds`],
/// и по тем же гейтам.
///
/// Зачем это отдельно от толчка. Толчок двигает ПОЗИЦИЮ, а ходьба тут же везёт
/// пешку обратно к цели — две силы работают друг против друга, и весь результат
/// уходит в намотанный путь (в замере стенда: 24 км пути на 2.4 км
/// продвижения). Руление меняет НАПРАВЛЕНИЕ той же самой ходьбы: скорость
/// сохраняется целиком, пешка обходит по дуге и никуда не «возвращается» —
/// именно так расходятся живые пешеходы, и именно этого механизма в
/// расталкивании не было.
///
/// Симметричный встречный поток без этого не расходится в принципе: у пары,
/// идущей строго друг на друга, вектор между центрами коллинеарен обоим курсам,
/// поперечной составляющей у коррекции нет ни у одной пары, и толпа остаётся
/// строго одномерной (стенд меряет разброс ровно 0.00 м на любых значениях
/// `rate`, `hold` и `sidestep`).
#[derive(Resource, Default)]
pub struct SeparationSteer(pub bevy::ecs::entity::EntityHashMap<Vec2>);

/// Вход в мир начинается без рулящих — по той же причине, что и без
/// придержанных (см. [`reset_separation_holds`]).
pub fn reset_separation_steer(mut steer: ResMut<SeparationSteer>) {
    steer.0.clear();
}

/// Куда пешке НЕЛЬЗЯ идти — единичный вектор на того, кто перегородил ей курс
/// (равнодействующая, если перегородили несколько). Читает
/// `move_moving_entities` и вычитает из шага составляющую ВДОЛЬ него
/// ([`SeparationLab::slide`]); наполняет прогон расталкивания там же, где
/// [`SeparationHolds`], и ровно по тому же условию.
///
/// Зачем это отдельно от придержки. Придержка режет ВЕСЬ шаг: и то движение,
/// которым пешка лезет в чужое тело, и то, которым она из-под него
/// выбирается. Отсюда её цена — поток, ползущий на доле скорости, — и отсюда
/// же соблазн выключить её совсем (`hold = 1`), после чего пешки на полном
/// ходу входят друг в друга: за кадр встречная пара сближается на 0.09 м, а
/// расталкивание успевает снять `rate · dt` ≈ 7% перекрытия, то есть заведомо
/// меньше. На стенде это видно как сотни пар, сошедшихся ближе половины
/// спрайта.
///
/// Скольжение снимает ровно ту составляющую, которая ведёт В тело, и не
/// трогает поперечную: лобовая пешка останавливается сама собой (весь её курс
/// вдоль запрета), а идущая по касательной проходит на полной скорости. Это то
/// же разделение, что у руления, но на шаге, а не на курсе: руление решает,
/// КУДА свернуть, скольжение — не пускает туда, где тело.
#[derive(Resource, Default)]
pub struct SeparationBlock(pub bevy::ecs::entity::EntityHashMap<Vec2>);

/// Вход в мир начинается без перегороженных, см. [`reset_separation_holds`].
pub fn reset_separation_block(mut block: ResMut<SeparationBlock>) {
    block.0.clear();
}

/// Всё, что прогон расталкивания ВЫДАЁТ шагу движения, одним параметром.
///
/// Группа, а не три отдельных `ResMut`: у `separate_pawns` и без них четырнадцать
/// параметров, а потолок кортежа системы — шестнадцать. Заодно видно, что это
/// один выход механизма, а не три независимых ресурса: наполняются они вместе,
/// чистятся вместе и врозь не имеют смысла.
#[derive(bevy::ecs::system::SystemParam)]
pub(super) struct SeparationOutput<'w> {
    holds: ResMut<'w, SeparationHolds>,
    steer: ResMut<'w, SeparationSteer>,
    block: ResMut<'w, SeparationBlock>,
}

impl SeparationOutput<'_> {
    fn clear(&mut self) {
        self.holds.0.clear();
        self.steer.0.clear();
        self.block.0.clear();
    }
}

